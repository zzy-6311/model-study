# C08：评估指标——为什么准确率会骗人
#
# 【这一课解决什么问题】
#   模型验证准确率 90%。这个数能说明什么？
#
#   答案是：几乎什么都不能说明。
#   这一课讲清楚为什么，以及应该看什么。
#
# 代码只有一处：从一张混淆矩阵算出各种指标。


# ============================================================
# 一、准确率为什么会骗人
# ============================================================
# 准确率 = 预测对的样本数 / 总样本数
#
# 问题出在"总样本数"里各类的比例上。
#
# 假设识别 10 个数字，但数据里"0"占了 90%，其他 9 个各占 1%。
# 一个永远输出"0"的模型，准确率是 90%。
# 它什么都没学会，却看起来很棒。
#
# 再看一个平衡数据集的例子：
#   3 类，每类 100 个样本，共 300 个。
#   一个永远猜"类 0"的模型：准确率 100/300 = 33.3%，
#   而它对类 0 的召回率是 100%。
#
# 所以第一件事：任何准确率都必须和一个"傻子模型"对比。
#
#   基线1：永远猜最多的那一类           -> 准确率 = 该类的占比
#   基线2：随机猜（10 类就是 10%）       -> 准确率 = 1/10
#
# 你的模型如果只有 35%，而基线是 33%，那基本等于没学。


# ============================================================
# 二、混淆矩阵：错误的全貌
# ============================================================
# 准确率只告诉你"错了多少"，不告诉你"错成什么"。
# 混淆矩阵告诉你后者。
#
#   行 = 真实类别
#   列 = 预测类别
#
#         预测0  预测1  预测2
#   真实0   95     4      1        <- 100 个 0，95 个认对
#   真实1    5    80     15        <- 100 个 1，80 个认对
#   真实2    2    10     88        <- 100 个 2，88 个认对
#
# 对角线（95, 80, 88）是认对的，其它格子是"谁被认成了谁"。
# 一眼能看出：类 1 最弱，而且有 15 个被认成了类 2。


# ============================================================
# 三、召回率和精确率
# ============================================================
# 召回率（recall）   该类样本中，被找出来的比例
#                    = 认对的 / 该类总数
#                    回答："这一类有多少漏掉了？"
#
# 精确率（precision）被判为该类的样本中，真正是该类的比例
#                    = 认对的 / 被判为该类的总数
#                    回答："你说它是这一类，有几分可信？"
#
# 拿类 1 算一下：
#   召回 = 80 / 100 = 0.80          100 个真实类 1，找到 80 个
#   精确 = 80 / (4+80+10) = 0.851   被判成类 1 的 94 个里，80 个是真的
#
# 为什么两个都要看？
#   只追求召回：把所有样本都判成类 1 -> 召回 100%，精确率 100/300 = 33%
#   只追求精确：只挑最有把握的那 1 个判成类 1，判对了 -> 精确率 100%
#
# 两个指标天生会打架，F1 是它们的调和平均，用来折中。


import torch

# ============================================================
# 四、从混淆矩阵算出所有指标
# ============================================================
print("=" * 60)
print("一、一张混淆矩阵的各项指标")

# 3 类，每类 100 个样本；行=真实，列=预测
cm = torch.tensor([
    [95,  4,  1],
    [ 5, 80, 15],
    [ 2, 10, 88],
], dtype=torch.float)

total = cm.sum().item()
correct = cm.diag().sum().item()
print("总样本 =", int(total), "  认对 =", int(correct))
print("整体准确率 =", round(correct / total, 4))

print("每类表现：")
for c in range(3):
    tp = cm[c, c].item()
    fn = cm[c].sum().item() - tp        # 真实是 c 但认错了
    fp = cm[:, c].sum().item() - tp     # 被误判成 c
    recall = tp / (tp + fn)
    precision = tp / (tp + fp)
    print(f"   类{c}:  召回={recall:.4f}  精确={precision:.4f}  漏掉={int(fn)}")

macro_recall = sum(cm[i, i].item() / cm[i].sum().item() for i in range(3)) / 3
print("宏平均召回 =", round(macro_recall, 4))

# 输出：
#   整体准确率 = 0.8767
#   类0: 召回=0.9500  精确=0.9314  漏掉=5
#   类1: 召回=0.8000  精确=0.8511  漏掉=20
#   类2: 召回=0.8800  精确=0.8462  漏掉=12
#
# 读这张表能看出三件事：
#   ① 整体 87.67%，但类 1 只有 80% —— 被平均值掩盖了
#   ② 类 1 漏掉 20 个，其中 15 个被认成了类 2（这是最严重的系统性错误）
#   ③ 类 0 最准（95%），说明它最容易区分


# ============================================================
# 五、宏平均和微平均
# ============================================================
# 多分类时把"每类的指标"合成一个数，有两种方式：
#
#   宏平均（macro）  先算每类的指标，再对类别等权平均
#                    每类不管有多少样本，说话一样重
#                    适合"每类都要做好"的场景
#
#   微平均（micro）  把所有样本混在一起算
#                    样本多的类主导结果
#                    多分类时微平均的准确率就等于整体准确率
#
# 例子：如果一个模型在罕见的类上很差，但在大类别上很好，
#   宏平均会毫不留情地低，微平均则看不出来。
#
# 报告指标时一定要说清楚是哪种，否则两个数差很远。


# ============================================================
# 六、怎么看错误样例
# ============================================================
# 混淆矩阵告诉你"哪两类容易混"，但看不出"为什么混"。
#
# 下一步是翻具体样本：
#   把"真实类 1 但被判成类 2"的那些图片打印出来看
#   常见原因：
#     图片本身模糊、笔画太细
#     标注错了（真值标签写错）
#     训练集里这类样本太少
#
# 这一步不能跳。能看到具体样本，才能判断是模型问题还是数据问题。


# ============================================================
# 七、这一课要记住的三句
# ============================================================
# 1. 准确率必须配基线看。
#    永远猜最多那一类的准确率，就是这个数据集的"及格线"。
#
# 2. 混淆矩阵告诉你"错成什么"，这比"错了多少"信息量大得多。
#
# 3. 召回率和精确率天生打架，还要说清宏平均还是微平均。
#    只报一个数，等于把问题藏起来了。

