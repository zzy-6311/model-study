# C02：训练集 / 验证集 / 测试集
#
# 这一课几乎全是讲解。只有一个地方需要看数字：数据泄漏到底有多容易发生。


# ============================================================
# 一、这一课解决什么问题
# ============================================================
# 你训练出一个模型，验证一下，报"准确率 99%"。
#
# 这个 99% 凭什么可信？
#   如果验证用的那批数据，刚才训练时模型已经见过了呢？
#   那它就是背答案背出来的，换新数据立刻露馅。
#
# 所以数据必须先分成互不重叠的几份，各管一件事。


# ============================================================
# 二、三个集合，各管一件事
# ============================================================
# 训练集（train）   用来更新参数。模型每一步都在"看答案"学
# 验证集（val）     用来调设置：学习率、层数、训练多少轮、什么时候停
#                   可以反复看、反复试
# 测试集（test）    最终评估。正常情况下只准看一次
#
# 类比：
#   训练集 = 练习册    做多少遍都行，边做边对答案
#   验证集 = 模拟考    可以反复考，用来调整复习策略
#   测试集 = 高考      只考一次，考完就定
#
# 最关键的一条：
#   如果你拿模拟考的题当练习册刷，模拟考分数就不代表真实水平了。
#   对应到模型：反复用测试集调参，报出来的准确率是虚高的。


# ============================================================
# 三、数据泄漏：一个"看起来完全正常"的操作
# ============================================================
# 假设你有 50 张原图，每张做了 2 个增强版本（旋转、裁剪、加噪声），
# 一共 100 个样本。你按常规做法随机切成 80 训练 / 20 验证。
#
# 问题来了：同一张原图的两个版本，可能一个在训练集、一个在验证集。
# 模型在验证集上遇到的那张图，训练时已经见过它的"兄弟"了。


import torch
from torch.utils.data import TensorDataset, random_split

print("=" * 60)
print("一、实测：随机切分漏了多少")

torch.manual_seed(0)

n_groups, copies = 50, 2
base = torch.randn(n_groups, 10)
items, group_ids = [], []
for g in range(n_groups):
    for c in range(copies):
        items.append(base[g] + 0.01 * torch.randn(10))   # 同一原图的轻微变体
        group_ids.append(g)

X = torch.stack(items)
y = torch.randint(0, 2, (n_groups,)).repeat_interleave(copies)
group_ids = torch.tensor(group_ids)
print("总样本 =", len(X), "  来自", n_groups, "张原图")

# 做法 A：按样本随机切（最常见的做法）
ds = TensorDataset(X, y)
tr, va = random_split(ds, [80, 20], generator=torch.Generator().manual_seed(42))
g_tr = set(group_ids[tr.indices].tolist())
g_va = set(group_ids[va.indices].tolist())
print("按样本切分 -> 被拆到两边的原图 =", len(g_tr & g_va), "张")

# 做法 B：按原图分组切（正确做法）
torch.manual_seed(1)
perm = torch.randperm(n_groups)
train_groups = set(perm[:40].tolist())
val_groups = set(perm[40:].tolist())
train_idx = [i for i, g in enumerate(group_ids.tolist()) if g in train_groups]
val_idx = [i for i, g in enumerate(group_ids.tolist()) if g in val_groups]
g_tr2 = set(group_ids[train_idx].tolist())
g_va2 = set(group_ids[val_idx].tolist())
print("按分组切分 -> 被拆到两边的原图 =", len(g_tr2 & g_va2), "张")

# 输出：
#   按样本切分 -> 被拆到两边的原图 = 14 张     <- 50 张里有 14 张泄漏
#   按分组切分 -> 被拆到两边的原图 = 0 张
#
# 14/50 = 28%。这不是极端情况，是"随机切"的默认结果。


# ============================================================
# 四、这种泄漏在真实项目里长什么样
# ============================================================
#   视频抽帧        相邻帧几乎一样，随机切就同时出现在两边
#   图像增强        同一张图的旋转/裁剪版本被分到两边
#   医疗影像        同一患者多次检查，随机切会让同一人跨两边
#   时间序列        随机打乱破坏了时间顺序，模型"看到未来"
#
# 这些都不是罕见情况，是默认会发生的情况。


# ============================================================
# 五、其他三种泄漏
# ============================================================
# ① 用测试集反复调参
#    试了 20 组设置，每组都在测试集上看一次，最后挑最好的
#    -> 测试集实际上参与了"选模型"，那个分数不再是"没见过的数据"上的表现
#
# ② 用全体数据算归一化参数（C03 会讲）
#    用所有图片算出 mean/std 再划分，验证集的信息已经漏进了预处理
#    正确做法：只用训练集算
#
# ③ 标签泄漏
#    某个特征其实是由标签直接推出来的
#    比如预测"是否购买"，数据里却有"购买金额"


# ============================================================
# 六、MNIST 的划分约定
# ============================================================
#   官方 train 60000 张  -> 切成 训练集 + 验证集（比如 50000 / 10000）
#   官方 test  10000 张  -> 测试集，只在最后用一次
#
# 不要从 test 里切验证集，也不要用 test 反复调参。


# ============================================================
# 七、三个习惯
# ============================================================
# 1. 固定随机种子，把划分结果的 indices 记录下来
#    否则每次跑的数据划分不一样，结果没法比较
# 2. 同源样本必须整体进同一个集合
#    同一视频的帧、同一张图的增强、同一个人的照片
# 3. 测试集在项目里"封存"，只在最后报告结果时用一次

