# C01：回归和分类是两种任务
#
# 这一课几乎没有代码。它回答一个问题：
#   模型要说出"这张图是几"，它到底输出什么？


# ============================================================
# 一、前面的阶段做的是"回归"
# ============================================================
# A、B 阶段你做的都是回归：
#   输入 x     ->  模型  ->  输出一个连续的数
#   比如拟合 y = x^2，输出 3.7241、-0.5 都正常
#
# 特点：
#   数值有大小和距离的含义（235.5 比 180.2 大）
#   只有一个数


# ============================================================
# 二、现在要做"分类"
# ============================================================
#   输入一张手写数字图  ->  模型  ->  输出"这是 0~9 里的哪一个"
#
# 看起来差不多，其实完全不同：
#   答案不是"一个数"，而是"10 个选项里选一个"
#
# 这个差别引出了三个必须先定下来的问题：
#   ① 模型应该输出什么格式？
#   ② 怎么判对错？
#   ③ 怎么衡量"错了多少"？
#
# C01 就是定这三件事，后面所有代码都按这个约定写。


# ============================================================
# 三、为什么不能直接让模型输出"7"
# ============================================================
# 有人会想：那就让模型输出一个数，7 就是 7，不是很简单吗？
#
# 这里有三个问题：
#
#   ① 输出 7.3 算什么？四舍五入成 7？那 7.5 呢？边界很武断
#
#   ② 模型会以为"0 和 9 差得最远"
#      但 0 和 9 只是两个不同的图案，没有大小、没有距离
#      让模型学"数字 9 比数字 0 大 9"，等于让它学一个假规律
#
#   ③ 图片稍微变一点，预测可能从 6.9 变成 7.1
#      -> 类别从 7 跳到了 6，错得很随机
#
# 所以分类的做法是：
#   给每一个类别各输出一个"分数"，谁的分数最高，就选谁


# ============================================================
# 四、四种东西，一定要分清
# ============================================================
# 用"十选一的选择题考试"来记：
#
#   现实里的事                代码里的名字      类型
#   ------------------------------------------------------
#   标准答案：第 3 题选 C     labels          整数 int64
#   学生给 A~J 各打的分        logits          浮点，可正可负
#   把分数换算成百分比          probs           浮点，0~1，和为 1
#   学生最终圈出的选项          pred            整数 int64
#   老师批改：正确选项得几分     loss            一个数
#
# 对应的三个操作：
#   logits.argmax(dim=1)      圈答案（选分数最高的位置）
#   F.softmax(logits, dim=1)  把分数换算成百分比
#   F.cross_entropy(...)      批改：正确选项的百分比越低，罚得越狠


import torch
import torch.nn.functional as F

# ============================================================
# 五、看一组具体数字
# ============================================================
print("=" * 60)
print("一、分数的样子")

# 2 道题，每题 3 个选项（真实是 10 个，这里缩小方便看）
logits = torch.tensor([
    [2.0, 1.0, 0.1],
    [0.5, 3.0, 0.2],
])
labels = torch.tensor([0, 1])       # 标准答案

print("logits（学生打的分）:")
print(logits)
print("labels（标准答案）:", labels.tolist())

print("argmax（圈出来的答案）:", logits.argmax(dim=1).tolist())
# [0, 1] —— 第 1 行最高分在位置 0，第 2 行最高分在位置 1

print("softmax（换算成百分比）:")
print(F.softmax(logits, dim=1))
# [[0.6590, 0.2424, 0.0986],
#  [0.0718, 0.8750, 0.0532]]
# 每行加起来等于 1


# ============================================================
# 六、损失是怎么来的（拆成三步看）
# ============================================================
print("=" * 60)
print("二、交叉熵损失")

probs = F.softmax(logits, dim=1)
p_true = probs[torch.arange(2), labels]      # 取出"正确答案"那个位置的概率

print("① 正确类别的概率 =", [round(v, 4) for v in p_true.tolist()])
print("② 取负对数       =", [round(-v, 4) for v in torch.log(p_true).tolist()])
print("③ 求平均         =", round((-torch.log(p_true)).mean().item(), 4))
print("直接调 cross_entropy =", round(F.cross_entropy(logits, labels).item(), 4))

# 输出：
#   ① [0.659, 0.875]
#   ② [0.417, 0.1336]
#   ③ 0.2753
#   cross_entropy = 0.2753      <- 完全一致
#
# 所以"分类训练"的目标就是一句话：
#   让"正确类别的概率"越来越大
#   换算到 logits，就是让正确类的分数比其它类高出一大截


# ============================================================
# 七、MNIST 的尺寸约定（记住这张表）
# ============================================================
#   东西          形状              含义
#   ------------------------------------------------------------
#   输入图片      [B, 1, 28, 28]    B 张灰度图
#   展平后        [B, 784]          28×28 压成一个向量
#   logits        [B, 10]           每张图 10 个类别的分数
#   标签          [B]               每张图一个编号（int64）
#   预测类别      [B]               argmax 之后
#
# B 是 batch size，会变；其余几个都是固定的
#
# 注意 [B, 10] 和 [B] 的区别：
#   模型输出 10 个分数，但每条样本只有一个正确答案


# ============================================================
# 八、这一课要记住的一句
# ============================================================
# 分类任务 = 给每个类别一个分数（logits）-> 用 argmax 选最高的 -> 
#            用 cross_entropy(正确类别的分数) 衡量错多少
#
# 类别之间是并列的，没有大小、没有距离。

print("=" * 60)
print("演示结束")
