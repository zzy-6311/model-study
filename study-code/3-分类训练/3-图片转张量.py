# C03：图片怎么变成张量
#
# 这一课几乎没有代码。它讲的是"数据进模型之前的最后一道工序"。
# 代码只放在需要看数字的地方。

# 一张图片有三种身份：
#
#   ① 磁盘上的文件     xxx.jpg      压缩过的字节，模型完全看不懂
#           ↓ 解码
#   ② 像素网格         H × W 的数字  每个数 0~255
#           ↓ 变形 + 缩放
#   ③ 张量             [C, H, W]     每个数 0~1（或标准化后）
#
# 模型只吃第 ③ 种。中间那一步就是这一课的全部内容。


# ============================================================
# 一、每个数字代表什么
# ============================================================
# 灰度图：一个像素 = 一个亮度
#   0   = 黑
#   255 = 白
#   中间 = 灰
#
# MNIST 就是 28×28 的灰度图：
#   笔画部分亮（数值大），背景黑（数值 0）
#
# 彩色图：一个像素 = 三个亮度，分别对应 R、G、B
#   纯红 = (255, 0, 0)
#   纯白 = (255, 255, 255)
#   纯黑 = (0, 0, 0)


import torch

# ============================================================
# 二、一条图片的完整形状旅程（不需要真图片文件）
# ============================================================
print("=" * 60)
print("一、形状变化")

# 假装这是从文件解码出来的 28×28 灰度图，数值 0~255
img_hw = torch.randint(0, 256, (28, 28)).float()
print("解码后形状 =", tuple(img_hw.shape), " 范围:",
      img_hw.min().item(), "~", img_hw.max().item())

# 第 1 步：加通道维，变成 [1, 28, 28]
# 第 2 步：除以 255，范围变成 0~1
img_chw = img_hw.unsqueeze(0) / 255.0
print("处理后形状 =", tuple(img_chw.shape), " 范围:",
      round(img_chw.min().item(), 4), "~", round(img_chw.max().item(), 4))

# 为什么要加那个 1？
#   模型永远按"批次"收数据：[批次, 通道, 高, 宽]
#   一张图也是 1 个批次，所以是 [1, 1, 28, 28]（灰度）
#   彩色图是 [1, 3, 28, 28]


# ============================================================
# 三、除以 255 到底改了什么
# ============================================================
print("=" * 60)
print("二、除以 255")

pixels = torch.tensor([0.0, 64.0, 128.0, 255.0])
print("原值:", pixels.tolist())
print("除以 255 后:", [round(v, 4) for v in (pixels / 255).tolist()])

# 为什么要缩到 0~1？两个原因：
#   1. 数值太大训练不稳。A09 讲过：学习率上限由数据尺度决定，
#      x 放大 10 倍，梯度就放大 10 倍，合适的 lr 要缩小 10 倍
#   2. 0~1 是绝大多数模型默认的输入范围，
#      初始化、激活函数、正则化都是按这个尺度设计的


# ============================================================
# 四、HWC -> CHW 必须用 permute，不能用 reshape
# ============================================================
print("=" * 60)
print("三、换轴")

# 造一个带编号的张量，假装是 [高=2, 宽=3, 通道=4] 的小图
hwc = torch.arange(24).reshape(2, 3, 4)
print("原图 [高,宽,通道] 的形状 =", tuple(hwc.shape))

chw = hwc.permute(2, 0, 1)      # 正确的换轴
wrong = hwc.reshape(4, 2, 3)    # 错误的做法

print("permute 后形状 =", tuple(chw.shape), " 第 0 通道:")
print(chw[0])
# [[ 0,  4,  8],
#  [12, 16, 20]]      <- 这是"通道 0"的整张图（2 行 3 列）

print("reshape 后形状 =", tuple(wrong.shape), " 第 0 块:")
print(wrong[0])
# [[0, 1, 2],
#  [3, 4, 5]]         <- 这不是一张图，只是把前 6 个数重新摆了

# 两者形状一样，内容完全不同。
# reshape 只重新切分，permute 才真正交换了"哪一维代表什么"。
# 用错不会报错，只会让模型看到错乱的颜色。


# ============================================================
# 五、标准化：减均值、除标准差
# ============================================================
print("=" * 60)
print("四、标准化")

x = torch.tensor([0.0, 0.1, 0.5, 0.9, 1.0])
mean, std = 0.1307, 0.3081          # MNIST 训练集统计出来的
print("原值:", x.tolist())
print("标准化后:", [round(v, 4) for v in ((x - mean) / std).tolist()])

# 除完 255 之后，数据在 0~1 之间，但仍然"偏在一侧"
#   MNIST 大部分像素是背景（接近 0），所以均值只有 0.13
# 标准化把它变成"均值 0、标准差 1"，让数据居中、尺度统一
#
# 好处：收敛更快，对学习率更宽容
#
# ★ mean 和 std 只能用训练集算
#   如果用全部数据（含验证集）算，验证集的信息就漏进了预处理流程 —— 
#   和 C02 讲的数据泄漏是同一种错误


# ============================================================
# 六、最常见的三个错误
# ============================================================
print("=" * 60)
print("五、重复除 255 会怎样")

bad = (torch.tensor([128.0]) / 255) / 255
print("128 除以两次 255 =", round(bad.item(), 6))
# 0.001969 —— 模型看到的基本全是 0，训练几乎不动，但程序不报错
#
# 这种情况常发生在：
#   你自己手动 /255 了，又交给 ToTensor()（它内部已经除过一次）

# 另外两个错误：
#   ② RGB / BGR 弄混   OpenCV 读出来是 BGR，PIL 是 RGB
#   ③ 验证时用了随机增强  训练可以随机，验证必须固定，否则每次结果都不一样


# ============================================================
# 七、这一课要记住的一句"约定"
# ============================================================
# 一张 28×28 灰度图片：
#   读成 [1, 28, 28] 的张量
#   除以 255 变成 0~1
#   用训练集算出的 mean=0.1307, std=0.3081 做标准化
#   然后才喂给模型
#
# 推理时必须照着这句再做一遍，一模一样。
# 少除一次 255、把 RGB 当 BGR、忘了标准化 —— 模型不会报错，
# 只会安静地给出垃圾结果。

print("=" * 60)
print("流程演示结束")
