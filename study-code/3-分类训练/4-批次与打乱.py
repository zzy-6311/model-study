# C04：数据是怎么一批批进模型的
#
# 【这一课解决什么问题】
#   你有 60000 张图。模型训练时要一张一张吃、还是一起吃？
#   这一课讲"分批"这件事背后的原理，不涉及任何写法。


# ============================================================
# 一、为什么不一次吃全部
# ============================================================
# 从数学上讲，一次用全部数据算出来的梯度是"真梯度"，
# 方向最准，没有任何噪声。听起来最理想。
#
# 但实际做不到，有三个原因：
#
#   ① 装不下
#      60000 张 28×28 的图是 4700 万个数，加上模型中间层的激活值，
#      显存直接爆掉。图片再大一点（比如 640×640 的检测任务），
#      几百张就爆。
#
#   ② 太慢
#      用全部数据算一次梯度，才更新一次参数。
#      一个 epoch（把数据过一遍）只更新 1 次，学得太慢。
#
#   ③ 没必要那么准
#      梯度的方向本来就只需要"大致对"。
#      用一小批样本估出来的方向，虽然有点抖，但走 100 步
#      比走 1 步准得多。


# ============================================================
# 二、batch 的本质：用一小批"估计"整体梯度
# ============================================================
# 这是这一课最重要的原理，值得慢慢讲。
#
# 训练要的东西是"全部样本的平均梯度"：
#
#       真梯度 = (g1 + g2 + ... + gN) / N
#
# 其中 g_i 是"第 i 个样本单独算出来的梯度"。
#
# 但 N 太大算不动，于是我们只抽一小批（比如 64 个）：
#
#       batch梯度 = (g_a + g_b + ... + g_64) / 64
#
# 这个数和真梯度不一样，但它是"真梯度的无偏估计"——
# 意思是：这一次可能偏大一点、下一次可能偏小一点，
#         但反复抽、平均下来，正好等于真值。
#
# 用数字看：

g = [0.6, -0.2, 1.0, -0.4]      # 4 个样本各自的梯度
print("真梯度（4 个全用）= ", round(sum(g) / 4, 4))
print("批次 A（前 2 个）  = ", round(sum(g[:2]) / 2, 4))
print("批次 B（后 2 个）  = ", round(sum(g[2:]) / 2, 4))
print("两批梯度的平均      = ", round(((sum(g[:2]) / 2) + (sum(g[2:]) / 2)) / 2, 4))

# 输出：
#   真梯度 = 0.25
#   批次 A = 0.20     <- 偏小
#   批次 B = 0.30     <- 偏大
#   两批平均 = 0.25   <- 正好回到真值
#
# 结论：
#   单个 batch 的梯度是"有噪声的估计"，方向不完全准
#   但它没有系统性偏差，多走几步就平均掉了
#   这就是为什么训练曲线会上下抖动，但整体在降


# ============================================================
# 三、为什么每一轮都要重新打乱
# ============================================================
# 如果数据是按类别排好序的（0 的图全在前面，1 的后面……），
# 又正好按顺序切批，会发生什么：
#
#   第 1 步：64 张全是"0"      -> 梯度只指向"更像 0"
#   第 2 步：64 张全是"0"      -> 又往同一个方向推
#   ...
#   第 3000 步：终于轮到"1"了  -> 梯度突然反方向
#
# 模型会在两个极端之间来回甩，很难收敛。
#
# 打乱（shuffle）解决的就是这个问题：
#   每一批里都混着各种类别，估出来的梯度方向接近真实整体方向
#
# 注意是"每一轮重新打乱"，不是只在开始打乱一次：
#   同一个 epoch 里，每个样本只出现一次（不重复训练）
#   但下一个 epoch，配对方式又不一样了
#   -> 相当于每一轮看到的是不同的"批次组合"，能减少过拟合


# ============================================================
# 四、最后一个不满的批次怎么办
# ============================================================
# 60000 ÷ 64 = 937.5，不整除。
# 最后一个批次只有 32 个样本，比别的批次少一半。
#
# 两种处理方式：
#   留  ：这个 32 个样本的小批次，梯度依然是无偏的（只是噪声大一点）
#   丢  ：把最后 32 个样本直接扔掉，保证每个批次都是 64
#
# 丢掉的好处：每一步的计算量稳定，某些硬件上更快
# 丢掉的代价：每个 epoch 有 32 个样本没被训练到
#
# 更隐蔽的问题是"统计"：
#   如果 10 个批次里 9 个是 64 张、1 个是 32 张，
#   把 10 个批次的 loss 简单平均，会高估那个小批次的影响。
#   正确做法是按样本数加权平均（C07 会讲）。


# ============================================================
# 五、epoch 和 step 的换算
# ============================================================
#   step（步）  = 一次参数更新 = 吃一个批次
#   epoch（轮） = 把整个训练集完整过一遍
#
#   一个 epoch 的步数 = 训练集样本数 ÷ 批次大小（向上取整）
#
N_total, batch = 60000, 64
steps = (N_total + batch - 1) // batch
print()
print(f"{N_total} 个样本，批次 {batch} -> 每个 epoch {steps} 步")
print(f"训练 10 轮 = {steps * 10} 次参数更新")
print(f"如果想一个 epoch 只更新 1 次，批次就得是 {N_total}")

# 输出：
#   60000 个样本，批次 64 -> 每个 epoch 938 步
#   训练 10 轮 = 9380 次参数更新
#
# 这个换算很重要，因为：
#   "训练 10 轮"和"训练 10000 步"是两件事
#   换批次大小之后，同样的轮数对应的更新次数完全不同


# ============================================================
# 六、批次大小怎么选（三个权衡）
# ============================================================
# ① 梯度质量 vs 更新次数
#    批次大：每步方向准，但一个 epoch 的步数少
#    批次小：每步方向抖，但更新次数多
#    经验上：小的往往更快收敛，但抖动大、训练不稳定
#
# ② 显存
#    批次越大，中间激活值越多，显存吃得越多
#    batch 翻倍，显存大致翻倍
#
# ③ 和学习率的配合
#    批次变大，梯度估计更平滑，通常要同步把学习率调大
#    常见做法：批次翻倍，学习率也翻倍（不是严格定律）
#    因为"每步走得稳"之后，可以放心迈大步
#
# C 阶段教学用 32 或 64 就够，MNIST 很小，不需要纠结。


# ============================================================
# 七、这一课要记住的三句
# ============================================================
# 1. 每步用一小批样本，估的是"平均梯度"。
#    单个批次有噪声，但反复抽平均下来是对的。
#
# 2. 每一轮必须重新打乱。
#    否则同类别扎堆，梯度方向来回甩。
#
# 3. 一个 epoch 的步数 = 样本数 ÷ 批次大小。
#    "训练多少轮"和"更新多少次"是两件事。

