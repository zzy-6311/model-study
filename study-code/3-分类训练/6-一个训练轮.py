# C06：一个 epoch 里到底发生了什么
#
# 【这一课解决什么问题】
#   你写"训练 10 轮"，可一轮里到底算了什么？
#   最后报出来的那个 loss 和准确率，是怎么汇总出来的？
#
# 这一课讲清楚三件事：
#   ① 一轮里参数被更新了多少次
#   ② loss 怎么汇总才不出错
#   ③ 训练 loss 和验证 loss 为什么数值对不上


# ============================================================
# 一、一个 epoch = 938 次完整的训练动作
# ============================================================
# 60000 个样本，批次 64 -> 938 个批次。
#
# 每一个批次都要完整走一遍：
#
#   ① 前向：把 64 张图喂进去，得到 64 组 logits
#   ② 算损失：这 64 个样本的交叉熵取平均
#   ③ 反向：算出每个参数的梯度
#   ④ 更新：参数被改动一次
#
# 所以一个 epoch 结束时，参数已经被改了 938 次，不是 1 次。
#
# 这一点很重要，因为它意味着：
#   同一轮里，第 1 个批次用的模型和第 938 个批次用的模型，
#   已经不是同一个模型了。
#   参数一路在变，所以每个批次的损失是基于不同版本的模型算出来的。
#
# 换句话说：一个 epoch 内的"训练过程"本身就是一个持续变化的过程，
# 我们只是用一个平均值来描述它，这个平均值天然是"被稀释"的。


# ============================================================
# 二、loss 怎么汇总（这里有个容易错的地方）
# ============================================================
# 最自然的想法：把 938 个批次的 loss 加起来除以 938。
#
# 这在批次大小完全一样时是对的。但最后一个批次经常不满：
#   60000 ÷ 64 = 937.5  ->  937 个满批次 + 1 个只有 32 个样本的批次
#
# 这时"简单平均"会给那个小批次过高的权重。
# 举个夸张的例子看差别：

batch_losses = [0.5] * 9 + [5.0]      # 9 个满批次各 64 个样本，1 个批次只有 3 个样本
sample_counts = [64] * 9 + [3]

simple = sum(batch_losses) / len(batch_losses)
weighted = sum(l * n for l, n in zip(batch_losses, sample_counts)) / sum(sample_counts)

print("=" * 60)
print("一、两种平均方式的差别")
print("简单平均（把批次当等权）   =", round(simple, 4))
print("加权平均（按样本数）       =", round(weighted, 4))

# 输出：
#   简单平均 = 0.95
#   加权平均 = 0.5233
#
# 差了快一倍。原因：那个只有 3 个样本的批次，
# 在简单平均里占了 1/10 的权重，但它只占总样本的 0.5%，
# 于是它的 5.0 被放大了 20 倍地影响结果。
#
# 正确做法永远是加权平均：
#   把每个批次的 loss 乘上它的样本数，加起来，再除以总样本数。


# ============================================================
# 三、准确率怎么算
# ============================================================
# 准确率不能用"loss 的平均"那套，它是一个计数问题：
#
#   对每个样本：argmax 出来的类别 == 标签？ -> 记 1，否则 0
#   一个 epoch 结束：把所有的 1 加起来，除以总样本数
#
# 关键：要在"样本级"统计，不能在"批次级"统计。
#   因为不同批次的样本数可能不同，批次级平均同样会算偏。
#
# 另外要注意：判断对错要用 argmax 的结果，
# 不能拿 logits 去比 —— logits 是分数，标签是编号，两回事。


# ============================================================
# 四、训练 loss 和验证 loss 为什么对不上
# ============================================================
# 很多人第一次训练时会发现：
#
#   训练 loss = 0.38
#   验证 loss = 0.52
#
# 然后怀疑"是不是验证集有问题"。多数时候不是，原因有三个：
#
# ① 训练 loss 是"整个 epoch 的平均"，而 epoch 里模型在变好
#    第 1 批的 loss 可能有 2.0，第 938 批只有 0.3
#    平均值被前面的差成绩拉高了
#    而验证 loss 只用"此刻这个模型"算一次，没有这个稀释
#
# ② 训练时的模型和验证时的模型行为不同
#    Dropout 层训练时随机失活，验证时关闭
#    BatchNorm 用当前批次的统计量 vs 用累计的统计量
#    -> 同一个模型，两种模式下输出的数值本来就不一样（C07 细讲）
#
# ③ 模型确实开始背训练集了
#    训练 loss 持续下降，验证 loss 反而上升
#    -> 这是过拟合的信号，是另一回事，要看曲线走势而不是单点数值
#
# 所以判断模型好不好，不能只看"两个数差不多"，要看两条曲线的走势。


# ============================================================
# 五、一轮结束该记录什么
# ============================================================
#   训练 loss（按样本加权）
#   训练准确率
#   验证 loss
#   验证准确率
#
# 四个数，每个 epoch 记一行。画出来就是两条曲线。
#
# 判断标准：
#   两条都在降        -> 还在学，继续
#   训练降、验证升    -> 开始过拟合，该停或者加正则
#   两条都平了        -> 学到头了，或者学习率有问题
#   验证几乎不动但训练在降 -> 模型在背答案，泛化没提升


# ============================================================
# 六、这一课要记住的三句
# ============================================================
# 1. 一个 epoch 里参数被更新了 938 次，不是一个"整体动作"。
#    训练 loss 是整个过程中不同版本模型的平均，天然偏高。
#
# 2. loss 汇总必须按样本数加权，准确率必须在样本级统计。
#    批次大小不一致时，"简单平均"会算偏。
#
# 3. 训练 loss 和验证 loss 数值不同是正常的，甚至必然而然。
#    要看两条曲线的走势，而不是单点的差值。

print()
print("这一课的重点：一个 epoch 是个持续变化的 938 步过程，不是一个数。")
