# C05：交叉熵——分类损失为什么长这个形状
#
# 【这一课解决什么问题】
#   分类要回答"模型错了多少"。可这个"错"怎么定义？
#
#   回归用的是平方误差：(预测 - 答案)²，很直观。
#   分类为什么不能照搬，非要换成 -log(正确类的概率)？
#
# 这一课把这件事讲透。代码只有两处，都是"看数字"。


# ============================================================
# 一、第一步：把分数变成概率
# ============================================================
# 模型输出的是 10 个分数（logits），可以是任意实数：
#
#   [-1.2,  3.7,  0.5, ... ]
#
# 这些数不好直接比较"像不像"。所以先转成概率：
#
#   概率 = exp(分数) / 所有 exp(分数) 之和
#
# 这叫 softmax。为什么要用 exp？三个原因：
#
#   ① 任何实数经过 exp 都变成正数（概率不能是负的）
#   ② 所有数加起来正好是 1（自动满足概率的定义）
#   ③ exp 会放大差距：3.7 比 0.5 高 3.2，exp 之后差距是 e^3.2 ≈ 24 倍
#
# 第三条很关键：模型分数领先一点点，概率就拉开很多。
# 这让"猜得最像的那个"概率接近 1，其它接近 0，训练信号更清晰。


# ============================================================
# 二、第二步：从概率到损失，为什么是 -log(p)
# ============================================================
# 设"正确答案那个类别的概率"为 p。损失定义为：
#
#        loss = -log(p)
#
# 为什么不直接用 (1 - p)？看这个表就明白了：

import math

print("=" * 60)
print("一、-log(p) 长什么样")

for p in (1.0, 0.9, 0.5, 0.1, 0.01):
    print(f"  正确类概率 p={p:<5}  ->  loss = {-math.log(p):.4f}")

# 输出：
#   p=1.0   -> loss = 0.0000      完全确定且正确，不罚
#   p=0.9   -> loss = 0.1054      很有把握，罚一点
#   p=0.5   -> loss = 0.6931      一半一半
#   p=0.1   -> loss = 2.3026      明显猜错，重罚
#   p=0.01  -> loss = 4.6052      错得离谱，重罚到底
#
# 这个形状有三个好性质：
#
#   ① p = 1 时损失正好是 0（完美的时候不罚）
#   ② p 越小，损失涨得越慢但一直涨（不会饱和，永远有信号）
#   ③ 从 0.9 掉到 0.1，损失从 0.1 涨到 2.3 —— 差 22 倍
#      而 (1-p) 只从 0.1 涨到 0.9，差 9 倍
#
# 换句话说：-log 对"明明错得很离谱却还很自信"这种情况，罚得特别狠。
# 这正是我们想要的。


# ============================================================
# 三、这个名字从哪来：信息量
# ============================================================
# -log(p) 在信息论里叫"信息量"或"自信息"：
#
#   一件事发生的概率越小，它发生时带来的"惊讶"越大
#
#   太阳从东边升起（p≈1）       -> 信息量 0，完全不惊讶
#   硬币正面（p=0.5）            -> 信息量 0.69
#   中彩票（p=0.01）             -> 信息量 4.6，非常惊讶
#
# 交叉熵就是"正确答案这件事，在模型看来有多惊讶"。
#
# 所以训练的目标可以翻译成一句很朴素的话：
#   让模型对正确答案不要感到惊讶 —— 也就是"早就猜到了"。


import torch

# ============================================================
# 四、为什么不用平方误差（关键对比）
# ============================================================
print("=" * 60)
print("二、错得很离谱时，两种损失的梯度")

# 二分类：正确答案是第 0 类
# 情况：logits = [-5, 5]，模型非常笃定地选了第 1 类（完全错）

z1 = torch.tensor([-5.0, 5.0], requires_grad=True)
p1 = torch.softmax(z1, dim=0)
ce1 = -torch.log(p1[0])
ce1.backward()
print("交叉熵 : loss =", round(ce1.item(), 4),
      " 对 logits 的梯度 =", [round(v, 4) for v in z1.grad.tolist()])

z2 = torch.tensor([-5.0, 5.0], requires_grad=True)
p2 = torch.softmax(z2, dim=0)
target = torch.tensor([1.0, 0.0])
mse2 = ((p2 - target) ** 2).sum()
mse2.backward()
print("平方误差: loss =", round(mse2.item(), 4),
      " 对 logits 的梯度 =", [round(v, 6) for v in z2.grad.tolist()])

# 输出：
#   交叉熵  : loss = 10.0  梯度 = [-1.0, 1.0]        <- 很大的信号
#   平方误差: loss = 2.0   梯度 = [-0.0002, 0.0002]  <- 几乎是 0
#
# 这就是分类不能用平方误差的核心原因：
#
#   错得越离谱，softmax 输出来的概率越"极端"（0.0000 和 1.0000）
#   而平方误差对概率的梯度里含有 p×(1-p) 这个因子
#   p 接近 0 或 1 时，p×(1-p) 接近 0 -> 梯度消失
#
#   结果：模型错得最狠的时候，恰恰收不到"你错了"的信号，
#         只能慢慢挪，训练几乎停滞。
#
# 交叉熵就没有这个问题：它的梯度是 (概率 - 答案)，
# 错得越狠，(概率-答案) 越大，信号越强。


# ============================================================
# 五、交叉熵的梯度长什么样（一句话记住）
# ============================================================
# 对 logits 求导，结果简单得惊人：
#
#       梯度 = 预测概率 - 真实标签（one-hot）
#
# 举例：真实是第 0 类，预测概率 [0.9, 0.1]
#   梯度 = [0.9-1, 0.1-0] = [-0.1, +0.1]
#   -> 把第 0 类的分数往上推 0.1，第 1 类往下压 0.1
#
# 如果预测成 [0.1, 0.9]（错得厉害）
#   梯度 = [0.1-1, 0.9-0] = [-0.9, +0.9]
#   -> 推力大了 9 倍
#
# 这就是"错得越多，纠正力度越大"的数学来源。
# 不需要额外的权重调节，损失函数本身自带这个性质。


# ============================================================
# 六、一个工程细节：别自己去算 log
# ============================================================
# 如果某个类别的概率算出来正好是 0，log(0) = 负无穷，
# 损失直接变成 inf，训练崩掉。
#
# 所以实际实现里不"先算概率再取对数"，而是把两步合并成一步
# （数学上等价，但内部用减法避免溢出）。这叫 log_softmax 技巧。
#
# 这也是为什么"交叉熵损失"这个函数同时接收原始分数（logits），
# 而不是接收已经算好的概率：
#   你交概率给它，它会以为那是"没做 softmax 的分数"，再算一次 -> 全错


# ============================================================
# 七、这一课要记住的三句
# ============================================================
# 1. 交叉熵 = -log(正确类别的概率)，衡量"模型对答案有多惊讶"
#
# 2. 不用平方误差的原因：错得越狠，平方误差的梯度越接近 0，
#    而交叉熵的梯度反而越大。分类要的是后者。
#
# 3. 交叉熵对 logits 的梯度 = 概率 - 答案，简洁又不会消失。

print()
print("这一课的重点不在数字，而在'为什么是这个形状'。")
