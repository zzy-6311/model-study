# D06：下采样与感受野
#
# 【这一课解决什么问题】
#   一层 3×3 卷积只看 3×3 的一小块。
#   那网络怎么判断"整张图里有没有一只猫"？
#
#   答案是：堆层。层数堆够了，最后一个输出就能"看到"整张图。
#   "一个输出到底看到了多大范围"，这个量叫感受野。


# ============================================================
# 一、感受野的定义
# ============================================================
#   输出特征图上的**一个点**，对应回原始输入上的**一块区域**。
#   这块区域的边长，就是这一层的感受野。
#
# 举例：
#   一层 3×3 卷积，输出上的一个点，是由输入的 3×3 那块算出来的。
#   感受野 = 3。
#
#   再接一层 3×3：
#   第二层输出上的一个点，由第一层的 3×3 算出；
#   而第一层的每个点又对应输入的 3×3。
#   往两边各扩 1 格，所以覆盖 5×5。感受野 = 5。
#
# 规律（全是 3×3、步长 1）：
#   1 层 -> 3
#   2 层 -> 5
#   3 层 -> 7
#   n 层 -> 2n + 1


# ============================================================
# 二、为什么用 3×3 堆叠，而不是直接上大核
# ============================================================
# 两层 3×3 的感受野，和一层 5×5 一样（都是 5×5）。
# 但参数差很多。假设输入输出都是 C 个通道：
#
#   一层 5×5 : C × C × 5 × 5 = 25 C^2
#   两层 3×3 : 2 × (C × C × 3 × 3) = 18 C^2     -> 省 28%
#
#   三层 3×3 : 27 C^2  （感受野 7）
#   一层 7×7 : 49 C^2                            -> 省 45%
#
# 还有第二个好处：中间多了一层，就多了一次非线性激活。
# 非线性越多，网络能表达的函数越复杂（B08 讲过 ReLU 的作用）。
#
# 所以"多个小核"在参数和表达能力上都优于一个大核。
# 这是 VGG（2014）的核心思想，之后几乎所有 CNN 都这么做。


# ============================================================
# 三、stride 的作用：让感受野加速扩大
# ============================================================
# 如果只有 3×3、步长 1，堆到感受野 100 需要约 50 层。太深了。
#
# 步长 2 的下采样解决了这个问题：
#   每做一次 stride=2，特征图高宽减半，
#   相当于"每个输出跨过的输入范围"翻倍。
#   于是后面每一层 3×3，能在原始图上多覆盖 2 倍的距离。
#
# 递推公式：
#   r_out = r_in + (k - 1) × jump
#   jump  = jump × stride
#
# 其中 jump 是"特征图上走一格，相当于原图走几格"。

print("=" * 60)
print("一、YOLO 风格的前 9 层，感受野怎么涨")

seq = [(3, 2), (3, 2), (3, 1), (3, 2), (3, 1), (3, 2), (3, 1), (3, 2), (3, 1)]
r, jump = 1, 1
print(f"{'层':>3} {'核':>3} {'步长':>5} {'感受野':>7} {'jump':>6}")
for i, (k, s) in enumerate(seq, 1):
    r = r + (k - 1) * jump
    jump = jump * s
    print(f"{i:>3} {k:>3} {s:>5} {r:>7} {jump:>6}")

# 输出：
#   层   核  步长   感受野   jump
#    1    3    2       3      2
#    2    3    2       7      4
#    3    3    1      15      4
#    4    3    2      23      8
#    5    3    1      39      8
#    6    3    2      55     16
#    7    3    1      87     16
#    8    3    2     119     32
#    9    3    1     183     32
#
# 读法：
#   第 8 层之后 jump = 32，说明特征图上走一格 = 原图走 32 格。
#   这时特征图是原图的 1/32，但每个点能看到原图 119×119 的范围。
#
# 只有 9 层，感受野就到了 183。如果全靠步长 1，需要 90 层才行。
#
# ★ 这就是 YOLO 的 P3/P4/P5 的来源：
#   下采样 8 倍的特征图（stride 8）   -> P3，感受野小，负责小物体
#   下采样 16 倍（stride 16）         -> P4，负责中等物体
#   下采样 32 倍（stride 32）         -> P5，负责大物体
#   三种尺度的特征图同时用来检测，这就是"多尺度检测"。


# ============================================================
# 四、下采样的三种手段
# ============================================================
# ① 池化（MaxPool / AvgPool）
#    取窗口里的最大值或平均值。
#    没有参数，不能学习。早期网络（AlexNet、VGG）常用。
#
# ② 步长卷积（stride=2 的卷积）
#    一边下采样一边提取特征，有参数、能学习。
#    现代网络（ResNet、YOLO）都用这个代替池化。
#
# ③ 膨胀卷积（dilated convolution）
#    核的采样点之间插空洞，不增加参数也能扩大覆盖范围。
#    例：3×3 核、dilation=2 -> 实际覆盖 5×5，但只有 9 个权重。
#    YOLO26 的 SPPF、C2PSA 里会用到类似的思路（用不同尺度的池化/注意力
#    来扩大感知范围）。

# 为什么现在少用池化了？
#   池化是"不可学习的下采样"，而且会直接丢掉大部分信息。
#   步长卷积能一边减尺寸一边学特征，信息利用率更高。


# ============================================================
# 五、理论感受野 vs 有效感受野
# ============================================================
# 公式算出来的叫"理论感受野"：数学上这个输出能触到的最远输入。
#
# 但实际上，感受野范围内不同位置的贡献并不相等：
#   中心的像素经过的路径多，权重大
#   边缘的像素经过的路径少，权重小
#
# 真实起作用的是一个"高斯形状"的区域，比理论值小得多，
# 这叫"有效感受野"。
#
# 实践含义：
#   理论感受野 183，不代表网络真的能用上 183×183 的信息。
#   所以有些方法会专门设计（比如加空洞卷积、加注意力）来"填满"感受野。


# ============================================================
# 六、这一课要记住的三句
# ============================================================
# 1. 感受野 = 输出上一个点能看到原始输入的多大范围。
#    纯 3×3 步长 1 堆叠：n 层 -> 2n+1。
#
# 2. 用多个 3×3 代替一个大核：感受野相同，参数更少，非线性更多。
#
# 3. stride=2 让 jump 翻倍，感受野加速扩大。
#    YOLO 的 P3/P4/P5 就是 stride 8/16/32 三个尺度，
#    分别负责小、中、大物体。

