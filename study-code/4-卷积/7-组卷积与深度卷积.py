# D07：组卷积与深度卷积
#
# 【这一课解决什么问题】
#   普通卷积的参数 = C_in × C_out × k × k。
#   两个 256 通道的层相连，一层就 59 万参数。
#
#   有没有办法，在保持"能提取特征"的前提下，把参数量砍掉一个数量级？
#   有。这就是组卷积、深度卷积、深度可分离卷积。
#
#   Ultralytics 的 Conv 模块签名是：
#     Conv(c1, c2, k=1, s=1, p=None, g=1, d=1, act=True)
#                                       ↑
#                                    这个 g 就是本课的主角


# ============================================================
# 一、组卷积：把通道分成几组，组内相连
# ============================================================
# 普通卷积：每个输出通道都连所有输入通道。
#
# 组卷积（groups=g）：把输入通道分成 g 组，每组只连对应的一组输出通道。
#
#   g = 1   -> 就是普通卷积
#   g = 2   -> 输入分 2 组，输出分 2 组，1 组只看 1 组
#   g = 4   -> 分成 4 组
#   g = C_in -> 每个通道自己一组（就是深度卷积）
#
# 参数量的变化：
#   普通:  C_in × C_out × k × k
#   分组:  (C_in/g) × C_out × k × k = 普通 / g
#
# 权重张量的形状也会变：
#   普通  [C_out, C_in,       k, k]
#   分组  [C_out, C_in / g,   k, k]      <- 第二维只剩 1/g

import torch
import torch.nn as nn


def n_params(m):
    return sum(p.numel() for p in m.parameters())


C = 64
print("=" * 60)
print("一、同样是 64 -> 64、3x3，改 groups 会怎样")
print(f"{'groups':>7} {'参数':>9} {'weight 形状':>20}")
for g in (1, 2, 8, 64):
    layer = nn.Conv2d(C, C, 3, groups=g)
    print(f"{g:>7} {n_params(layer):>9,} {str(tuple(layer.weight.shape)):>20}")

# 输出：
#   groups      参数          weight 形状
#        1    36,928     (64, 64, 3, 3)
#        2    18,496     (64, 32, 3, 3)     <- 正好一半
#        8     4,672     (64,  8, 3, 3)     <- 正好 1/8
#       64       640     (64,  1, 3, 3)     <- 1/58
#
# 规律很干净：参数 = 普通 / g。
# 代价是：不同组之间不再交换信息。


# ============================================================
# 二、深度卷积：g = C_in 的极端情况
# ============================================================
# 每个输入通道单独配一个核，输出还是 C_in 个通道。
# 权重形状 [C_in, 1, k, k]。
#
# 参数 = C_in × k × k  （只和自己有关，不和其他通道混合）
#
# 它做的事：对每个通道**独立地**做一次空间滤波。
#   比如通道 1 找竖边、通道 2 找横边……各自干各自的，互不干扰。
#
# 关键缺陷：它完全不混合通道。
#   如果某个特征需要"通道 1 有竖边 且 通道 2 有横边"才能判断，
#   深度卷积看不到这种组合。


# ============================================================
# 三、深度可分离卷积：拆成两步
# ============================================================
# 既然深度卷积缺了"通道混合"，那就补一步：
#
#   第 1 步：深度卷积（3×3）  -> 每个通道各自做空间滤波
#   第 2 步：1×1 卷积          -> 把 C 个通道线性组合成 C_out 个
#
# 这个组合叫"深度可分离卷积"（depthwise separable convolution），
# 是 MobileNet 的核心，也是轻量网络的标配。

depthwise = nn.Conv2d(C, C, 3, groups=C)      # 第 1 步
pointwise = nn.Conv2d(C, C, 1)                 # 第 2 步
separable = n_params(depthwise) + n_params(pointwise)
normal = n_params(nn.Conv2d(C, C, 3))

print()
print("=" * 60)
print("二、深度可分离 vs 普通卷积")
print(f"  深度卷积    {n_params(depthwise):>8,}")
print(f"  1x1 卷积    {n_params(pointwise):>8,}")
print(f"  合计        {separable:>8,}")
print(f"  普通卷积    {normal:>8,}")
print(f"  省了        {(1 - separable / normal) * 100:>7.1f}%")

# 输出：
#   深度卷积       640
#   1x1 卷积     4,160
#   合计         4,800
#   普通卷积    36,928
#   省了          87.0%
#
# 通道数越大，省得越多：

print()
print(f"{'通道数':>6} {'普通 3x3':>12} {'深度可分离':>12} {'节省':>7}")
for c in (32, 64, 128, 256, 512):
    a = (c * 9 + 1) * c
    b = (9 + 1) * c + (c + 1) * c
    print(f"{c:>6} {a:>12,} {b:>12,} {(1 - b / a) * 100:>6.1f}%")

# 输出：32 -> 85.1%，512 -> 88.7%
# 大通道场景下几乎省了 9 成参数。


# ============================================================
# 四、为什么这样拆不亏
# ============================================================
# 关键在于：普通卷积其实在同时干两件事
#
#   ① 空间上：在邻域里找模式（竖边、角点……）
#   ② 通道上：把不同通道的信息组合起来
#
# 这两件事是可以分开做的：
#   先用深度卷积干 ①（每个通道各自找空间模式）
#   再用 1×1 卷积干 ②（把通道重新组合）
#
# 数学上不是完全等价，但效果接近，参数少一个数量级。
# 这就是"因式分解"的思想：把一个大操作拆成两个小操作。


# ============================================================
# 五、代价是什么
# ============================================================
# 省参数一定是有代价的：表达能力变弱了。
#
# 普通卷积可以表达"通道 1 的左上角和通道 2 的右下角同时亮"这类组合；
# 深度可分离要先把两部分各自算完，再线性组合，能表达的组合种类变少。
#
# 常见的补偿手段：
#   ① 多堆几层（层数换参数）
#   ② 用残差连接（D08 讲，保证信息能直通）
#   ③ 适当加宽通道（参数省了，可以把通道开大一点）
#
# 现代轻量网络基本都是"深度可分离 + 残差 + 1×1 提通道"这个组合。


# ============================================================
# 六、在 YOLO 源码里对应什么
# ============================================================
# ① Ultralytics 的 Conv 模块（本地 conv.py 第 61 行）：
#
#      def __init__(self, c1, c2, k=1, s=1, p=None, g=1, d=1, act=True)
#
#    里面就是 nn.Conv2d(..., groups=g, dilation=d)。
#    所以 g 就是 groups，d 就是膨胀率。你在结构表里看到模块参数变多时，
#    很可能就是在传 g 或 d。
#
# ② yolo26.yaml 里的 Conv 大多是 g=1（默认），例如：
#
#      - [-1, 1, Conv, [64, 3, 2]]     # 64 通道、3×3、步长 2
#
#    这里的 [64, 3, 2] 只填了 c2、k、s，g 用默认 1。
#
# ③ 但 1×1 卷积在 YOLO 里到处都是。
#    看 yaml 里那些 C3k2 模块，它们内部的做法是：
#      先用 1×1 把通道压到很窄（比如压缩 4 倍）
#      在窄通道上做 3×3 卷积（便宜）
#      再用 1×1 把通道提回去
#    这就是 D04 讲的"1×1 只改通道不改空间"的经典用法：
#    用极少的参数完成通道变换，把计算集中在真正需要的地方。
#
# ④ SPPF（yaml 第 36 行）用不同尺寸的池化并联再拼接，
#    作用和"膨胀卷积"类似：不增加参数，扩大感受野。


# ============================================================
# 七、这一课要记住的三句
# ============================================================
# 1. 组卷积把通道分组，参数变成 1/g，代价是组间不交换信息。
#    g = C_in 时就是深度卷积，参数只剩 C_in × k × k。
#
# 2. 深度可分离 = 深度卷积 + 1×1 卷积，
#    把"空间滤波"和"通道混合"拆开做，参数省 85%~89%。
#
# 3. 1×1 卷积是轻量网络里最常用的工具：不改高宽，只改通道，
#    参数只有 C_in × C_out。

