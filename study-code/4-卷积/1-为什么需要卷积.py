# D01：为什么图片不能直接喂全连接层
#
# 【这一课解决什么问题】
#   你已经会用 Linear 搭网络了。图片不就是一堆数吗？
#   把 224×224 的图展平成一条向量，接一个 Linear，不就行了？
#
#   这一课算一笔账，说明这条路为什么走不通。
#   代码只有一处，全是算术。


# ============================================================
# 一、一张图片对模型来说是什么
# ============================================================
# 一张 224×224 的彩色图：
#   224 行 × 224 列 × 3 个通道（RGB）= 150,528 个数字
#
# 全连接层的要求是：每个输出都要和每个输入相连。
# 所以输入有多少个数，就要为"每个输出"准备那么多个权重。
#
# 这就是问题的起点。


# ============================================================
# 二、算一笔账
# ============================================================
import math

n_in = 224 * 224 * 3
print("=" * 60)
print("一、全连接层要多少参数")
print("输入数字个数 =", n_in)

for out in (10, 512, 1000):
    p = n_in * out
    print(f"  接到 {out:4d} 个输出 -> 参数 {p:,} 个，光权重就占 {p * 4 / 1024 / 1024:.1f} MB")

# 输出：
#   接到   10 个输出 -> 参数 1,505,280 个，5.7 MB
#   接到  512 个输出 -> 参数 77,070,336 个，294.0 MB
#   接到 1000 个输出 -> 参数 150,528,000 个，574.2 MB
#
# 注意：这只是一层。
# 一个能用的网络至少几层，参数会迅速涨到几亿、几十亿。


# ============================================================
# 三、真实世界的证据：VGG16
# ============================================================
# VGG16 是一个很有名的老网络（2014），它就是"卷积 + 大全连接"的典型。
#
# 它的卷积部分做完之后，特征图是 7×7×512，然后接三个全连接层：
#   FC1: 7×7×512 -> 4096
#   FC2: 4096    -> 4096
#   FC3: 4096    -> 1000
#
# 算一下这三层：

fc1 = 7 * 7 * 512 * 4096
fc2 = 4096 * 4096
fc3 = 4096 * 1000
total_fc = fc1 + fc2 + fc3

print()
print("=" * 60)
print("二、VGG16 的分类头")
print(f"  FC1: {fc1:,}")
print(f"  FC2: {fc2:,}")
print(f"  FC3: {fc3:,}")
print(f"  合计: {total_fc:,}")
print(f"  VGG16 总参数约 1.38 亿，这三层占了 {total_fc / 138e6 * 100:.1f}%")

# 输出：合计 123,633,664，占总参数的 89.6%
#
# 也就是说：VGG16 的全部卷积（提取特征、真正干活的部分）只用了 1400 万参数，
# 而最后三个"把特征变成分类结果"的全连接层，吃掉了 1.24 亿。
#
# 这是深度学习史上一个很经典的教训。
# 后来的网络（ResNet 之后）基本都把这几层废掉了，
# 换成一个几乎不要参数的操作（D06 会讲）。


# ============================================================
# 四、参数多还不是最要命的，三个更深的问题
# ============================================================
# ① 数据量跟不上
#
#   一个经验说法：每个参数至少要见到 1~10 个训练样本，才能学得靠谱。
#   1.5 亿参数 -> 需要十几亿张图。
#   ImageNet 也只有 120 万张。
#
#   参数比数据多太多，模型就只能死记硬背（过拟合）。
#
# ② 同一个东西，在不同位置要重新学一遍
#
#   一只猫的耳朵，可能出现在图片左上角，也可能在右下角。
#   全连接层对每个位置都有独立的权重：
#     耳朵在左上角 -> 一套权重学会了
#     耳朵在右下角 -> 另一套权重，要从头学
#
#   而真实世界的规律是："这个形状就是猫耳朵"，和它在哪无关。
#   全连接层没有这个先验，只能靠数据硬学。
#
# ③ 空间结构被拉坏了
#
#   展平之后，像素变成一条长向量：
#     [R00,G00,B00, R01,G01,B01, ..., R223,G223,B223]
#
#   于是"像素 (0,0)"和"像素 (0,1)"挨着（好），
#   但"像素 (0,223)"和"像素 (1,0)"也挨着（其实一个在右边缘、一个在下一行开头）。
#   模型没法从这条长向量里看出"谁和谁在图片里是邻居"。


# ============================================================
# 五、所以我们需要一种"更懂图片"的运算
# ============================================================
# 上面三个问题，其实都指向同一件事：
#   全连接层假设"每个输入和每个输出都有关系"，这个假设对图片太宽松了。
#
# 图片的真相是两条：
#
#   ① 局部性：判断一个像素周围发生了什么，只需要看它附近
#      （远处的像素基本不相干）
#
#   ② 规律处处相同：猫耳朵的形状，出现在哪里都是猫耳朵
#      -> 同一组权重应该在整张图上到处用
#
# 把这两条写进运算里，就是卷积。
# 下一课就讲卷积到底做了哪个运算，以及它怎么把参数从 1.5 亿压到几千。


# ============================================================
# 六、这一课你要会算的一笔账
# ============================================================
# 给一个输入形状和一个输出数量，算出全连接层的参数量：
#
#   参数 = 输入元素总数 × 输出数量
#
# 举例：
#   输入 150,528 个数，输出 1000 -> 150,528,000 个参数
#
# 等你学会卷积之后，再算同一件事：
#   输入 224×224×3，用 64 个 3×3 卷积核 ->
#   参数 = (3×3×3 + 1) × 64 = 1,792 个
#
# 从 1.5 亿到 1792，差了 8 万倍。
# 这个对比就是 D02 的全部内容。

