# D05：步长、填充，和输出尺寸公式
#
# 【这一课解决什么问题】
#   D02 的例子：3×3 输入配 2×2 核，输出变成 2×2 —— 变小了。
#   可很多网络里，卷积前后尺寸不变；也有些地方尺寸正好减半。
#
#   这一课给你一个公式，任何配置都能算出输出多大。
#   这个公式是读 YOLO 配置表的基本功：
#   以后看到 [64, 3, 2] 这种参数，你要立刻反应出"高宽减半、通道变 64"。


# ============================================================
# 一、为什么输出会变小
# ============================================================
# 核在图上滑，滑到边缘就得停下（不能滑出图外）。
# 3×3 的输入配 2×2 的核：
#
#   横向能放的位置：左(0)、右(1)  -> 2 个
#   纵向能放的位置：上(0)、下(1)  -> 2 个
#   所以输出 2×2
#
# 一般的说法：
#   不填充时，输出边长 = 输入边长 - 核边长 + 1
#   3 - 2 + 1 = 2  ✓
#
# 问题：如果每层都变小，堆十几层之后图就没了（224 -> ... -> 0）。
# 而且边缘像素被卷积的次数比中心少，信息利用不充分。


# ============================================================
# 二、填充（padding）：在边缘补 0
# ============================================================
# 做法：在图的四周各补一圈（或几圈）0。
#
#   3×3 的图，补 1 圈之后变成 5×5：
#
#     0  0  0  0  0
#     0  1  2  3  0
#     0  4  5  6  0
#     0  7  8  9  0
#     0  0  0  0  0
#
# 现在再用 2×2 的核滑：(5 - 2) + 1 = 4 -> 输出 4×4
# 如果补 1 圈、核 3×3：(5 - 3) + 1 = 3 -> 输出和输入一样大
#
# ★ 注意：padding=1 的意思是"每一边各补 1 圈"，不是"总共补 1 圈"。
#   所以尺寸会增加 2×padding。
#
# 补 0 的两个作用：
#   ① 保持尺寸，让网络能堆很多层
#   ② 让边缘像素也能被核"完整地"扫到，不浪费


# ============================================================
# 三、步长（stride）：每次滑多远
# ============================================================
# stride = 1：一格一格滑（默认）
# stride = 2：每次跳 2 格
#
#   输出边长大约是输入的一半，所以 stride=2 常用来"下采样"。
#
# 下采样的作用：
#   ① 减少计算量（尺寸减半，后面的计算量少 4 倍）
#   ② 扩大感受野（每个输出"看"的范围更大）
#   ③ 提供多尺度信息（YOLO 就是靠不同层级的特征图检测不同大小的物体）
#
# 注意 stride=2 不是"精确的除以 2"，而是靠公式算出来的，
# 奇数尺寸会有向下取整的偏差（第五节会看到）。


# ============================================================
# 四、输出尺寸公式（唯一要记的）
# ============================================================
#
#        输出边长 = ⌊ (输入边长 + 2×padding - 核边长) / stride ⌋ + 1
#
#   ⌊ ⌋ 表示向下取整
#
# 记这个公式的一个直观方式：
#   先算"核能放几个位置"：
#     - 补了 padding 之后，图变成 输入 + 2p
#     - 第一个位置占掉 k 格，剩下 输入+2p-k 格可以滑
#     - 每次滑 s 格，还能滑 (输入+2p-k)/s 次
#     - 加上第一个位置，就是 /s + 1
#
# 所以公式不是背出来的，是数出来的。

import torch
import torch.nn as nn

print("=" * 60)
print("一、公式和实测对照")


def out_size(h, k, p, s):
    return (h + 2 * p - k) // s + 1


cases = [
    (640, 3, 1, 1),   # 最常用：尺寸不变
    (640, 3, 1, 2),   # 减半
    (640, 3, 0, 1),   # 不填充：尺寸变小
    (640, 5, 2, 1),   # 5×5 核配 padding 2：尺寸不变
    (640, 2, 0, 2),   # 2×2 核步长 2：精确减半
    (28, 3, 1, 2),    # MNIST 尺寸减半：28 -> 14
    (13, 3, 1, 2),    # 奇数尺寸：13 -> 7
    (7, 3, 1, 2),     # 继续：7 -> 4
]

print(f"{'输入':>5} {'核':>3} {'填充':>5} {'步长':>5} {'公式':>6} {'实测':>6}")
for h, k, p, s in cases:
    conv = nn.Conv2d(1, 1, k, stride=s, padding=p)
    real = conv(torch.zeros(1, 1, h, h)).shape[-1]
    print(f"{h:>5} {k:>3} {p:>5} {s:>5} {out_size(h, k, p, s):>6} {real:>6}")

# 输出：
#   输入   核  填充  步长   公式   实测
#    640   3    1    1    640    640
#    640   3    1    2    320    320
#    640   3    0    1    638    638
#    640   5    2    1    640    640
#    640   2    0    2    320    320
#     28   3    1    2     14     14
#     13   3    1    2      7      7
#      7   3    1    2      4      4
#
# 注意 13 -> 7：13 除以 2 应该是 6.5，向下取整加 1 得 7。
# 所以"减半"在奇数尺寸上不是精确的，会多留一格。
# 这就是为什么很多网络输入尺寸都选 32 的倍数（32、64、640）。


# ============================================================
# 五、三种最常见的配置
# ============================================================
# ① k=3, p=1, s=1    尺寸不变
#    这是绝大多数"提特征"的层用的配置。
#    为什么 p=1？因为 (3-1)/2 = 1，补一圈正好让 3×3 卷积不改变尺寸。
#
# ② k=3, p=1, s=2    尺寸减半
#    用来下采样。比池化更"有条件"（池化只是取最大/平均）。
#
# ③ k=1, p=0, s=1    尺寸不变，只改通道数
#    1×1 卷积看不到邻域，只做"跨通道的加权组合"。
#    用途：把通道从 512 压到 128，或者放大通道。
#    参数量只有 C_in × C_out。


# ============================================================
# 六、1×1 卷积：不改空间，只改通道
# ============================================================
print()
print("=" * 60)
print("二、1x1 卷积")

c11 = nn.Conv2d(64, 32, 1)
x = torch.zeros(1, 64, 40, 40)
print("输入", tuple(x.shape), "-> 输出", tuple(c11(x).shape))
print("参数量 =", sum(p.numel() for p in c11.parameters()),
      " (64×32+32 =", 64 * 32 + 32, ")")

# 输出：
#   输入 (1, 64, 40, 40) -> 输出 (1, 32, 40, 40)
#   参数量 2080
#
# 高宽一点没变，通道从 64 变成 32。
# 它的作用是"把 64 个特征图线性组合成 32 个"，
# 常用于降维、融合不同通道之间的信息。
# 代价很低（2080 个参数），所以网络里到处在用。


# ============================================================
# 七、读懂 YOLO 配置里的写法
# ============================================================
# yolo26.yaml 里一层长这样（简化）：
#
#   [-1, 1, Conv, [64, 3, 2]]
#          ↑        ↑   ↑ ↑
#       层类型    通道 核 步长
#
# 翻译成人话：
#   输入连到上一层（-1），重复 1 次，用 Conv 模块，
#   输出 64 通道、3×3 核、步长 2（padding 在代码里按核自动算）
#
# 效果：
#   通道 C_in -> 64
#   高宽 -> 减半（因为 stride=2、k=3、p=1）
#
# 另一层可能是：
#   [-1, 1, Conv, [128, 3, 1]]     尺寸不变，通道变 128
#   [-1, 1, Conv, [256, 1, 1]]     尺寸不变，通道变 256（1×1 卷积）
#
# 看到这三个数，你就能立刻推出"这一层出来是多大"——
# 这正是 D08 要带着你做的整张表。


# ============================================================
# 八、这一课要记住的三句
# ============================================================
# 1. 输出边长 = ⌊(输入 + 2×padding - 核) / stride⌋ + 1
#    这个公式是数位置数出来的，不是背的。
#
# 2. padding 是"每边各补几圈"，所以尺寸加 2×padding。
#    k=3、p=1 时尺寸不变；s=2 时尺寸减半。
#
# 3. 1×1 卷积不改高宽，只改通道，参数量只有 C_in × C_out，
#    是网络里最常用的"通道变换"工具。

