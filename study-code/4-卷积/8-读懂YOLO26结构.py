# ============================================================
# 四、三个可以手算验证的地方
# ============================================================
# 【验证 1】第一层的 464 个参数
#
#   Ultralytics 的 Conv 模块 = 卷积 + BatchNorm + 激活
#   卷积不带偏置（偏置由 BN 吸收），所以：
#
#     卷积权重 = k × k × C_in × C_out = 3 × 3 × 3 × 16 = 432
#     BN 参数  = 每通道 2 个（缩放 + 偏置）= 16 × 2 = 32
#     合计     = 464   ✓
#
#   公式：Conv 参数 = k^2 × C_in × C_out + 2 × C_out
#
#   验算第 3 层（64 → 64）：
#     9 × 64 × 64 + 2 × 64 = 36,864 + 128 = 36,992   ✓
#
#   验算第 5 层（128 → 128）：
#     9 × 128 × 128 + 256 = 147,456 + 256 = 147,712   ✓
#
# 【验证 2】Concat 的通道数
#
#   Concat 是"沿通道拼接"，把两层的通道数加起来：
#     第 12 层：上一层 256 通道 + 第 6 层 128 通道 = 384   ✓
#     第 15 层：上一层 128 + 第 4 层 128 = 256            ✓
#     第 18 层：上一层  64 + 第 13 层 128 = 192           ✓
#     第 21 层：上一层 128 + 第 10 层 256 = 384           ✓
#
# 【验证 3】Detect 的 8400
#
#   三个尺度输出的空间位置数：
#     80 × 80 = 6400
#     40 × 40 = 1600
#     20 × 20 =  400
#     ------------------
#     合计     8400   ✓
#
#   84 = 4 个框参数 + 80 个类别。
#   所以输出形状 (84, 8400)：每个位置一个预测，
#   一共 8400 个位置，每个位置 84 个数。


# ============================================================
# 五、head 在干什么：三步一个循环
# ============================================================
# 看第 11~22 层，有一个很规律的循环：
#
#   上采样 -> 拼接 -> C3k2   （提取小物体特征）
#   上采样 -> 拼接 -> C3k2   （更小的物体）
#   下采样 -> 拼接 -> C3k2   （开始往回收）
#   下采样 -> 拼接 -> C3k2
#
# 这就是 FPN + PAN 结构，作用是"特征融合"：
#
#   ① 上采样阶段（自顶向下）
#      P5 的特征图很小但"看得远"（感受野大，语义强）
#      放大之后和 P4 拼接，让 P4 也带上"全局"信息
#      继续放大和 P3 拼接
#
#   ② 下采样阶段（自底向上）
#      P3 的特征图大、细节多，但"看得近"
#      缩小之后和 P4、P5 拼接，让大尺度也带上细节
#
#   为什么要融合？
#     大物体需要"语义强"的特征（深层），
#     小物体需要"分辨率高"的特征（浅层）。
#     融合之后，每个尺度都同时有语义和细节。
#
#   Upsample 用 nearest（最近邻），最省算力，只是把图放大。
#   Concat 沿通道拼接，不改变高宽，只增加通道数。


# ============================================================
# 六、三尺度检测：P3 / P4 / P5
# ============================================================
#   P3: 第 16 层，80×80，步长 8    -> 检测小物体
#   P4: 第 19 层，40×40，步长 16   -> 检测中等物体
#   P5: 第 22 层，20×20，步长 32   -> 检测大物体
#
# 为什么必须三个尺度？
#   如果只用 P5（20×20），一个格子在原图上对应 32×32 像素，
#   比这更小的物体根本占不满一个格子，检不出来。
#   而 P3 的一个格子只对应 8×8 像素，小物体也能占几个格子。
#
# yaml 最后一行 [-1, 1, Detect, [nc]] 里的 nc 是类别数（默认 80），
# 而 Detect 实际接收的三层输入，是 [16, 19, 22]。
# 这行 yaml 写的是 [nc]，是因为 parser 会自动补上那三个层的索引。


