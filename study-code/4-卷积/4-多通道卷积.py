# D04：多通道卷积
#
# 【这一课解决什么问题】
#   前面的例子都是"1 通道进、1 通道出"。
#   可真实图片是 3 通道（RGB），而且我们希望同时检测很多种模式。
#
#   所以实际的一层卷积长这样：
#     输入 3 通道  ->  输出 64 通道
#
#   这一课讲清楚：多出来的通道是哪来的、每个通道在算什么、参数怎么变。


# ============================================================
# 一、为什么输出要有多个通道
# ============================================================
# 一个 3×3 的核能检测一种模式（比如"左暗右亮的竖边"）。
# 如果图片里还有横边、斜边、圆角、颜色梯度……一个核不够用。
#
# 于是同时用很多个核：
#   核 1 -> 检测竖边   -> 输出通道 1
#   核 2 -> 检测横边   -> 输出通道 2
#   核 3 -> 检测斜边   -> 输出通道 3
#   ...
#   核 64 -> 检测第 64 种模式 -> 输出通道 64
#
# 所以"输出 64 通道"的意思就是：这一层用了 64 个不同的核，
# 每个核各自产出一张响应图，摞成一摞。
#
# 通道数 = 这一层用了几种模式（这是人设计的，训练学它具体是什么模式）。


# ============================================================
# 二、输入有多个通道怎么办
# ============================================================
# 这是最容易搞混的地方。
#
# 假设输入 2 个通道（比如灰度图 + 边缘图），要输出 1 个通道。
# 做法是：每个输入通道各配一个核，分别卷积，然后把结果相加。
#
#   输出 = 卷积(通道1, 核1) + 卷积(通道2, 核2) + 偏置
#
# 手算验证一下：

import torch
import torch.nn as nn

c1 = torch.zeros(3, 3); c1[0, 0] = 1.0      # 通道1：左上角有个 1
c2 = torch.zeros(3, 3); c2[2, 2] = 4.0      # 通道2：右下角有个 4
x = torch.stack([c1, c2])[None]             # 拼成 [1, 2, 3, 3]

k = torch.zeros(1, 2, 2, 2)
k[0, 0] = torch.tensor([[1.0, 0.0], [0.0, 0.0]])     # 通道1 的核：只看左上
k[0, 1] = torch.tensor([[0.0, 0.0], [0.0, 1.0]])     # 通道2 的核：只看右下

conv = nn.Conv2d(2, 1, 2, bias=False)
with torch.no_grad():
    conv.weight.copy_(k)

print("=" * 60)
print("一、2 通道输入 -> 1 通道输出")
print("通道1（左上角是 1）:")
print(c1)
print("通道2（右下角是 4）:")
print(c2)
print("输出:")
print(conv(x)[0, 0].detach())

# 输出：
#   [[1, 0],
#    [0, 4]]
#
# 左上角的 1 来自通道1（用它的核扫出来的）
# 右下角的 4 来自通道2（用它的核扫出来的）
#
# 也就是说：两个通道的信息被"加"进了同一个输出通道。
# 输出通道看到的是"所有输入通道的加权组合"，不是某一个通道。


# ============================================================
# 三、完整的计算规则
# ============================================================
# 一层卷积的完整描述：
#
#   输入：C_in 个通道
#   输出：C_out 个通道
#   核：  k × k
#
# 权重张量的形状是 [C_out, C_in, k, k]，可以这样读：
#
#   [ 64,        3,      3,  3 ]
#     ↑          ↑       ↑   ↑
#   输出通道  输入通道   核高 核宽
#
# 意思是：有 64 个输出通道；每一个输出通道，都要对 3 个输入通道
#         各准备一个 3×3 的核，把它们的结果相加。
#
# 所以每个输出通道有 3×3×3 = 27 个权重 + 1 个偏置 = 28 个，
# 64 个输出通道 -> 28 × 64 = 1792 个参数。


# ============================================================
# 四、参数量公式
# ============================================================
#        参数 = (C_in × k × k + 1) × C_out
#
#                  └──────┬─────┘   └┬┘
#                   每个输出通道的权重 偏置
#
# print 出来核对一下：

print()
print("=" * 60)
print("二、几个常见配置的参数量")

for c_in, c_out, kk in [(3, 16, 3), (3, 64, 3), (64, 128, 3), (128, 128, 3)]:
    layer = nn.Conv2d(c_in, c_out, kk)
    real = sum(p.numel() for p in layer.parameters())
    formula = (c_in * kk * kk + 1) * c_out
    print(f"  {c_in:3d} -> {c_out:3d} 核 {kk}x{kk} : 实际 {real:6d}  公式 {formula:6d}"
          f"  权重形状 {tuple(layer.weight.shape)}")

# 输出：
#     3 ->  16 核 3x3 : 实际    448  公式    448
#     3 ->  64 核 3x3 : 实际   1792  公式   1792
#    64 -> 128 核 3x3 : 实际  73856  公式  73856
#   128 -> 128 核 3x3 : 实际 147584  公式 147584
#
# 注意最后两个：通道数只翻了一倍，参数却翻了四倍。
# 因为参数量是 C_in × C_out 的乘积关系。
#
# 这就是为什么深层网络的通道数不能随便加：
#   两个 128 通道的层相连，一层就 14.7 万参数。


# ============================================================
# 五、输出形状怎么变
# ============================================================
# 输入形状：[B, C_in, H, W]
# 输出形状：[B, C_out, H_out, W_out]
#
#   通道维：C_in 变成 C_out（由这一层用几个核决定）
#   高宽：由核大小、步长、填充决定（D05 讲）
#
# 一个关键点：
#   通道数和高宽是两件独立的事。
#   通道数（"用几种模式"）是本层自己定的；
#   高宽（"特征图多细"）取决于你怎么滑。
#
# 举个 YOLO 里常见的配置：
#   输入 [1, 3, 640, 640]
#   Conv 64 通道、3×3 核、步长 2
#   -> 输出 [1, 64, 320, 320]
#
#   通道 3 -> 64（用了 64 个核）
#   高宽 640 -> 320（步长 2，减半）


# ============================================================
# 六、每张"特征图"是什么
# ============================================================
# 输出 64 个通道 = 64 张图，每张图记录"某种模式在图里哪些位置出现了"。
#
# 举例（一个训练好的网络）：
#   通道 3  可能是"竖直边缘"的响应图
#   通道 17 可能是"某种颜色块"的响应图
#   通道 40 可能是"圆形"的响应图
#
# 这些模式不是人指定的，是训练学出来的。
# 训练的过程，就是不断调整这 64×3×3×3 个权重，
# 让它们各自变成"对分类有用"的检测器。
#
# 越往后的层，通道数越多，检测的"模式"越抽象：
#   浅层  -> 边缘、颜色、纹理
#   中层  -> 部件（眼睛、轮子、窗户）
#   深层  -> 整个物体（猫、车、人）


# ============================================================
# 七、这一课要记住的三句
# ============================================================
# 1. 输出通道数 = 这一层用了几个核 = 检测几种模式。
#
# 2. 每个输出通道会把"所有输入通道"都卷一遍再相加，
#    所以权重形状是 [C_out, C_in, k, k]。
#
# 3. 参数 = (C_in × k × k + 1) × C_out。
#    通道数翻倍，参数翻四倍（因为 C_in × C_out 是乘积）。

