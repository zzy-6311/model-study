# F04：性能怎么公平地测
#
# 【这一课解决什么问题】"我的模型 8 ms" —— 这句话为什么几乎没意义？
#   因为同一个模型，换一种测法能测出 5 个不同的数。
#   这一课讲清楚：要报哪几个数、哪些条件必须写死、看哪个分位数。


# ============================================================
# 一、同一个模型，五个不同的数
# ============================================================
# 实测（YOLO26n / 640×640 / batch=1 / RTX 4060）：
#
#   第一次调用          329.0 ms     <- 冷启动
#   预热后单次           17.2 ms
#   200 次的平均         19.9 ms
#   200 次的 P50         16.4 ms
#   200 次的 P95         38.6 ms
#   200 次的最大值       45.1 ms
#
# ★ 从 16 ms 到 329 ms，全是"这个模型的耗时"。
#   所以不写清条件、不写清统计方式，"8 ms" 这个数毫无意义。


# ============================================================
# 二、冷启动为什么贵 20 倍
# ============================================================
#   第一次调用要做这些事：
#     - 初始化 CUDA 上下文（几百 MB）
#     · cudnn 为每个卷积挑最快算法（要试算几次）
#     · 第一次分配显存，初始化内存池
#     · 加载权重到显存
#
#   之后就复用，所以稳态快得多。
#
# ★ 服务端必须预热：启动后先空跑几次，
#   否则第一个真实用户的请求要等 300+ ms。


# ============================================================
# 三、为什么要看 P95，不看平均
# ============================================================
#   实测分布：
#     P50  16.4 ms    一半请求比这快
#     P95  38.6 ms    5% 的请求比这慢
#     平均 19.9 ms
#
#   平均 19.9 看起来还行，但**"5% 的请求超过 38 ms"**才是用户真实感受。
#
#   平均值的坏处：少数很慢的请求会被大量快的请求稀释掉。
#   比如 95 个 16ms + 5 个 200ms，平均只有 25ms，但体验是"时不时卡一下"。
#
#   所以延迟类指标一定要报分位数：
#     实时系统看 P95 或 P99
#     离线批处理看吞吐（张/秒）就够


# ============================================================
# 四、测之前必须固定的六件事
# ============================================================
#   ① 设备          哪张显卡/哪个 CPU，有没有其他程序在跑
#   ② batch         1 和 8 完全不是一个量级
#   ③ 分辨率        640 和 320 差 2 倍以上（F03 实测）
#   ④ 精度          FP32 还是 FP16/INT8
#   ⑤ 线程数        推理引擎开几个线程（ORT 的 intra_op_num_threads）
#   ⑥ 是否预热      预热几次
#
# ★ 报告里缺任何一项，别人都没法复现你的数，也没法比较。


# ============================================================
# 五、真正要优化的是"端到端"，不是"模型"
# ============================================================
# 一次完整的图片检测不止"推理"这一段：
#
#   读文件 + 解码   打开 jpg、解成像素矩阵
#   预处理          resize + 归一化 + HWC->CHW + 转张量
#   推理            模型前向
#   后处理          NMS、分数过滤、坐标逆变换
#
# 实测单张（1280×720 的图）：
#   预处理（resize + 归一化 + HWC->CHW）   11.6 ms
#     其中纯 resize                          7.6 ms
#   推理（P50）                            16.4 ms
#
# ★ 预处理和推理是同一个量级。
#   所以"模型只用了 16 ms"不等于"系统响应 16 ms"，
#   实际端到端可能是 30~40 ms。


# ============================================================
# 六、CUDA 异步：测不准的头号原因
# ============================================================
# CUDA 调用是异步的：Python 发完指令就返回，
# 真正的计算还在 GPU 队列里。
#
#   错：t0=time(); m(x); print(time()-t0)      测到的是"发指令的时间"
#   对：t0=time(); m(x); torch.cuda.synchronize(); print(time()-t0)
#
# 更准的写法是用 CUDA 事件：
#   start = torch.cuda.Event(True); end = torch.cuda.Event(True)
#   start.record(); ...; end.record(); torch.cuda.synchronize()
#   end.elapsed_time(start)     # 直接给毫秒
#
# ★ 这个坑在 E08 提过，测性能时天天遇到。


# ============================================================
# 七、一份能用的性能报告长什么样
# ============================================================
#   device      RTX 4060 Laptop 8GB / i9-13900HX
#   model       YOLO26n, ONNX Runtime 1.31.1 CPU / or PyTorch 2.9.1 CUDA
#   input       640×640, batch=1, FP32
#   warmup      10 次
#   measure     200 次
#   latency     P50 16.4 ms / P95 38.6 ms
#   throughput  约 50 张/秒（batch=1）
#
# ★ 报"P50 + P95"两个数，比报平均值有用得多。
#   如果再按"批处理"测一轮，把吞吐也报上，就更完整了。


# ============================================================
# 八、这一课要记住的三句
# ============================================================
# 1. 同一个模型能测出 16ms 到 329ms 五个不同的数。
#    不写清条件、不写清统计方式，性能数字没有意义。
#
# 2. 看 P95，不看平均值。平均值会把"偶尔卡一下"稀释掉。
#
# 3. 端到端才是用户感受。预处理和推理往往是同一量级，
#    只优化模型可能只优化了其中的一半。

