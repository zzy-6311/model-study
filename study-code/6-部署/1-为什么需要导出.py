# F01：为什么部署要换一个引擎
#
# 【这一课解决什么问题】
#   模型训练好了，存在一个 .pth 里。能不能直接拿去用？
#
#   在你自己电脑上可以。但要交给别人、放到手机、放到嵌入式板子上、
#   或者要求更快——"带一整套 PyTorch"就不现实了。
#
#   这一课讲清楚：导出到底做了什么，以及它会改变什么。


# ============================================================
 # ============================================================
# ① 目标机器没有 PyTorch
#    PyTorch 装完要好几个 GB（你这台机器上就有）。
#    手机 App、单片机、车载盒子，装不下也不该装。
#
# ② 想更快、更省
#    PyTorch 是为"灵活"设计的：动态建图、支持任意 Python 控制流。
#    推理时这些能力用不上，反而带来开销。
#    专门的推理引擎可以把图优化（算子融合、常量折叠、量化），更快更省。
#
# ③ 需要跨语言
#    C++ 程序、C# 上位机、Web 前端，都想调这个模型。
#
# ★ 共同点：**推理只需要"算"，不需要"改"。**
#   训练要的是梯度、反向图、参数更新；
#   推理只要一次前向。


# ============================================================
# 二、导出的本质：动态图 -> 静态图
# ============================================================
#   训练时：PyTorch 是"边跑边建图"。
#           每个 batch 都重新记一遍，图上带着梯度信息，
#           还能有 if / for 这种 Python 控制流。
#
#   导出时：把这一张图"固化"下来——
#           去掉梯度、把参数当常量、把每个操作换成一个标准算子。
#
# 固化出来的东西，叫**计算图（computational graph）**。
# 它不含 Python 代码，只含"算子 + 连接关系 + 权重"。
#
#   算子就是 Conv、Relu、Add、MaxPool 这种标准操作。
#   任何推理引擎都实现了这些算子，所以能脱离 PyTorch 跑。
#
# ★ 一句话：导出 = 把你的 Python 代码，翻译成一张"算子清单"。


# ============================================================
# 三、实测：导出来的图长什么样
# ============================================================
# 造一个小 CNN，然后导出成 ONNX（一种通用的计算图格式）。

import os

import torch
import torch.nn as nn

model = nn.Sequential(
    nn.Conv2d(3, 8, 3, padding=1),
    nn.BatchNorm2d(8),
    nn.ReLU(),
    nn.MaxPool2d(2),
    nn.Flatten(),
    nn.Linear(8 * 16 * 16, 10),
).eval()

x = torch.randn(1, 3, 32, 32)
path = os.path.join(os.environ.get("TEMP", "."), "demo.onnx")

with torch.no_grad():
    torch.onnx.export(
        model, x, path,
        dynamo=False,            # 用传统导出路径（新版默认需要 onnxscript）
        opset_version=17,
        input_names=["images"],
        output_names=["logits"],
    )

print("=" * 60)
print("一、导出结果")
print("文件大小 =", os.path.getsize(path), "字节",
      "（约", round(os.path.getsize(path) / 1024), "KB）")

import onnx

graph = onnx.load(path).graph
print("图里的节点数 =", len(graph.node))
print("节点类型 =", [n.op_type for n in graph.node])

# 输出：
#   文件大小 = 83621 字节（约 82 KB）
#   节点数 = 5
#   节点类型 = ['Conv', 'Relu', 'MaxPool', 'Flatten', 'Gemm']
#
# ★ 注意：代码里有 6 层，图里只有 5 个节点。
#   **BatchNorm 消失了。**
#
#   为什么？因为 BN 在推理时是一个"固定的线性变换"：
#     y = gamma × (x - mean) / sqrt(var + eps) + beta
#   其中 gamma、mean、var、beta 全是训练时定下来的常数。
#   所以它可以被**折进前面那个卷积**：
#     新权重 W' = W × gamma / sqrt(var + eps)
#     新偏置 b' = (b - mean) × gamma / sqrt(var + eps) + beta
#
#   折完之后，卷积和 BN 变成了一个卷积。参数不变多，计算少了一次。
#   这叫"算子融合"，是导出时自动做的优化。
#
#   ★ 这也解释了一件事：为什么训练和推理必须分开（C07）。
#     训练时 BN 用的是当前批次的统计量，不能折；
#     推理时用固定的 running 统计量，才能折。


# ============================================================
# 四、文件大小 = 参数量 × 4 字节
# ============================================================
#   卷积  3->8, 3x3 : 8×3×9 + 8 = 224
#   BN 的 gamma/beta : 16（会被折掉，但训练时存在）
#   全连接 2048->10  : 2048×10 + 10 = 20,490
#   ----------------------------------
#   合计约 20,700 个参数
#
#   20,700 × 4 字节 = 82,800 字节 —— 和实测的 83,621 几乎一致。
#
#   ★ ONNX 文件里基本就是"权重 + 一点图结构描述"。
#     所以文件大小 ≈ 参数量 × 4 字节。
#     YOLO26n 是 2.57M 参数，ONNX 文件大约 10 MB。


# ============================================================
# 五、导出之后，契约必须写死
# ============================================================
# 图里只记录"输入的形状和类型"，不记录"这个数是怎么来的"。
# 所以下面这些必须在代码里、文档里明确写下来：
#
#   项目          例子                写错的后果
#   ------------------------------------------------------
#   输入形状      [1, 3, 640, 640]    模型按别的尺寸训练，结果全错
#   通道顺序      RGB（不是 BGR）     把红当蓝，准确率掉一截
#   取值范围      0~1（除以 255）     忘了除，输入是 0~255，输出垃圾
#   归一化        mean/std 数值       少做或多做一步，结果偏
#   输出含义      logits / 概率       拿 logits 当概率用，阈值全错
#   类别顺序      {0: 猫, 1: 狗}      标签对不上，输出"猫"显示成"狗"
#
# ★ 这就是"推理输入输出契约"。C03 讲的那份预处理约定，
#   在这里变成了一份必须交付的文档。
#   模型文件本身永远不含这些信息。


# ============================================================
# 六、导出会改变什么、不会改变什么
# ============================================================
#   不会改变：数学上算的是同一个函数
#   会改变：
#     ① 没有梯度了（推理不需要）
#     ② 没有动态控制流了（if/for 必须能静态展开）
#     ③ 有些算子被融合了（Conv+BN）
#     ④ 数值可能有微小差异（不同引擎的实现细节）
#
# ★ 第 ③ 条是好事（更快），第 ④ 条要注意——
#   导出的模型和你 PyTorch 里的输出**不会逐位相同**，
#   需要验证"差多少算正常"（F04 讲）。


# ============================================================
# 七、这一课要记住的三句
# ============================================================
# 1. 导出 = 把"代码 + 权重"固化成"算子图 + 权重"。
#    脱掉 Python，推理才可能跑在别人的机器上。
#
# 2. BatchNorm 会被折进卷积（算子融合），所以图里的层数会比代码里少。
#
# 3. 模型文件里只有图和权重，**没有预处理和类别信息**。
#    这些必须由你写成契约，否则推理一定出错。

