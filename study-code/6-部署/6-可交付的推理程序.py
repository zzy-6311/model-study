# F06：一个能交付的推理程序
#
# 【这一课解决什么问题】
#   代码在你机器上跑通了，模型文件也导出了。
#   把它交给别人（或者一个月后的自己），还能不能复现出一样的结果？
#
#   多数情况下不能。原因是"模型文件里只有权重"，而正确使用它
#   需要另外一堆信息，这些信息不在文件里，只在你的脑子里。
#
#   这一课讲清楚：交付到底要交什么。


# ============================================================
# 一、"能跑"和"能交付"的区别
# ============================================================
#   能跑：你现在在 IDE 里按一下运行，出结果了
#   能交付：别人拿到一个文件夹，不看你的代码，也能得到同样的结果
#
# 差距在五个地方：
#
#   ① 预处理参数写在代码里，没写进文档
#   ② 依赖版本没记录，换台机器就装不出版本对的库
#   ③ 没有固定样例，谁也没法验证"结果一样"
#   ④ 输入不合法时直接崩溃，没有提示
#   ⑤ 不知道这个模型在什么情况下会失效


# ============================================================
# 二、交付物清单（缺一项就不算交付）
# ============================================================
#   ┌─────────────────────────────────────────────┐
#   │  1. 模型文件        model.onnx              │
#   │  2. 推理脚本        predict.py              │
#   │  3. 契约卡          README（下一节有模板）   │
#   │  4. 固定样例        sample.jpg + 期望输出    │
#   │  5. 依赖清单        requirements.txt        │
#   │  6. 已知限制        写清楚什么情况下不准     │
#   └─────────────────────────────────────────────┘
#
# ★ 其中"固定样例"最容易被省略，但它是最有价值的：
#   它是唯一能证明"你交付的东西和你说的一致"的证据。
#   别人跑出来和你不一样，第一件事就是拿固定样例对。


# ============================================================
# 三、契约卡：把模型文件里没有的信息写下来
# ============================================================
# 以 YOLO26n（D08 那个）为例，一张合格的契约卡长这样：
#
#   ------------------------------------------------------------
#   模型      YOLO26n, Ultralytics 8.4.204
#   文件      yolo26n.onnx (约 10 MB)
#
#   输入
#     形状    [1, 3, 640, 640]   （NCHW）
#     通道    RGB（不是 BGR）
#     取值    0~1（像素 / 255.0）
#     归一化  无（YOLO 用的是 /255，不做 mean/std）
#     尺寸    必须是 32 的倍数；用 LetterBox 把任意图变成 640×640
#
#   输出
#     形状    [1, 84, 8400]
#              84  = 4 个框参数 + 80 个类别分数
#              8400 = 80×80 + 40×40 + 20×20（三个尺度的位置数）
#     含义    logits，不是概率；需要 sigmoid 才能当置信度
#
#   后处理
#     置信度阈值   0.25（可调）
#     NMS IoU      0.45（可调）
#     坐标还原     先减 padding、再除以缩放比，回到原图坐标系
#
#   类别
#     0: person  1: bicycle  2: car ...（附完整列表）
#     顺序错了会把"猫"显示成"狗"
#
#   已知限制
#     小目标（小于 32×32 像素）容易漏检
#     极端长宽比的图（超过 4:1）补边后有效分辨率低
#     夜间/低照度图片未经训练，效果未知
#   ------------------------------------------------------------
#
# ★ 注意这几项都不是"可选的说明"，而是**用错就一定出错**的参数：
#   通道顺序错了 -> 颜色全反
#   少了 /255    -> 输入是 0~255，模型看到的是"过曝"的图
#   少了 sigmoid -> 阈值判断全错
#   类别顺序错   -> 结果张冠李戴


# ============================================================
# 四、固定样例：交付里最硬的证据
# ============================================================
# 做法：
#   准备 1~3 张有代表性的图（正常图、多目标图、空图）
#   记录：输入文件的哈希、输出的完整数值（或摘要）、
#         后处理之后的前几个框（坐标、分数、类别）
#
# 别人拿到之后：
#   跑同样的图 -> 比输出的前几位 -> 一致就说明环境对了
#
# ★ 为什么不用"看图片上的框画得对不对"来验证？
#   因为人眼分辨不出 0.01 的坐标差异，也看不出分数从 0.83 变成 0.79。
#   数值对比才能发现"预处理少了一步"这种问题。


# ============================================================
# 五、输入检查：崩之前先给人话
# ============================================================
# 好程序和不合格程序的区别，全在这里：
#
#   不合格：FileNotFoundError，或者更糟——读进来一张灰度图，
#           广播成三通道，跑完结果全错，一声不吭
#
#   合格：
#     路径不存在        -> "找不到图片: xxx.jpg"
#     通道数不对        -> "需要 3 通道 RGB，收到 1 通道灰度图"
#     尺寸不是 32 倍数  -> "输入 1000x1000 不是 32 的倍数，已自动补到 1024"
#     图片太大          -> "图片 8000x6000，缩放后小目标可能丢失"
#
# ★ 原则：**能自动修复的就修复并告知，不能修复的给出明确原因。**
#   不要静默地"尽力而为"，那是 bug 的温床。


# ============================================================
# 六、三个最常见的交付事故
# ============================================================
#  事故                          原因                预防
#  ------------------------------------------------------------
#  换台机器结果不一样            预处理没写进文档     契约卡 + 固定样例
#  装不上/版本冲突               没记依赖版本         requirements.txt
#  一喂奇怪输入就崩               没做输入检查         显式校验 + 人话报错
#
# 还有一个隐形的：
#   训练时用的是 BGR（OpenCV 读的），推理时用 RGB（PIL 读的），
#   结果准确率掉一截，但没人知道为什么。
#   -> 契约卡里"通道顺序"这一行就是防这个的。


# ============================================================
# 七、这一课要记住的三句
# ============================================================
# 1. 模型文件里只有图和权重。预处理、类别、阈值这些"用法"，
#    必须另外写成契约，否则换个环境一定出错。
#
# 2. 固定样例 + 期望输出，是验证"你交付的和你说的一致"的唯一证据。
#
# 3. 输入检查的原则：能修的修好并告知，不能修的明确说原因，
#    不要静默地"尽力而为"。

