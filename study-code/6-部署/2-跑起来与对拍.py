# F02：跑起来，然后对拍
#
# 【这一课解决什么问题】
#   导出的文件能加载、能跑通，输出也是 10 个数。
#   但这 10 个数对不对？
#
#   "跑通了"和"算对了"是两件事。这一课做对拍：
#   同一个输入，PyTorch 和 ONNX Runtime 各算一遍，比差多少。


# ============================================================
# 一、引擎执行的三步
# ============================================================
#   ① 创建 session：把 ONNX 文件加载进来，做图优化、分配内存
#      （这一步比较慢，所以生产环境只做一次，不是每次推理都建）
#
#   ② 准备输入：一个"名字 -> 数组"的字典
#      名字必须和导出时写的一致（这里是 "images"）
#      数组必须是 numpy，dtype 和形状也要对上
#
#   ③ 跑一次：sess.run(["输出名"], {输入名: 数组})
#      返回的是一个列表（因为可能有多个输出）
#
# ★ 注意：ORT 吃的是 numpy 数组，不是 PyTorch 张量。
#   所以路径是：PyTorch 张量 -> .numpy() -> ORT -> numpy 结果。


# ============================================================
# 二、实测：差多少
# ============================================================

import os

import numpy as np
import torch
import torch.nn as nn
import onnxruntime as ort

torch.manual_seed(0)

model = nn.Sequential(
    nn.Conv2d(3, 16, 3, padding=1), nn.BatchNorm2d(16), nn.ReLU(),
    nn.MaxPool2d(2),
    nn.Conv2d(16, 32, 3, padding=1), nn.BatchNorm2d(32), nn.ReLU(),
    nn.AdaptiveAvgPool2d(1), nn.Flatten(),
    nn.Linear(32, 10),
).eval()

x = torch.randn(4, 3, 32, 32)
path = os.path.join(os.environ.get("TEMP", "."), "f02.onnx")

with torch.no_grad():
    torch.onnx.export(model, x, path, dynamo=False, opset_version=17,
                      input_names=["images"], output_names=["logits"])
    ref = model(x).numpy()                      # PyTorch 的结果，作为参考

sess = ort.InferenceSession(path, providers=["CPUExecutionProvider"])
out = sess.run(["logits"], {"images": x.numpy()})[0]

print("=" * 60)
print("一、对拍结果")
print("PyTorch 前 5 个:", [round(float(v), 6) for v in ref[0][:5]])
print("ORT     前 5 个:", [round(float(v), 6) for v in out[0][:5]])

diff = np.abs(ref - out)
print()
print("最大绝对误差 =", f"{diff.max():.3e}")
print("平均绝对误差 =", f"{diff.mean():.3e}")
print("相对误差     =", f"{diff.max() / np.abs(ref).max():.3e}")
print("argmax 全一致？", (ref.argmax(1) == out.argmax(1)).all())

# 输出：
#   最大绝对误差 = 4.470e-08
#   平均绝对误差 = 1.304e-08
#   相对误差     = 1.878e-07
#   argmax 全一致？ True
#
# ★ 4.47e-08 这个量级意味着什么？
#   float32 能表示的相对精度大约是 1.2e-07。
#   误差正好在这个量级 —— 说明两个引擎算的是**同一个数学函数**，
#   差别只来自"浮点加法的顺序"。


# ============================================================
# 三、为什么不是 0（四个来源）
# ============================================================
# ① 算子融合改变了计算顺序
#    PyTorch 里是：卷积 -> (减均值、除标准差、乘 gamma、加 beta)
#    导出后是：用折好的新权重做一次卷积
#    数学等价，但浮点运算的次数和顺序都变了 -> 最后几位不同
#
# ② 卷积算法不同
#    引擎会挑最适合当前尺寸和硬件的实现：
#    直接法、Winograd、FFT……不同算法的累加顺序不同。
#
# ③ 多线程累加
#    一个卷积要加几百上千项，多线程分块并行，
#    合并顺序不同 -> 结果差最后几位。
#
# ④ 指令集与向量化
#    AVX、FMA 之类的指令会改变舍入方式。
#
# ★ 这四个来源都无法消除，只能判断"差得是否合理"。


# ============================================================
# 四、怎么判断"差异是否正常"
# ============================================================
# 三个层次，从严格到宽松：
#
#   ① 逐位相同
#     几乎不可能，除非两边用完全相同的实现。
#
#   ② 相对误差在精度量级以内
#     float32 -> 相对误差 < 1e-6 就算正常
#     float16 -> < 1e-3
#     这是最实用的判据。
#
#   ③ 最终结论一致
#     argmax 的类别一样、检测框的数量和位置基本重合。
#     对业务来说这才是真正要保证的。
#
# ★ 千万不要用"绝对误差 < 0.01"这种拍脑袋的阈值。
#   阈值必须和输出的量级、dtype 绑定：
#     输出值在 0~1 之间时，0.01 是灾难性的偏差；
#     输出值在 0~1000 之间时，0.01 完全正常。


# ============================================================
# 五、输入相关的三个坑
# ============================================================
# ① 名字必须对上
#    创建 session 之后可以先问它要什么：
#       sess.get_inputs()[0].name     -> "images"
#       sess.get_inputs()[0].shape    -> [4, 3, 32, 32]（或动态维度）
#       sess.get_inputs()[0].type     -> tensor(float)
#
# ② dtype 必须对上
#    模型是 float32，你喂 float64 会直接报错或被拒绝。
#    从 PyTorch 转过来通常是 tensor.numpy()，dtype 会自然保持。
#
# ③ 内存布局
#    numpy 数组必须是连续的（C 顺序）。
#    从张量经过转置、切片得来的数组可能不连续，需要 .copy()。


# ============================================================
# 六、这一课要记住的三句
# ============================================================
# 1. 对拍是部署的第一道关：同一个输入，两个引擎各算一遍。
#    没有对拍，你不知道导出有没有改变语义。
#
# 2. 差异不会为 0。实测 4.5e-08，正好是 float32 的精度量级，
#    说明是同一函数的两种实现，而不是模型被改变了。
#
# 3. 判据用"相对误差 + 结论一致"，不要用拍脑袋的绝对阈值。

