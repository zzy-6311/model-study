# H02：Conv —— 模型里最小的标准件
#
# 【这一课要讲清楚的一件事】
#
#   YOLO 里出现最多的那个零件叫 Conv。
#   它不是一个卷积，而是**三个动作连在一起**：
#
#     输入 -> ① 卷积 -> ② 归一化 -> ③ 激活 -> 输出
#
#   这一课讲清楚：这三步各自在干什么、为什么必须捆在一起、
#   以及这个零件在整个模型里占多少份量。


# ============================================================
# 一、先看大图景：一个零件，三个动作
# ============================================================
#   把模型想象成一条流水线。流水线上的工位，绝大多数长这样：
#
#     ┌──────────────────────────────────────┐
#     │  Conv                                 │
#     │    ① 卷积     看邻居，找图案           │
#     │    ② 归一化   把数值拉回正常范围        │
#     │    ③ 激活     加一个弯，制造非线性      │
#     └──────────────────────────────────────┘
#
#   ★ 关键：这三步不是可选的，缺一步都不行。下面逐个说为什么。


# ============================================================
# 二、① 卷积在干什么
# ============================================================
#   用一个小窗口（比如 3×3）在特征图上滑动，
#   每滑到一个位置，就把窗口里的数加权求和，输出一个数。
#
#   一层卷积做完，输入 [C_in, H, W] 变成输出 [C_out, H, W]
#   （如果步长是 2，H 和 W 会减半）。
#
#   ★ 它做的是"看邻居、找局部图案"（D02 讲过）。
#     3×3 的窗口能看出边缘、角、纹理。


# ============================================================
# 三、② 归一化在干什么
# ============================================================
#   卷积输出的数值范围是不可控的：
#     有的层输出普遍是 0.001 量级
#     有的层输出普遍是 500 量级
#
#   这会让后面的层很难受：
#     数值太小 -> 梯度也小 -> 学不动（E03 讲过的梯度消失）
#     数值太大 -> 激活函数饱和 -> 梯度接近 0
#
#   归一化的做法：把这一批输出的每个通道，
#   减去均值、除以标准差，拉成"均值 0、方差 1"：
#
#     y = (x - 均值) / 标准差
#
#   然后再乘一个可学习的 γ、加一个可学习的 β，
#   让网络自己决定"要不要还原成别的范围"：
#
#     y = γ × (x - 均值) / 标准差 + β
#
#   ★ 一句话：**不管上一层算出什么量级，先拉到同一个尺度再往下传。**
#     这就是 C07 讲的 BatchNorm。


# ============================================================
# 四、③ 激活在干什么
# ============================================================
#   如果没有激活，两层卷积叠在一起还是线性变换：
#
#     第一层： y = W1 x + b1
#     第二层： z = W2 y + b2 = W2(W1 x + b1) + b2 = (W2W1) x + ...
#
#   合并之后还是一个线性函数 —— 叠 100 层等于叠 1 层。
#
#   激活函数的作用就是"掰弯"这个线性关系（B08 讲过）：
#
#     ReLU(x) = max(0, x)
#     SiLU(x) = x × sigmoid(x)
#
#   ★ 有了它，多层叠起来才能表达复杂的形状。


# ============================================================
# 五、三合一：源码就是把这三步串起来
# ============================================================
#   conv.py 第 80 行附近：
#
#     def forward(self, x):
#         return self.act(self.bn(self.conv(x)))
#
#   从里到外读：
#     self.conv(x)          ① 卷积
#     self.bn(...)          ② 归一化
#     self.act(...)         ③ 激活
#
#   ★ 整节课的核心就是这一行。
#     剩下的都是"为什么这么写"的细节。


# ============================================================
# 六、为什么捆成一个模块，而不是每次写三行
# ============================================================
#   因为这三件事永远连着出现。模型里需要 102 处，
#   如果每次都写三行，代码会又长又容易漏。
#
#   捆成 Conv 之后：
#     Conv(64, 128, 3)       就是"64 通道进、128 通道出、3×3 窗口"
#     Conv(128, 256, 3, 2)   最后那个 2 是步长，输出尺寸减半
#
#   ★ 这就是"标准件"：像乐高里那种固定形状的砖，
#     搭任何结构都从它开始。


# ============================================================
# 七、三个连带的小细节（知道就行，不影响理解主干）
# ============================================================
#   【细节 1】卷积不带偏置（bias=False）
#     归一化里那个 β 就是一个可学习的偏置。
#     卷积再带一个，两个作用完全重叠，等于白加参数。
#
#   【细节 2】顺序是"先归一化、后激活"
#     先把数值拉到正常范围，激活函数才工作在有效区间。
#     反过来的话，激活已经把分布切过一刀（ReLU 把负数清零），
#     再归一化就破坏了这个形状。
#
#   【细节 3】默认激活是 SiLU，不是 ReLU
#     SiLU(x) = x × sigmoid(x)
#
#     x = -3  ->  ReLU 0.00    SiLU -0.14   负半轴不是硬切
#     x =  1  ->  ReLU 1.00    SiLU  0.73
#     x =  3  ->  ReLU 3.00    SiLU  2.86
#
#     好处：0 附近光滑（ReLU 在 0 处不可导），负半轴有微弱信号。


# ============================================================
# 八、这个零件在模型里有多重
# ============================================================
#   统计 yolo26n：
#
#     Conv（带 BN + SiLU）   102 个
#     DWConv（深度卷积）      12 个
#
#   参数构成（按 state_dict 统计）：
#
#     卷积核权重            2,552,208   98.5%
#     归一化的 γ 和 β          19,568    0.75%
#     检测头输出层 bias           504    0.02%
#     --------------------------------------------
#     合计                  2,572,280   100%
#
#   ★ 结论：模型 98.5% 的参数都是卷积核。
#     "模型多大"这件事，基本等价于"卷积核有多少"。


# ============================================================
# 九、成本：同一个零件，贵的和便宜的不一样
# ============================================================
#   参数量 ≈ C_in × k² × C_out
#   算力   ≈ 2 × H_out × W_out × C_in × k² × C_out
#
#   两个真实例子：
#
#   层 0  Conv(3 → 16, 3×3, 步长2)   输出 16×320×320
#     参数 464         很小
#     算力 0.09G       不算小（320×320 面积大）
#
#   层 7  Conv(128 → 256, 3×3, 步长2)  输出 256×20×20
#     参数 295,424     很大
#     算力 0.24G       反而不高（20×20 面积小）
#
#   ★ 参数看通道，算力看面积 —— H01 的规律在这里再次出现。


# ============================================================
# 十、这一课要记住的三句
# ============================================================
# 1. YOLO 的 Conv = 卷积 + 归一化 + 激活，三个动作捆成一个标准件。
#    源码里就是 act(bn(conv(x))) 这一行。
#
# 2. 三步各管一件事：卷积找图案、归一化控尺度、激活加非线性。
#    缺一步，网络就训不好或表达力不够。
#
# 3. 模型 98.5% 的参数是卷积核。所以"模型多大"就是"卷积核多少"。

