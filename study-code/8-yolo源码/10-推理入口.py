# H10：推理入口 —— 从一张图到最终几个框
#
# 【这一课要讲清楚的一件事】
#
#   训练时我们关心损失；推理时只关心一件事：
#   **一张图进来，几个框出去，每个框的坐标在原图的什么位置。**
#
#   这条路径不长，但中间经过了三个坐标系，
#   坐标搞错是部署阶段最常见的 bug（G04 讲过原理，这里是源码对应）。


# ============================================================
# 一、三个坐标系
# ============================================================
#   【坐标系 A】原图坐标系
#     你从磁盘读进来的那张图，1280×720。
#     用户要的结果必须在这个坐标系里。
#
#   【坐标系 B】LetterBox 之后的坐标系
#     1280×720 等比缩小到 640×360，上下补 140 灰边 -> 640×640。
#     框在这里要跟着缩放和平移。
#
#   【坐标系 C】模型输入坐标系
#     就是 B 再转成张量：NCHW、RGB、0~1。
#     模型的所有输出都在这个坐标系里。
#
#   ★ B 和 C 的空间尺寸相同（都是 640×640），
#     区别只在"是 numpy 图像"还是"是张量"。真正麻烦的是 A 和 C 的换算。


# ============================================================
# 二、preprocess 做了四件事（engine/predictor.py:184）
# ============================================================
#   输入：一张 BGR 的 uint8 图（OpenCV 读出来的样子）
#
#     ① LetterBox              -> 尺寸变成 640×640，记下 r 和 pad
#     ② BHWC -> BCHW           -> (h, w, 3) 变成 (3, h, w)
#     ③ BGR -> RGB             -> im.flip(1)
#     ④ / 255                  -> 0~255 变 0.0~1.0
#
#   源码里对应四行：
#     im = im.permute(0, 3, 1, 2).contiguous()   # ②
#     im = im.flip(1)                            # ③ BGR -> RGB
#     im = im.float().div_(255)                  # ④
#
#   ★ 第 ③ 步最容易出错：
#     训练时如果用的是 PyTorch 的 ImageFolder / PIL（RGB），
#     推理时用 OpenCV 读（BGR）又忘了转换，颜色就全反了。
#     F06 的契约卡里"通道顺序"那一行，防的就是这个。


# ============================================================
# 三、LetterBox 记下的三个数
# ============================================================
#   以 1280×720 的图为例（G04 算过）：
#
#     r     = 0.5         缩放比
#     pad_w = 0           左右补边
#     pad_h = 140         上下补边
#
#   正变换（原图 -> 模型）：
#     x' = x × r + pad_w
#     y' = y × r + pad_h
#
#   一个框 [100, 200, 300, 400] 变成：
#     x1' = 100 × 0.5 + 0   = 50
#     y1' = 200 × 0.5 + 140 = 240
#     x2' = 300 × 0.5 + 0   = 150
#     y2' = 400 × 0.5 + 140 = 340
#     -> [50, 240, 150, 340]
#
#   逆变换（模型 -> 原图）：
#     x = (x' - pad_w) / r
#     y = (y' - pad_h) / r
#
#   ★ 顺序不能反：先减平移，再除缩放。
#     搞反的话框会整体偏移（G04 实测偏了 280 像素）。


# ============================================================
# 四、postprocess 的两步
# ============================================================
#   models/yolo/detect/predict.py:34 的 postprocess：
#
#     ① 筛选与去重
#          preds = nms.non_max_suppression(
#              preds, conf, iou, classes, agnostic_nms, max_det,
#              end2end=getattr(self.model, "end2end", False),
#          )
#
#        ★ 注意最后那个参数：end2end=True 时，
#          这个函数可能只做"分数筛选 + TopK"，没有真正的抑制。
#          （H07 讲的两个层次：函数名 ≠ 实际行为）
#
#     ② 坐标还原
#          pred[:, :4] = ops.scale_boxes(
#              img.shape[2:],      # 模型输入尺寸 (640, 640)
#              pred[:, :4],        # 框（在 640 坐标系里）
#              orig_img.shape,     # 原图尺寸 (720, 1280, 3)
#          )
#
#        ★ scale_boxes 做的就是第三节那个逆变换。
#          它的输入里没有显式传 r 和 pad ——
#          因为 r 和 pad 可以从"两个尺寸的比值"重新算出来。
#
#   这一步之后，框才回到用户能理解的坐标系（原图像素）。


# ============================================================
# 五、完整调用链（记住这条就够）
# ============================================================
#   用户代码
#     model.predict(source)                       # engine/model.py
#       -> predictor(source)                      # engine/predictor.py
#          -> preprocess(image)                   # 184 行：LetterBox + 转张量
#          -> inference(im)                       # 模型前向（H06）
#             -> Detect.forward                   # head.py:185
#                -> _inference                    # 距离转框 + sigmoid（G06）
#          -> postprocess(preds, img, orig_imgs)  # detect/predict.py:34
#             -> non_max_suppression              # 阈值 + 去重（G08）
#             -> scale_boxes                      # 坐标还原（G04）
#       -> Results 对象（含 boxes、masks、keypoints）


# ============================================================
# 六、坐标系错乱的三个典型症状
# ============================================================
#   ① 框整体偏移
#      忘减 padding，或者 padding 用的是别的图的（G04）。
#      症状：框都往下/往右移了一段固定距离。
#
#   ② 框大小不对（都偏大或偏小）
#      缩放比例用错，或者用了两次。
#      症状：框跟着图一起放大/缩小了。
#
#   ③ 框位置随机、完全对不上
#      xyxy / xywh 混用（G02），或者归一化和像素混用。
#      症状：框在画面里乱跳，但数量差不多对。
#
#   ★ 排查顺序：
#     先存下"预处理后的张量"，用同一份喂 PyTorch 和部署端（F05 的三段隔离）；
#     再单独检查 scale_boxes 的输入输出。


# ============================================================
# 七、为什么这一课放在最后
# ============================================================
#   前九课都在讲"模型内部"：结构、前向、损失。
#   这一课是"模型外面"：进去之前要变成什么样，出来之后要变回什么样。
#
#   ★ 一个能跑通的推理程序，需要的知识是：
#
#       模型内部（H01~H08）   知道 8400 个位置、84 个数是什么
#       + 坐标系（G02/G04）   知道框在哪个坐标系、怎么换算
#       + 后处理（G08）       知道阈值和 NMS 在做什么
#       + 契约（F06）         知道预处理参数必须和训练一致
#
#     缺任何一块，都会表现为"模型不准"，但其实是代码错了。


# ============================================================
# 八、这一课要记住的三句
# ============================================================
# 1. 推理路径只有四步：LetterBox、转张量、前向、NMS + 坐标还原。
#
# 2. 三个坐标系（原图 / LetterBox 后 / 模型输入），
#    关键是 r 和 pad 这两个数，正变换"先缩放后平移"，
#    逆变换"先减平移后除缩放"。
#
# 3. BGR/RGB 转换在 preprocess 里（im.flip(1)），
#    训练和推理不一致是准确率下降的常见原因。

