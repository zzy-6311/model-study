# H04：SPPF 和 C2PSA —— 两种"看得更远"的办法
#
# 【这一课要讲清楚的一件事】
#
#   3×3 卷积一次只能看 3 个像素远。但检测需要"知道这块属于哪个物体"，
#   所以必须让每个位置看到更大的范围。
#
#   YOLO26 用了两种手段：
#     SPPF   用池化把视野撑大，几乎不花参数
#     C2PSA  用自注意力看整张图，代价是位置数的平方
#
#   这一课把两个都讲清楚：它们在算什么、怎么做到、各花多少钱。


# ============================================================
# 一、先理解"视野"
# ============================================================
#   一层 3×3 卷积，每个输出只看输入的 3×3 范围。
#   叠两层，视野 5×5；叠 n 层，视野 (2n+1)×(2n+1)。
#
#   要看到 13×13，得叠 6 层 3×3 —— 层数越多，参数越多。
#   所以人们想别的办法：能不能用更便宜的操作换来更大的视野？


# ============================================================
# 二、SPPF：用小池化叠出大视野
# ============================================================
#   SPPF = Spatial Pyramid Pooling - Fast。
#
#   核心技巧：**同一个 5×5 最大池化，连续做 3 次。**
#
#     第 1 次：视野 5×5
#     第 2 次：视野 5 + 4 = 9×9
#     第 3 次：视野 9 + 4 = 13×13
#
#   ★ 等效于"直接做一次 13×13 池化"，
#     但计算量是 3×25 = 75，而 13×13 是 169 —— 便宜 56%。
#     这就是名字里 "Fast" 的来源。


# ============================================================
# 三、SPPF 的数据流（层 9，256 通道进）
# ============================================================
#     x: 256 通道
#       │
#       ▼ cv1 = Conv(256 → 128, 1×1, 无激活)      参数 33,024
#     128 通道
#       │
#       ├── y0 = 原样 ─────────────────┐
#       ├── y1 = MaxPool(y0)  5×5      │
#       ├── y2 = MaxPool(y1)           │  池化 0 参数
#       └── y3 = MaxPool(y2)           │
#                                       │
#       ▼ 拼起来 128 × 4 = 512 通道
#       ▼ cv2 = Conv(512 → 256, 1×1)              参数 131,584
#     256 通道
#
#   总参数 164,608（实测一致）
#
#   ★ 两处省钱：
#   ① 先把通道压到一半，池化只在这一半上做
#   ② 池化零参数（只取最大值，没有权重）
#
#   四个分支 = 四种视野（5 / 9 / 13 / 原样），
#   拼在一起交给后面那层 1×1 自己决定"该重视哪个尺度"。


# ============================================================
# 四、C2PSA 要解决什么：卷积是"局部"的
# ============================================================
#   卷积有个天生的限制：**每个位置只和邻居打交道。**
#
#   如果图里有一只很大的鸟，左翅膀和右翅膀隔了几百像素，
#   卷积要叠很多层才能把它们联系起来。
#
#   自注意力不一样：**每个位置直接和图上所有位置算相关度。**
#
#     卷积   = 只看周围一圈的邻居
#     注意力 = 可以看整张图，自己决定"谁对我重要"


# ============================================================
# 五、注意力到底在算什么（4 个位置的小例子）
# ============================================================
#   假设有 4 个位置，每个位置 2 个数：
#
#     p0 = [1, 0]
#     p1 = [0, 1]
#     p2 = [1, 1]
#     p3 = [0.5, 0.5]
#
#   第一步：两两算相似度（点积，越像越大）

import torch

torch.set_printoptions(precision=3, sci_mode=False)

x = torch.tensor([[1.0, 0.0],
                  [0.0, 1.0],
                  [1.0, 1.0],
                  [0.5, 0.5]])

scores = x @ x.T                        # 4×4 相似度矩阵
scaled = scores / (x.shape[1] ** 0.5)   # 除以 sqrt(d)，防止数值过大
weights = torch.softmax(scaled, dim=1)  # 每行归一化
out = weights @ x                       # 加权求和

print("=" * 62)
print("一、注意力在算什么")
print("相似度矩阵（x·x^T）：")
print(scores)

# 输出：
#         p0    p1    p2    p3
#   p0  1.00  0.00  1.00  0.50
#   p1  0.00  1.00  1.00  0.50
#   p2  1.00  1.00  2.00  1.00
#   p3  0.50  0.50  1.00  0.50
#
# p0 和 p2 相似度 1.00（都是第一维为 1 的那一类）
# p0 和 p1 相似度 0.00（完全不像）

print()
print("softmax 之后的权重（每行和为 1）：")
print(weights)
print("每行和 =", weights.sum(1))

# 输出：
#         p0    p1    p2    p3
#   p0  0.313 0.154 0.313 0.220
#   p1  0.154 0.313 0.313 0.220
#   p2  0.199 0.199 0.403 0.199
#   p3  0.226 0.226 0.322 0.226

print()
print("输出（每个位置变成全图的加权平均）：")
print(out)

# 输出：
#   p0  [0.736, 0.577]
#   p1  [0.577, 0.736]
#   p2  [0.702, 0.702]
#   p3  [0.661, 0.661]
#
# ★ p0 原来是 [1, 0]，现在变成 [0.736, 0.577] ——
#   它把自己和"像自己"的 p2 混在了一起，也吸收了一点别人的信息。
#
#   这就是注意力：**每个位置重新描述自己，描述里包含全图的加权信息。**


# ============================================================
# 六、Q / K / V：真实的注意力不是直接拿输入比
# ============================================================
#   上面的例子为了简单，直接拿输入当查询。
#   真实模型里会做三次不同的线性变换：
#
#     Q = 我在找什么      （Query，查询）
#     K = 我能提供什么    （Key，钥匙）
#     V = 我实际的内容    （Value，值）
#
#     权重 = softmax(Q·Kᵀ / √d)
#     输出 = 权重 × V
#
#   类比图书馆检索：
#     Q = 你想找的主题
#     K = 每本书的标签
#     V = 每本书的内容
#   拿主题和所有标签比一遍，相关度高的书，内容多看一点。
#
#   ★ "自"注意力的意思是：Q、K、V **都来自同一个输入**。
#     所以是"每个位置和图上所有位置（包括自己）比一遍"。
#
#   ★ 多头（num_heads）：把通道分成几组，每组各算一遍注意力，
#     最后拼起来。不同的头可以关注不同的关系
#     （一个看颜色、一个看相邻、一个看形状……）。


# ============================================================
# 七、真实尺寸（层 10，128 通道）
# ============================================================
#     dim      = 128
#     heads    = 2
#     head_dim = 128 / 2 = 64
#     key_dim  = 64 × 0.5 = 32      （attn_ratio=0.5，K 再窄一半省参数）
#
#     qkv  = Conv(128 → 256, 1×1)     33,280 参数
#            → 拆成 Q(128) + K(64) + V(64)
#     proj = Conv(128 → 128, 1×1)     16,640 参数   （多头结果合并后再投影）
#     pe   = Conv(128 → 128, 3×3, 深度卷积)  1,408  （位置编码）
#     ------------------------------------------------------
#     attn 合计                        51,328
#
#   ★ 那个 pe 是干嘛的：
#     注意力本身**不知道位置**——把所有位置打乱顺序，
#     加权求和的结果是一样的。所以要给每个位置加一点"我在哪"的信息。
#     这里用一个深度 3×3 卷积实现：让邻居之间产生关系，就有了位置感。


# ============================================================
# 八、PSABlock = 注意力 + 前馈 + 两个残差
# ============================================================
#     x ──→ Attention ──→ (+) ──→ FFN ──→ (+) ──→ 输出
#      └──────────────────┘   └───────────┘
#           残差 1               残差 2
#
#     ffn = Conv(128 → 256, 1×1) → Conv(256 → 128, 1×1)   66,304 参数
#
#   ★ 两个残差的作用和 B03 一样：给梯度一条直通的路，
#     同时保住原始信息（万一注意力学歪了，也不至于全丢）。


# ============================================================
# 九、C2PSA 整体：也是"劈通道"
# ============================================================
#     x: 256 通道
#       │
#       ▼ cv1 = Conv(256 → 256, 1×1)            66,048
#     劈成 a(128) + b(128)
#       │
#       ├─ a: 原样抄近路 ──────────────────┐
#       │                                   │
#       └─ b: → PSABlock ─────────────────┤   117,632
#                                           │
#       ▼ 拼回 256 通道
#       ▼ cv2 = Conv(256 → 256, 1×1)            66,048
#     256 通道
#
#   总参数 249,728（实测一致）
#
#   ★ 和 C3k2 是同一个套路：一半抄近路，一半干重活。


# ============================================================
# 十、成本对比
# ============================================================
#   层  模块     参数       FLOPs    位置数
#   --------------------------------------------------
#   9   SPPF   164,608    0.13G    20×20 = 400
#   10  C2PSA  249,728    0.20G    20×20 = 400
#   --------------------------------------------------
#   合计       414,336    0.33G
#              占全模型 16% 参数、5.5% 算力
#
#   ★ 它们是"用参数换视野"，不是"用算力换视野"。


# ============================================================
# 十一、为什么都放在 20×20 上
# ============================================================
#   注意力的代价是位置数的平方：
#     P5  20×20 =   400 个位置 -> 相关矩阵 16 万
#     P3  80×80 = 6,400 个位置 -> 相关矩阵 4,096 万（256 倍）
#
#   如果 SPPF 放在层 2（160×160），同样的参数，FLOPs 会变成 64 倍：
#     0.13G -> 8.3G
#
#   ★ 设计网络时，贵的操作要放在深层 —— 那里特征图小，便宜得多。


# ============================================================
# 十二、这一课要记住的三句
# ============================================================
# 1. SPPF 用"5×5 池化连做 3 次"等效出 13×13 的视野，零参数，便宜 56%。
#
# 2. 注意力的本质：每个位置用 softmax(相似度) 当权重，
#    把所有位置的信息加权平均，重新描述自己。
#    代价是位置数的平方。
#
# 3. 两个模块都在 P5（20×20）上工作 —— 那里位置最少，是最便宜的"地段"。

