# H06：一张图怎么流过这 24 层
#
# 【这一课要讲清楚的一件事】
#
#   H05 讲了 yaml 怎么变成 24 层。但那 24 层是"一条线"还是"一张网"？
#   跨层连接（Concat 取第 6 层、Detect 取三个尺度）是怎么实现的？
#
#   答案在 nn/tasks.py 第 184 行的 _predict_once —— **只有 12 行。**


# ============================================================
# 一、整个前向循环
# ============================================================
#   def _predict_once(self, x):
#       y = []                                   # 存每一层的输出
#       for m in self.model:                     # 逐层
#           if m.f != -1:                        # 如果输入不是上一层
#               x = y[m.f] if isinstance(m.f, int) #                   else [x if j == -1 else y[j] for j in m.f]
#           x = m(x)                             # 跑这一层
#           y.append(x if m.i in self.save else None)   # 决定要不要留
#       return x
#
#   ★ 就这些。整个网络的前向、所有跨层连接，都在这 12 行里。


# ============================================================
# 二、三个关键东西
# ============================================================
#   【y】一个列表，长度 = 层数，用来存"要保留的输出"
#
#       注意 append 的内容可能是 None：
#         y.append(x if m.i in self.save else None)
#       没被 save 的层，往列表里塞一个 None 占位。
#       这样 y[i] 的下标永远等于层号 i，取的时候不用算偏移。
#
#   【m.f】这一层的"输入来自哪"
#       -1       上一层（最常见）
#       6        第 6 层
#       [-1, 6]  上一层 + 第 6 层（Concat 用）
#
#   【self.save】哪些层的输出必须留着
#       实测 yolo26n 的 save 列表：
#         [4, 6, 10, 13, 16, 19, 22]
#       正好是"被后面引用到的那些层"：
#         第 4 层被第 15 层的 Concat 用
#         第 6 层被第 12 层的 Concat 用
#         第 10 层被第 21 层的 Concat 用
#         第 13 层被第 18 层的 Concat 用
#         第 16、19、22 层被第 23 层的 Detect 用
#
#   ★ 换句话说：**save 列表是 from 字段"反推"出来的。**
#     你写了 from=[-1, 6]，第 6 层的输出就必须留着。


# ============================================================
# 三、走一遍真实的 24 层
# ============================================================
#   层   from        保存   模块        说明
#   ------------------------------------------------------
#    0   -1          —     Conv        输入图片
#    1   -1          —     Conv
#    2   -1          —     C3k2
#    3   -1          —     Conv        P3 尺度（80×80）
#    4   -1          是     C3k2        ← 留给第 15 层
#    5   -1          —     Conv        P4 尺度（40×40）
#    6   -1          是     C3k2        ← 留给第 12 层
#    7   -1          —     Conv        P5 尺度（20×20）
#    8   -1          —     C3k2
#    9   -1          —     SPPF
#   10   -1          是     C2PSA       ← 留给第 21 层
#   ------------------------------------------------------
#   11   -1          —     Upsample    20×20 -> 40×40
#   12   [-1, 6]     —     Concat      当前 40×40 + 第6层 40×40
#   13   -1          是     C3k2        ← 留给第 18 层
#   14   -1          —     Upsample    40×40 -> 80×80
#   15   [-1, 4]     —     Concat      当前 80×80 + 第4层 80×80
#   16   -1          是     C3k2        ← 留给 Detect（P3 输出）
#   ------------------------------------------------------
#   17   -1          —     Conv        80×80 -> 40×40
#   18   [-1, 13]    —     Concat      当前 40×40 + 第13层 40×40
#   19   -1          是     C3k2        ← 留给 Detect（P4 输出）
#   ------------------------------------------------------
#   20   -1          —     Conv        40×40 -> 20×20
#   21   [-1, 10]    —     Concat      当前 20×20 + 第10层 20×20
#   22   -1          是     C3k2        ← 留给 Detect（P5 输出）
#   ------------------------------------------------------
#   23   [16,19,22]  —     Detect      三个尺度的特征图一起送进去
#
#   ★ 看这条路径就明白了：
#     上半段（11~16）是"自顶向下"：把大尺度的信息往上传给小尺度
#     下半段（17~22）是"自底向上"：把小尺度的信息往下传给大尺度
#     这就是 FPN + PAN 结构，通俗叫"特征金字塔"。


# ============================================================
# 四、三个跨层连接点具体在做什么
# ============================================================
#   【第 12 层】Concat([x, y[6]])
#     x    = 第 11 层上采样的结果（来自 P5，20×20 -> 40×40）
#     y[6] = 第 6 层的输出（P4，40×40，128 通道）
#     两个都是 40×40，沿通道拼起来 -> 256 通道
#     -> 后面第 13 层把这个"深层信息 + 中层信息"的混合体加工一遍
#
#   【第 15 层】Concat([x, y[4]])
#     同样的操作，在 80×80 的尺度上再来一次
#     y[4] 是 P3（80×80，64 通道）
#
#   【第 23 层】Detect([y[16], y[19], y[22]])
#     这一步没有 Concat，而是把三个不同尺度的特征图
#     分别送进三个并行的检测头分支
#     （G06 讲的 80×80 / 40×40 / 20×20 三个尺度）
#
#   ★ 注意区别：
#     Concat 是"同一尺度、沿通道拼"（要求空间尺寸一致）
#     Detect 是"不同尺度、分别处理"（每个尺度自己出结果）


# ============================================================
# 五、为什么用"列表 + 下标"这种写法
# ============================================================
#   假设不用列表，而是给每层起个变量名：
#
#     x0 = net[0](img)
#     x1 = net[1](x0)
#     ...
#     x12 = net[12](torch.cat([x11, x6], 1))
#
#   问题：层数、连接关系是 yaml 里随时会改的。
#   每改一次结构，就得重写一遍代码。
#
#   ★ 用"列表 + 下标"之后，结构完全由数据决定：
#     第几层、从哪来、要不要留，全在配置里。
#     代码永远是那 12 行。
#
#   这是"数据驱动"的典型写法：
#     网络拓扑是数据（yaml 里的 from/save），不是代码。


# ============================================================
# 六、一个容易忽略的细节：y 里大部分是 None
# ============================================================
#   24 层的网络，y 的长度是 24，但只有 7 个位置是真张量：
#     y[4] y[6] y[10] y[13] y[16] y[19] y[22]
#   其余 17 个都是 None。
#
#   ★ 为什么不全部保留？
#     因为中间结果很占显存（E07 讲的"激活值"）。
#     全部保留的话，640×640 输入、batch 8，光中间结果就要几个 GB。
#     只保留"被后面用到的"，是最省的做法。
#
#   这也解释了一件事：
#     如果你在 yaml 里加了跨层连接，save 列表会自动变长，
#     显存占用也会跟着涨 —— 这不是 bug，是必然代价。


# ============================================================
# 七、这一课要记住的三句
# ============================================================
# 1. 整个前向就是 12 行：按 from 取输入、跑这一层、
#    按 save 决定要不要保留输出。
#
# 2. save 列表（[4,6,10,13,16,19,22]）是从 from 字段反推出来的，
#    它决定了显存里要留多少中间结果。
#
# 3. 上半段自顶向下、下半段自底向上，这就是 FPN+PAN 特征金字塔。

