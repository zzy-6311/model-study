# ============================================================
# 三、从这张表读出的四条规律
# ============================================================
# 【规律 1】下采样层（Conv s=2）参数多、FLOPs 中等
#
#   看层 5、7：通道数翻倍的地方，参数暴涨
#     层5  128 通道 3×3 ：147,712 参数
#     层7  256 通道 3×3 ：295,424 参数
#   因为 conv 参数 = C_in × C_out × k²，通道一翻倍，参数涨 4 倍。
#
#   但它们的 FLOPs 只有 0.47G 和 0.24G —— 因为输出特征图小（40×40、20×20）。
#
# ★ 结论：**参数看通道，算力看面积。**
#
#
# 【规律 2】C3k2 参数中等，但 FLOPs 一直不低
#
#   层 2 只有 6,640 参数，却有 0.33G —— 因为它在 160×160 上算。
#   层 22 有 463,104 参数，只有 0.37G —— 因为它在 20×20 上算。
#
# ★ 同一个"参数量差 70 倍"，FLOPs 几乎一样。
#   这说明：**在浅层（大分辨率）省一点通道，比在深层省通道更划算。**
#
#
# 【规律 3】Upsample / Concat 零参数、零 FLOPs，但决定后面的一切
#
#   第 12 层的 Concat 把 256+128 拼成 384 通道，
#   于是第 13 层的 C3k2 要处理 384 输入 —— 它的参数（119,808）就是这么来的。
#
# ★ 加了 Concat 的通道数，代价会转移到下一个模块。
#
#
# 【规律 4】Detect 头：参数少，算力高
#
#   30.9 万参数（12%），1.20G（20.2%）。
#   为什么？它在三个尺度上各做了 4 层卷积：
#     P3 80×80、P4 40×40、P5 20×20
#   其中 P3 那一路在 80×80 上算，面积是 P5 的 16 倍。
#
# ★ 这是最反直觉的一点：
#   **想减算力，改检测头比改 backbone 更划算**，
#   因为它一直在高分辨率上工作，没有下采样来"摊薄"成本。


