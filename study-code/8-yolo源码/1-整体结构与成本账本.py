# 一、24 层，分三段
# ============================================================
#   backbone（第 0~10 层）  提取特征，逐步下采样
#   neck    （第 11~22 层） 特征融合，把不同尺度的信息混起来
#   head    （第 23 层）    检测头，输出 8400 个预测
#
#   段        参数        占比     FLOPs     占比
#   ----------------------------------------------------
#   backbone  1,365,472   53.1%    3.04G    51.0%
#   neck        897,152   34.9%    1.72G    28.8%
#   head        309,656   12.0%    1.20G    20.2%
#   ----------------------------------------------------
#   合计      2,572,280  100.0%    5.96G   100.0%
#
# ★ 第一眼就要注意的两件事：
#   ① backbone 和 neck 各占一半左右的算力
#   ② head 的参数只有 12%，却吃了 20% 的算力 —— 这不符合直觉


