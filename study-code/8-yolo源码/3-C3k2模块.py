# H03：C3k2 —— 模型里用了 8 次的主力模块
#
# 【这一课要讲清楚的一件事】
#
#   C3k2 的形状是：**把通道劈成两半，只让一半去"干重活"。**
#
#   这听起来简单，但它让模型在保持表达能力的同时，
#   把最贵的那部分计算量降到了四分之一。
#
#   这一课讲：它为什么这么设计、数据怎么流、省了多少。


# ============================================================
# 一、先看形状
# ============================================================
#   输入 x（c1 个通道）
#     │
#     ├─ cv1（1×1 卷积，通道变成 2c）
#     │
#     ├─── 劈成两半 ───┐
#     │                │
#     │  左半 (c 通道)  │  右半 (c 通道)
#     │     │           │     │
#     │     │           │     └──→ 依次过 n 个 Bottleneck（重活在这）
#     │     │           │            │
#     │     └───────────┴────────────┘
#     │                 │
#     └──── 三份拼起来（2c + n·c 通道）→ cv2（1×1 卷积）→ 输出 c2
#
#   ★ 关键点：
#     左半**什么都不做**，直接原样送到最后
#     右半才去走那些带 3×3 卷积的块
#
#   这就是 CSP（Cross Stage Partial）的核心思想：
#   **让一部分通道"抄近路"，不参与昂贵的计算。**


# ============================================================
# 二、为什么要抄近路
# ============================================================
#   如果 32 个通道全都过 3×3 卷积：
#     参数 = 32 × 32 × 9 + 偏置 ≈ 9,280
#
#   劈成两半，只让 16 个通道过：
#     参数 = 16 × 16 × 9 + ... ≈ 2,352
#
#   ★ 通道减半，参数降到约 1/4（因为参数是通道数的平方）。
#
#   而信息没有丢：左半 16 个通道原封不动穿过去，
#   最后和右半的输出拼在一起，一起做 1×1 融合。
#
#   类比：一条流水线上有两组零件，
#         一组去"深加工车间"绕一圈，一组直接送到装配台。
#         装配台（cv2）再把它们合起来。


# ============================================================
# 三、用真实的层走一遍（层 2）
# ============================================================
#   层 2 的配置：C3k2(32 → 64, n=1, c3k=False, e=0.25)
#
#     c1 = 32        输入通道
#     c2 = 64        输出通道
#     c  = c2 × e = 64 × 0.25 = 16     每一半的通道数
#
#   数据流：
#
#     x: 32 通道
#       │
#       ▼ cv1 = Conv(32 → 32, 1×1)        参数 1,088
#     32 通道
#       │
#       劈成 16 + 16
#       │
#       ├─ 左 16 ─────────────────────────┐
#       │                                  │
#       └─ 右 16 → Bottleneck(16→16) →     │  参数 2,352
#                     (内部先压到 8 通道)
#                                          │
#       ▼ 三份拼起来：16 + 16 + 16 = 48 通道
#         cv2 = Conv(48 → 64, 1×1)         参数 3,200
#       │
#       ▼ 输出 64 通道
#
#   总计 1,088 + 2,352 + 3,200 = 6,640
#   实测：6,640  ✓


# ============================================================
# 四、Bottleneck 内部还压了一次
# ============================================================
#   上面的 Bottleneck(16 → 16) 参数是 2,352，怎么来的？
#
#   Bottleneck 的默认 e = 0.5，内部结构是"两头宽、中间窄"：
#
#     16 通道 → Conv 3×3 → 8 通道  → Conv 3×3 → 16 通道
#               ↑ 参数 1,168            ↑ 参数 1,184
#     再加残差（输入直接加到输出）
#
#   ★ 这就是"bottleneck"这个词的本意：瓶颈。
#     先用 1×1 或窄通道把维度压下去，
#     在窄通道上做昂贵的 3×3，再升回来。
#
#   对比：如果不压，16 → 16 的 3×3 要 16×16×9 = 2,304 参数；
#         压到 8 之后两次 3×3 一共 2,352 —— 差不多，
#         但如果隐藏层更宽（比如 e=1），差距就很明显了。


# ============================================================
# 五、源码就三行
# ============================================================
#   C3k2 继承了 C2f，核心在 C2f 的 292 行：
#
#     self.c   = int(c2 * e)                  # 每一半的通道
#     self.cv1 = Conv(c1, 2 * self.c, 1, 1)   # 1×1，扩到 2c
#     self.cv2 = Conv((2 + n) * self.c, c2, 1)# 1×1，压回 c2
#     self.m   = [Bottleneck(c, c) ...] × n   # 重活在这
#
#     def forward(self, x):
#         y = list(self.cv1(x).chunk(2, 1))   # 劈成两半
#         y.extend(m(y[-1]) for m in self.m)  # 右半逐个过块
#         return self.cv2(torch.cat(y, 1))    # 全拼起来再压
#
#   ★ forward 的三行，正好对应上面那张图的三个阶段：
#     劈开 → 右半加工 → 拼回。
#
#   注意 cv2 的输入通道是 (2 + n) * c：
#     2 份来自"劈开的两半"
#     n 份来自"每个块的输出"（每个块都往列表里加一份）
#     所以 n 越大，cv2 的输入越宽，参数也越多。


# ============================================================
# 六、它出现 8 次，参数占了三分之一
# ============================================================
#   层号：2、4、6、8（backbone）、13、16、19、22（neck）
#
#   层  输入→输出       c     参数      FLOPs
#   --------------------------------------------------
#   2   32 → 64        16    6,640     0.33G
#   4   64 → 128       32   26,080     0.33G
#   6   128 → 128      32   87,040     0.28G
#   8   256 → 256      64  346,112     0.28G
#   13  384 → 128      64  119,808     0.38G
#   16  256 → 64       32   34,304     0.43G
#   19  192 → 128      64   95,232     0.30G
#   22  384 → 256     128  463,104     0.37G
#   --------------------------------------------------
#   合计              约 1.18M 参数（占全模型 46%）
#
#   ★ 两个观察：
#   ① 层 8 和层 22 参数最多（346K / 463K），因为它们通道最宽
#   ② 但它们的 FLOPs 并不高（0.28G / 0.37G），因为特征图很小（20×20）
#
#   最贵的是层 16：参数才 34K，FLOPs 0.43G —— 它在 80×80 上算。


# ============================================================
# 七、层 22 有点特殊：它带注意力
# ============================================================
#   yaml 里层 22 的参数是：C3k2(384 → 256, n=1, c3k=True, e=0.5, attn=True)
#
#   三个开关：
#     c3k=True    内部块换成 C3k（一个更深的 CSP 结构），而不是简单的 Bottleneck
#     e=0.5       每一半 = 256 × 0.5 = 128 通道
#     attn=True   每个块后面再接一个 PSABlock（自注意力）
#
#   实测这个层的组成：
#     cv1  Conv(384 → 256, 1×1)          98,816
#     m    Sequential(Bottleneck, PSABlock)  265,472
#     cv2  Conv(384 → 256, 1×1)          98,816
#     ------------------------------------------------
#     合计                               463,104
#
#   ★ 也就是说：**263K 里有 265K 花在那个 Bottleneck+PSABlock 上**，
#     其中 PSABlock（注意力）是主要开销。
#
#   为什么放在最后一层？因为它输出的正是 P5（20×20，最低分辨率），
#   位置数只有 400，注意力在这里的代价可以接受。
#   如果放在 80×80 的层上，代价会大 16 倍。


# ============================================================
# 八、这一课要记住的三句
# ============================================================
# 1. C3k2 = 劈通道 + 只让一半走重活 + 最后拼回来。
#    这就是 CSP 思想：抄近路的通道保留信息，不走重活省算力。
#
# 2. 通道减半，参数和算力降到约 1/4（因为是平方关系）。
#    实测层 2：全过 3×3 要 9,280 参数，劈开只花 2,352。
#
# 3. 它出现 8 次，参数占全模型 46%。
#    但"参数最多"的层 8/22 不是"算力最贵"的层 ——
#    最贵的是 80×80 上的层 16。

