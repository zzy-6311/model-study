# H08：标签分配与损失 —— 训练信号从哪来
#
# 【这一课要讲清楚的一件事】
#
#   G07 讲了对齐度分配的**原理**，这一课把它落到代码上：
#
#     utils/tal.py    TaskAlignedAssigner  决定"哪个预测学哪个框"
#     utils/loss.py   v8DetectionLoss      决定"错了多少、怎么加权"
#
#   读完这一课，你应该能回答：
#     为什么 box 权重要 7.5、cls 只要 0.5？
#     为什么分类损失要除以 target_scores_sum？


# ============================================================
# 一、损失由三项组成
# ============================================================
#   本地 YOLO26 的损失名（loss.py:377）：
#
#     loss_names = ("box_loss", "cls_loss", "l1_loss")
#
#   ★ 注意：没有 dfl_loss。
#     因为 reg_max=1，那段判断是：
#       self.use_dfl = m.reg_max > 1
#       loss_names = (... "dfl_loss") if use_dfl else (... "l1_loss")
#
#   三项各管什么：
#
#     box_loss   框的位置和形状（用 CIoU，G05）
#     cls_loss   类别判断（用 BCE + 软标签，G07）
#     l1_loss    四个距离的绝对误差（辅助项，让距离本身也贴近）
#
#   默认权重（cfg/default.yaml 第 104~107 行）：
#
#     box: 7.5
#     cls: 0.5
#     dfl: 1.5   （reg_max=1 时这一项作用于 l1_loss）


# ============================================================
# 二、7.5 : 0.5 意味着什么
# ============================================================
#   定位的权重是分类的 15 倍。
#
#   ★ 这不是随手定的，它反映了一个事实：
#     **检测任务里，"框在哪"比"是什么类"更难，也更影响结果。**
#
#   如果 cls 权重太大，模型会倾向于"到处都猜对类别"
#   而不管框准不准 —— 分数高、框乱飘。
#
#   反过来，如果 box 权重过大，模型会把框调到极准，
#   但类别分不清 —— 满图都是框，不知道是什么。
#
#   这组权重是经验值，改了要重新验证 mAP（G09）。


# ============================================================
# 三、第一步：分配（tal.py）
# ============================================================
#   loss.py:384 构造分配器：
#
#     self.assigner = TaskAlignedAssigner(
#         topk=tal_topk,      # one2many 是 10，one2one 是 1
#         num_classes=self.nc,
#         alpha=0.5,
#         beta=6.0,
#     )
#
#   分配器做的事（G07 讲过原理，这里是代码对应）：
#
#     ① 找出"中心点落在某个 GT 框内"的候选位置
#     ② 算每个候选和这个 GT 的 IoU
#     ③ 算对齐度 = 分类分数^alpha × IoU^beta
#     ④ 每个 GT 取 TopK（10 个或 1 个）
#     ⑤ 一个位置被多个 GT 选中时，归给对齐度最高的
#     ⑥ 输出两张表：
#          target_labels   每个正样本该学哪个类
#          target_scores   每个正样本的软标签（按对齐度归一化，G07）
#
#   ★ alpha=0.5、beta=6 就是 G07 那组实测数字的来源：
#     beta 大 -> IoU 主导 -> "框准"比"分数高"更重要。


# ============================================================
# 四、第二步：分类损失（BCE + 软标签）
# ============================================================
#   loss.py:470 那一行：
#
#     loss[1] = bce_loss.sum() / target_scores_sum
#
#   拆开看：
#
#     ① self.bce = nn.BCEWithLogitsLoss(reduction="none")
#        对 8400 个位置 × 80 个类，逐个算"预测 vs 目标"的二元交叉熵
#
#     ② 目标的构成：
#        正样本位置：软标签（比如 0.559、1.000、0.025），不是 1
#        背景位置  ：全 0
#
#     ③ 全部加起来，除以 target_scores_sum（正样本软标签之和）
#
#   ★ 为什么除以它？
#     因为每张图的目标数量不同（有的 1 个、有的 30 个）。
#     不除的话，目标多的图 loss 天然更大，梯度尺度不稳定。
#     除掉之后，loss 大致是"平均每个正样本的损失"。
#
#   ★ 为什么背景位置也要算？
#     它们的目标是 0，算损失相当于"反复告诉模型这里是背景"。
#     G01 说的"全猜背景就能 99% 准确"的问题，
#     就是靠"软标签 + 归一化 + 只对正样本算框损失"三者一起缓解的。


# ============================================================
# 五、第三步：框损失（只对正样本）
# ============================================================
#   loss.py:473：
#
#     loss[0], loss[2] = self.bbox_loss(pred_dist, ...)
#
#   两个分量：
#
#     loss[0]  CIoU 损失 = 1 - CIoU
#              CIoU 同时考虑重叠、中心距离、长宽比（G05）
#
#     loss[2]  距离的 L1 误差
#              直接约束"四个距离的数值"，是 CIoU 的补充
#
#   ★ 关键：**它们只对正样本位置计算。**
#     8400 个位置里只有几十个是正样本，其余位置不参与框损失。
#
#     这就是为什么检测损失和分类损失长得不一样：
#       分类：8400 个位置全算
#       框  ：只算几十个正样本
#
#   ★ 还有一个小细节：CIoU 是对"预测框和 GT 框"算的，
#     但预测框在解码时要减去对齐点（G06 的 dist2bbox）。
#     所以代码里会先 bbox_decode，再算 IoU。


# ============================================================
# 六、完整的一次训练步（把 H05~H08 串起来）
# ============================================================
#   ① 前向：图 -> 24 层 -> {"boxes":..., "scores":...}（H06）
#      训练时返回两套（one2many / one2one，H07）
#
#   ② 分配：对每套头，用 TaskAlignedAssigner 选出正样本
#      得到 target_labels / target_scores
#
#   ③ 算损失：
#        cls : BCE(预测分数, 软标签) / 软标签总和        -> × 0.5
#        box : 1 - CIoU(预测框, GT)                      -> × 7.5
#        l1  : |预测距离 - GT距离|                       -> × 1.5
#
#   ④ 三部分相加 -> 标量 loss
#
#   ⑤ loss.backward() -> 梯度回填（A05）
#
#   ⑥ optimizer.step() -> 更新参数（B09）


# ============================================================
# 七、为什么损失函数这么复杂
# ============================================================
#   对比分类任务：一个交叉熵就够了。
#
#   检测多了三件事，所以损失也多了三块：
#
#     ① 输出数量不定  -> 必须先分配（哪些预测该学谁）
#     ② 同时要管定位和分类 -> 两个损失项，还要配权重
#     ③ 正负样本极不平衡 -> 软标签、归一化、只对正样本算框损失
#
#   ★ 换句话说：检测损失函数的复杂度，
#     全是为了解决 G01 列出的那三个困难。
#     如果你觉得它绕，那说明你还记得分类任务有多简单 —— 这是好事。


