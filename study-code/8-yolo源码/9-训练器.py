# H09：训练器 —— 一个 epoch 到底做了什么
#
# 【这一课要讲清楚的一件事】
#
#   前面几课都是"模型内部"。这一课跳出来看整个训练循环：
#   一个 epoch 里，数据、梯度、权重、学习率各自发生了什么。
#
#   engine/trainer.py 有 1305 行，但核心流程只有一条线。


# ============================================================
# 一、一个 epoch 的骨架
# ============================================================
#   for epoch in range(epochs):
#       model.train()                       # 切训练模式（BN 用批次统计量）
#       for batch in train_loader:          # 逐批
#           ...前向、损失、反向、更新...      # 见第二节
#       model.eval()                        # 切推理模式
#       metrics = validate(val_loader)      # 用 EMA 权重验证
#       save_if_best(metrics)               # 保存最好的一次
#
#   ★ 注意"用 EMA 权重验证"这件事 —— 第五节会解释。


# ============================================================
# 二、一个 batch 里发生的六件事
# ============================================================
#   ① 预处理：把图片变成张量（LetterBox、归一化 — G04）
#
#   ② 前向 + 算损失
#        loss, loss_items = self.model(batch)      # trainer.py:557
#      ★ 注意参数是 batch 字典，不是张量。
#        传字典时，模型的 forward 会走"算损失"那条路；
#        传张量时，只返回预测结果。这是 ultralytics 的一个约定。
#
#   ③ 反向（AMP 放大版）
#        self.scaler.scale(self.loss).backward()   # :574
#
#   ④ 判断是否到了"更新点"
#        if ni - last_opt_step >= self.accumulate:  # :611
#            self.optimizer_step()
#
#   ⑤ 更新权重（含 EMA）
#        def optimizer_step():
#            self.scaler.unscale_(self.optimizer)  # 把放大过的梯度除回来
#            ...
#            self.scaler.step(self.optimizer)      # 真正更新
#            self.scaler.update()                  # 调整放大倍数
#            self.ema.update(self.model)           # 更新影子权重
#
#   ⑥ 记录日志（loss、学习率、显存）


# ============================================================
# 三、梯度累积：为什么 batch=8 却有 64 的效果
# ============================================================
#   default.yaml 里有个参数：
#     nbs: 64    nominal batch size（名义批量）
#
#   trainer.py:325：
#     self.accumulate = max(round(self.args.nbs / self.batch_size), 1)
#
#   实测：batch=8 -> accumulate = round(64 / 8) = 8
#
#   ★ 意思：**攒 8 个 batch 的梯度，才更新一次权重。**
#
#     第 1 个 batch：反向，梯度累加（不清零）
#     第 2 个 batch：反向，梯度继续累加
#     ...
#     第 8 个 batch：累加够了 -> optimizer.step() -> 清零
#
#   效果上相当于 batch=64（梯度是 64 张图的平均），
#   但显存只需要 8 张的（E07 讲的激活值）。
#
#   ★ 为什么这么做？
#     大 batch 的梯度更稳（噪声小），小 batch 省显存。
#     累积就是"既要稳、又要省"的折中。
#
#   注意一个细节（trainer.py:326）：
#     weight_decay 也会跟着调整：
#       weight_decay * batch_size * accumulate / nbs
#     因为更新次数变少了，正则化的强度要相应补偿。


# ============================================================
# 四、AMP：三步走
# ============================================================
#   default.yaml: amp: True。所以每个 batch 实际是：
#
#     ① scale  ：把 loss 乘一个大数（比如 1024），
#                 这样反向算出来的梯度也在可表示范围内（E07）
#     ② backward：用放大后的 loss 反向
#     ③ unscale：更新前把梯度除回来
#     ④ step   ：真正更新参数
#     ⑤ update ：根据有没有出现 inf/nan，调整放大倍数
#
#   ★ 这就是 E07 讲的 GradScaler，只是这里是源码里的实际调用。
#
#   注意：如果设 amp: "bf16"，就不需要 scaler（BF16 范围够大）。


# ============================================================
# 五、EMA：为什么还要维护一份"影子权重"
# ============================================================
#   训练时会有两份权重：
#
#     训练权重    self.model     每步都在动，抖动大
#     影子权重    self.ema.ema   训练权重的滑动平均，平滑
#
#   更新公式（指数移动平均）：
#     shadow = decay × shadow + (1 - decay) × trained
#     decay 一般在 0.999 以上
#
#   ★ 为什么要它？
#     训练后期的权重在最优解附近来回跳，
#     平均值往往比"最后一步"更接近真正的最优点。
#
#   ★ 验证用的是 EMA 权重（trainer.py:664 的 validate 内部取 self.ema.ema）。
#     所以你在日志里看到的 mAP，是"平滑后的模型"的成绩，
#     不是当前训练权重的成绩。
#
#   这也是为什么"训练 loss 很好但保存的模型效果一般"有时会发生：
#   保存的是 EMA 权重，不是你最后一步的权重。


# ============================================================
# 六、学习率：先热身，再慢慢降
# ============================================================
#   默认设置：
#     lr0: 0.01        初始学习率
#     lrf: 0.01        最终学习率 = lr0 × 0.01 = 0.0001
#     warmup_epochs: 3 前 3 个 epoch 热身
#     cos_lr: False    默认线性衰减（不是余弦）
#
#   学习率曲线长这样：
#
#     lr
#      │      ╱‾‾‾‾‾‾‾‾‾‾╲
#      │    ╱              ╲
#      │  ╱                  ╲___
#      └────────────────────────── epoch
#        0  3                100
#        └warmup┘  └──线性衰减──┘
#
#   ★ 热身是为了"别一上来就把预训练权重冲坏"：
#     前几个 epoch 学习率从很小慢慢升到 lr0。
#
#   ★ 后期衰减是为了"收敛得更细"：
#     学习率大时在最优解附近来回跳，小了才能落进去。


# ============================================================
# 七、验证与保存
# ============================================================
#   每个 epoch 结束后：
#
#     ① 切 eval 模式，用 EMA 权重在验证集上跑一遍
#     ② 算 mAP50 和 mAP50-95（G09）
#     ③ 用两者加权得到 fitness：
#          fitness = 0.1 × mAP50 + 0.9 × mAP50-95
#        ★ 所以"best.pt"是按 mAP50-95 选的，不是按 mAP50。
#     ④ 如果比之前好 -> 保存 best.pt
#     ⑤ 每轮都保存 last.pt（用于断点续训）
#
#   另外两个值得知道的参数：
#     patience: 100        连续 100 轮没提升就早停
#     close_mosaic: 10     最后 10 轮关掉 Mosaic 增强
#                          （因为 Mosaic 拼出来的图与真实分布不同，
#                            收尾要换成真实图，让模型适应）


# ============================================================
# 八、为什么"box_loss 一直降，mAP 却不涨"
# ============================================================
#   这是最常见的困惑。四个原因，按概率排序：
#
#   ① 过拟合
#      loss 是训练集上的，mAP 是验证集上的。
#      训练集记住了，验证集没学会 —— 看 E02 的诊断方法。
#
#   ② 验证集和训练集分布不同
#      比如验证集图片尺寸、光照、场景和训练集差很远。
#
#   ③ 权重不平衡
#      box 权重 7.5、cls 0.5（H08）。
#      如果 box_loss 降得很猛而 cls_loss 不动，
#      说明模型在狂调框，但类别分不清 —— mAP 涨不动。
#      这时该看的是"两个 loss 的比例"，不是总和。
#
#   ④ 标签有问题
#      G03 讲的五种错误，都会表现为"loss 降但 mAP 不涨"。
#
#   ★ 诊断顺序：先看两类 loss 的比例 -> 再看训练/验证 gap -> 最后查标签。


