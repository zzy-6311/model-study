# H05：parse_model —— 51 行 yaml 怎么变成 24 层网络
#
# 【这一课要讲清楚的一件事】
#
#   yolo26.yaml 只有 51 行，每行长这样：
#
#     [-1, 2, C3k2, [256, False, 0.25]]
#
#   这四个字段是什么意思？它怎么变成真正的 PyTorch 模块？
#   为什么同一个 yaml 能生成 n/s/m/l/x 五种大小的模型？
#
#   答案全在 nn/tasks.py 第 2055 行的 parse_model 里。


# ============================================================
# 一、一行的四个字段
# ============================================================
#   [-1, 2, C3k2, [256, False, 0.25]]
#    │   │   │      │
#    │   │   │      └─ args：构造参数（第 0 个是输出通道）
#    │   │   └──────── module：模块类名
#    │   └──────────── repeats：重复几次
#    └──────────────── from：输入来自哪一层
#
#   ★ from = -1 表示"上一层"。
#     如果是 [16, 19, 22]，表示"取第 16、19、22 层的输出"（Detect 就这么用）。
#     如果是 [-1, 6]，表示"把上一层和第 6 层拼起来"（Concat 就这么用）。


# ============================================================
# 二、parse_model 对每一行做五件事
# ============================================================
#   for i, (f, n, m, args) in enumerate(d["backbone"] + d["head"]):
#
#     ① 找到模块类
#        m = globals()[m]        # "C3k2" 这个字符串 -> C3k2 这个类
#        （如果是 "nn.Upsample"，就从 torch.nn 里取）
#
#     ② depth 缩放：重复次数
#        n = max(round(n * depth), 1) if n > 1 else n
#
#     ③ width 缩放：输出通道
#        c2 = make_divisible(min(c2, max_channels) * width, 8)
#
#     ④ 把输入通道插到参数最前面
#        args = [c1, c2, *args[1:]]
#
#     ⑤ 实例化，并记录"这一层的输出要保留吗"
#        m_ = m(*args)  （要重复的话包成 Sequential）
#        ch.append(c2)  并把输出通道记下来，供下一行用
#
#   ★ 核心就是这五步。整个 24 层网络，就是把 yaml 的 24 行各跑一遍。


# ============================================================
# 三、depth 缩放：重复次数
# ============================================================
#   n 的缩放规则很简单：
#
#     n = max(round(n * depth), 1)  如果原来的 n > 1
#     n 保持原样                     如果原来的 n == 1
#
#   yolo26n 的 depth = 0.50，所以：
#
#     yaml 写 2 -> round(2 × 0.5) = 1 次
#     yaml 写 1 -> 保持 1 次
#
#   ★ 这就是为什么同一个 yaml，n 版本只有 24 层，
#     而 l 版本（depth=1.0）有 392 层（含重复展开的子层）。
#
#   注意"如果 n > 1"这个条件：因为 n=1 的层多半是结构性层
#   （比如下采样 Conv、Concat、Detect），它们不该被缩放。


# ============================================================
# 四、width 缩放：输出通道
# ============================================================
#   c2 = make_divisible(min(c2, max_channels) * width, 8)
#
#   三层意思：
#     ① min(c2, max_channels)  先按上限截断
#     ② × width                再乘宽度的缩放系数
#     ③ make_divisible(_, 8)   取整到 8 的倍数
#
#   yolo26n 的 width = 0.25，max_channels = 1024，所以：
#
#     yaml 写 64   -> 64 × 0.25 = 16      -> 16
#     yaml 写 256  -> 256 × 0.25 = 64     -> 64
#     yaml 写 512  -> 512 × 0.25 = 128    -> 128
#     yaml 写 1024 -> 1024 × 0.25 = 256   -> 256
#
#   ★ 为什么取 8 的倍数？
#     GPU 的向量化指令按 8 或 16 对齐更高效。
#     比如算出 25，会取到 32；算出 33，会取到 40。
#
#   ★ 为什么要有 max_channels？
#     m/l/x 版本的 width 会到 1.0~1.5，
#     1024 × 1.5 = 1536 太大了，所以用 max_channels 卡住（m/l/x 是 512）。


# ============================================================
# 五、from 字段怎么变成真正的连接
# ============================================================
#   网络不是一条直线，有跨层连接。from 记录了三种情况：
#
#   ① -1          上一层
#        最常见的写法。第 i 层的输入就是第 i-1 层的输出。
#
#   ② n（单个正数） 前面某一层
#        比如 yaml 里 [-1, 6] 里的 6。
#
#   ③ [a, b, c]   多层
#        比如 Concat 的 [[-1, 6], 1, Concat, [1]]
#             表示"把上一层和第 6 层沿通道拼起来"
#        比如 Detect 的 [[16, 19, 22], 1, Detect, [nc]]
#             表示"取三个尺度的特征图"
#
#   ★ 关键：**被引用的层，它的输出必须被保留下来。**
#     否则网络跑到第 20 层时，第 6 层的输出早就被丢掉了。
#     这就是下一节 save 列表的作用。


# ============================================================
# 六、save 列表：哪些输出要留着
# ============================================================
#   源码第 2258 行：
#
#     save.extend(x % i for x in ([f] if isinstance(f, int) else f) if x != -1)
#
#   翻译成人话：
#     对这一行的 from 字段（单个或列表），
#     把每个正数的层号记进 save 列表。
#
#   最后 return 的时候：
#     return torch.nn.Sequential(*layers), sorted(save)
#
#   ★ 前向时（H06 会讲），程序按 save 列表决定"这一层的输出要存到 y 里"。
#     存下来的 y[6]、y[16]、y[19]、y[22]，
#     就是后面 Concat 和 Detect 要去取的东西。


# ============================================================
# 七、实测：几行 yaml 的真实结果
# ============================================================
#   yaml 行                                -> 实际生成的模块
#   ------------------------------------------------------------------
#   [-1, 1, Conv, [64, 3, 2]]              -> Conv(3 -> 16, 3×3, 步长2)
#   [-1, 2, C3k2, [256, False, 0.25]]      -> C3k2(32 -> 64, 重复1, c3k=False)
#   [-1, 1, Conv, [1024, 3, 2]]            -> Conv(128 -> 256, 3×3, 步长2)
#   [-1, 2, C2PSA, [1024]]                 -> C2PSA(256 -> 256, 重复1)
#   [-1, 1, C3k2, [1024, True, 0.5, True]] -> C3k2(384 -> 256, c3k=True, attn=True)
#   [[16,19,22], 1, Detect, [nc]]          -> Detect(80, reg_max=1, end2end, [64,128,256])
#
#   ★ 注意最后一行：yaml 里只写了 [nc]，
#     但实际传进去的是 [80, 1, True, [64, 128, 256]]。
#     后面那三个是 parse_model 自动补的：
#
#       args.extend([reg_max, end2end, [ch[x] for x in f]])
#                     ↑         ↑          ↑
#                     1        True      三个尺度的通道数
#
#     所以阅读源码时，Detect 的参数不能只看 yaml ——
#     它有一部分是代码补进去的。


# ============================================================
# 八、这个机制带来的三个直接影响
# ============================================================
#   ① 改结构 = 改 yaml
#      想删掉 C2PSA？把第 10 行删掉，或者注释掉。
#      想多一个尺度？加一层。
#
#   ② 改规模 = 改 scales 里的三个数
#      n: [0.50, 0.25, 1024]   ->  depth 0.5 / width 0.25 / 上限 1024
#      改成 [0.75, 0.35, 1024] 就得到一个介于 n 和 s 之间的模型。
#
#   ③ 改类别数 = 改 nc
#      nc: 80 -> 1，检测头的分类分支自动从 80 通道变成 1 通道。
#
#   ★ 这也解释了为什么"YOLO 换股票/换场景只要改配置文件" ——
#     结构本身是数据驱动的。


# ============================================================
# 九、这一课要记住的三句
# ============================================================
# 1. yaml 一行四个字段：from、repeats、module、args。
#    parse_model 把这 24 行分别实例化成模块，串成 Sequential。
#
# 2. 同一个 yaml 能生成五种大小，靠的是 depth 缩放重复次数、
#    width 缩放通道数（并取整到 8 的倍数）。
#
# 3. from 引用了哪些层，那些层的输出就必须被 save 下来。
#    这是跨层连接能工作的前提。

