# H07：Detect 检测头 —— 为什么有两套
#
# 【这一课要讲清楚的一件事】
#
#   打开 yolo26n 的检测头，会发现它有两份一模一样的卷积：
#
#     cv2 / cv3                  （one-to-many）
#     one2one_cv2 / one2one_cv3  （one-to-one，是上面那份的复制）
#
#   为什么要搞两份？因为**训练要的和推理要的，是相反的事**。


# ============================================================
# 一、训练要"多"，推理要"少"
# ============================================================
#   【训练】一个真实框，希望有多个位置来学它
#     理由：样本多、梯度多、学得快（G07 讲的 TopK=10）
#     副作用：一个物体会被好几个位置同时预测 -> 推理时会重复
#
#   【推理】希望一个物体只出一个框
#     否则要靠 NMS 去重（G08），而 NMS 有自己的代价
#
#   ★ 用一个头同时满足这两个需求，是矛盾的：
#     训练时让它"多个位置都能答对"，推理时就必然"多个位置都答"。
#
#   所以 YOLO26 干脆训练两个头：
#
#     one2many  一个 GT 带 10 个正样本   学得充分
#     one2one   一个 GT 只带 1 个正样本   输出天然不重复


# ============================================================
# 二、结构上怎么实现：就是复制一份
# ============================================================
#   head.py 第 144 行：
#
#     if end2end:
#         self.one2one_cv2 = copy.deepcopy(self.cv2)
#         self.one2one_cv3 = copy.deepcopy(self.cv3)
#
#   ★ 就是这么直接：把两个分支的卷积层复制一份。
#
#   实测参数（yolo26n）：
#     one2many 分支（cv2+cv3）  154,828
#     one2one  分支（复制品）   154,828
#     ----------------------------------
#     Detect 总计               309,656
#
#   ★ 也就是说：**检测头有一半的参数是"为了推理时能免掉 NMS"而多花的。**
#     这笔账要算清楚 —— 它不是白来的。


# ============================================================
# 三、训练时怎么走：两个分支都算损失
# ============================================================
#   head.py 第 199~206 行：
#
#     preds = self.forward_head(x, **self.one2many)
#     if self.one2one_cv2 is not None:
#         x_detach = [xi.detach() for xi in x] if self.training else x
#         one2one = self.forward_head(x_detach, **self.one2one)
#         preds = {"one2many": preds, "one2one": one2one}
#     if self.training:
#         return preds
#
#   两个细节：
#
#   ① 两个分支**都送进损失函数**（loss.py 里的 E2ELoss 会分别算）
#      所以同一个目标，两个头都从它身上学。
#
#   ② one2one 分支的输入是 **detach 过的**
#      detach 的意思是"梯度到此为止，不再往前传"。
#      所以 one2one 头自己的参数能学，但它的梯度**不会回传到 backbone**。
#      目的：不让两套头的梯度在 backbone 里打架。


# ============================================================
# 四、推理时怎么选：一个开关
# ============================================================
#   head.py 第 207 行：
#
#     y = self._inference(preds["one2one" if self.end2end else "one2many"] ...)
#
#   选哪个由 self.end2end 决定。而这个属性的定义（第 158 行）：
#
#     @property
#     def end2end(self):
#         return (self.one2one_cv2 is not None
#                 and (self._end2end or self.cv2 is None))
#
#   ★ 关键：**光有 one2one_cv2 还不够，还要 _end2end 这个开关打开。**
#     打开的方式是 model.end2end = True（tasks.py:572 的 setter）。
#
#   实测：yaml 里写着 end2end: True，但刚建出来的模型
#         head.end2end 是 False。
#
#   ★ 所以有两个层次，别混：
#     ① yaml 的 end2end: True  -> 决定"要不要建两套头"
#     ② 运行时的 _end2end 开关 -> 决定"推理用哪一套"
#
#     这也是 D08 提到的那件事：
#     "函数名叫 non_max_suppression，不代表一定执行了 NMS"。


# ============================================================
# 五、三种模式，三种行为
# ============================================================
#   【训练 training=True】
#     返回 {"one2many": ..., "one2one": ...}
#     两个都是原始张量（没有 sigmoid、没有解码），留给损失函数用
#
#   【推理 training=False】
#     只算被选中的那一路（省一半计算）
#     然后：
#       距离 -> xyxy（dist2bbox）
#       类别 logits -> sigmoid
#       拼成 [B, 4+nc, 8400]
#
#   【导出 export=True】
#     只返回张量，不返回元组
#     因为 ONNX 的计算图里不能有"多返回值"这种 Python 结构
#
#   ★ 同一份代码，靠 self.training / self.export 两个标志切换行为。
#     这是 PyTorch 的惯例（C07 讲的 train/eval 也是这个机制）。


# ============================================================
# 六、代价与取舍
# ============================================================
#   多花 154,828 参数（占全模型 6%），换来：
#     推理时不需要 NMS -> 后处理更快、结果更稳定
#
#   ★ 什么时候值得？
#     目标多、框密集的场景（比如人群检测），NMS 会成为瓶颈，值得。
#     目标少、简单场景，NMS 本来就很快，可能不值得。
#
#   这也是为什么"免 NMS"不是一个无条件的优点：
#   它用参数换掉了一段后处理代码。


# ============================================================
# 七、这一课要记住的三句
# ============================================================
# 1. 检测头有两套：one2many（训练要的多正样本）和
#    one2one（推理要的不重复）。多花 15 万参数换掉 NMS。
#
# 2. 训练时两套都算损失，但 one2one 的输入被 detach，
#    梯度不回传 backbone。
#
# 3. yaml 里的 end2end: True 只决定"建不建两套头"，
#    推理时用哪一套由运行时开关决定。

