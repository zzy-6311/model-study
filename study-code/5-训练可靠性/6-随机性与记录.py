# E06：随机性、可复现、实验记录
#
# 【这一课解决什么问题】
#   同一份代码、同一份数据，跑两次，准确率一个 91.2% 一个 89.5%。
#   这 1.7% 是"我改的东西起作用了"，还是随机波动？
#
#   分不清这两者，所有实验结论都不可信。


# ============================================================
# 一、随机从哪里来
# ============================================================
# 训练里的随机源至少有五个，任何一个没固定，结果就会变：
#
#   ① 参数初始化        每次创建层都是随机数
#   ② 数据打乱顺序       每个 epoch 的批次组成不同
#   ③ Dropout           每次前向随机丢弃不同的神经元
#   ④ 数据增强          随机裁剪、旋转、颜色抖动
#   ⑤ 多进程数据加载     多个 worker 各自有随机状态
#
# 另外还有两个"隐藏的"：
#   ⑥ 浮点求和的顺序     多线程并行累加，线程数不同结果就会差最后几位
#   ⑦ cuDNN 的算法选择    GPU 上某些算子有多个实现，运行时会挑，挑哪个不一定


# ============================================================
# 二、实测：设种子到底有用多少
# ============================================================

import torch
import torch.nn as nn

torch.manual_seed(1234)          # 先把造数据这一步固定，保证每次运行都看到同样的数字
X = torch.randn(200, 20)
y = torch.randint(0, 5, (200,))
loss_fn = nn.CrossEntropyLoss()


def run(seed=None, steps=100):
    if seed is not None:
        torch.manual_seed(seed)
    model = nn.Sequential(nn.Linear(20, 32), nn.ReLU(), nn.Linear(32, 5))
    opt = torch.optim.Adam(model.parameters(), lr=0.01)
    for _ in range(steps):
        opt.zero_grad()
        loss = loss_fn(model(X), y)
        loss.backward()
        opt.step()
    return model[0].weight.detach().clone(), loss.item()


print("=" * 62)
w1, l1 = run(42)
w2, l2 = run(42)
print("一、同一个种子跑两次")
print("  最大权重差 =", (w1 - w2).abs().max().item())
print("  loss      =", round(l1, 6), round(l2, 6))

w3, l3 = run(None)
w4, l4 = run(None)
print("二、不设种子跑两次")
print("  最大权重差 =", round((w3 - w4).abs().max().item(), 6))
print("  loss      =", round(l3, 6), round(l4, 6))
print("  loss 相差 =", round(abs(l3 - l4), 6))

# 输出：
#   同一个种子：权重差 0.0，loss 完全相同（0.033592）
#   不设种子  ：权重差 1.956，loss 分别是 0.035427 / 0.037930
#
# ★ 注意第二组：权重差了 1.956（比权重本身还大），
#   但 loss 只差 0.0025。
#
#   这不是 bug，是 A10 讲过的"解不唯一"：
#   这类问题有大量等效解，不同的初始化和数据顺序会走到不同位置，
#   但表现几乎一样。
#
#   反过来也要警惕：
#   "两次 loss 差不多" 不代表 "两个模型一样"，
#   它们可能是完全不同的两组参数。


# ============================================================
# 三、数据顺序的影响有多大
# ============================================================
# 同一个数据集，不同种子打乱出来的顺序，几乎完全不重合：

torch.manual_seed(0)
perm_a = torch.randperm(200)
torch.manual_seed(1)
perm_b = torch.randperm(200)
print()
print("=" * 62)
print("三、打乱顺序")
print("  seed=0 前 10 个:", perm_a[:10].tolist())
print("  seed=1 前 10 个:", perm_b[:10].tolist())
print("  完全相同的比例 =", round((perm_a == perm_b).float().mean().item(), 4))

# 输出：完全相同的比例 0.005（也就是 0.5%，基本就是巧合）
#
# 所以"忘了固定数据顺序"，等于每次都在用不同顺序训练。
# 那 1~2 个百分点的差异，很可能全是顺序带来的。


# ============================================================
# 四、"可复现"有三个层次，别搞混
# ============================================================
# ① 逐位相同（bitwise）
#    两次运行的每一个浮点数都完全一样。
#    同一台机器、同一版本、单线程，设了种子通常能做到。
#    换机器、换版本、换线程数，基本做不到（浮点加法顺序变了）。
#
# ② 统计等价
#    多次运行的指标分布一致（均值、方差都接近）。
#    这是做实验真正需要的：你能区分"改进"和"波动"。
#
# ③ 结论可重复
#    换一个种子、换一批数据，结论仍然成立。
#    这是科研标准，也是工程上最该追求的。
#
# ★ 很多人卡在第 ① 层，为了"完全复现"去开确定性模式，
#   结果训练慢了一倍，却没解决"结论稳不稳"的问题。


# ============================================================
# 五、想要更强的确定性，代价是什么
# ============================================================
# PyTorch 提供 torch.use_deterministic_algorithms(True)，
# 强制所有算子用确定性实现。
#
#   好处：同一机器上结果更稳定
#   代价：
#     某些算子没有确定性实现，会直接报错
#     GPU 上会强制关掉一些快速算法，训练变慢
#
# 更实用的做法（大多数项目的默认设置）：
#   固定种子
#   固定数据划分
#   用 num_workers=0 或给每个 worker 设种子
#   然后接受"最后几位会变"，用多次运行的均值和方差来做判断


# ============================================================
# 六、实验记录：记什么
# ============================================================
# 只记"准确率 91.2%"是没有用的，因为下次你复现不出来。
#
# 至少要记：
#   ① 代码版本（git commit）
#   ② 依赖版本（PyTorch、CUDA、Ultralytics）
#   ③ 随机种子
#   ④ 数据划分（哪份数据做验证集，最好把索引存下来）
#   ⑤ 完整超参数（lr、batch、epoch、优化器、scheduler）
#   ⑥ 运行命令
#   ⑦ 指标：不只记最好的一次，记几个种子的均值±方差
#   ⑧ 硬件（GPU 型号、驱动）
#
# 一个可用的最小模板：
#
#   date:      2026-11-17
#   commit:    aaa2589
#   env:       torch 2.9.1+cu128 / python 3.12.7 / RTX 4060
#   data:      mnist, val_split=seed42_10000
#   seed:      0,1,2
#   config:    lr=0.01 bs=64 epochs=10 Adam
#   result:    val_acc = 98.31% ± 0.12%
#
# ★ 关键在最后那个"±"：跑三个种子，报均值和方差。
#   没有方差，你根本不知道自己报的数字有多大不确定性。


# ============================================================
# 七、怎么判断"改进"是真的
# ============================================================
# 假设原方案 89.5%，新方案 91.2%。
#
#   步骤 1：两个方案各跑 3 个种子
#   步骤 2：看均值和方差
#           原方案 89.5 ± 0.4
#           新方案 91.2 ± 0.3
#           -> 差距 1.7 远大于波动 0.4，可以认为是真的
#
#   如果：
#           原方案 89.5 ± 1.2
#           新方案 91.2 ± 1.1
#           -> 差距还在波动范围内，不能下结论
#
# 这就是"一次实验不算数"的数学理由，不是保守，是必要的。


# ============================================================
# 八、这一课要记住的三句
# ============================================================
# 1. 随机源有五个以上，只固定"模型初始化"是不够的。
#    数据顺序、Dropout、增强、worker 都要管。
#
# 2. "权重差 1.9，loss 只差 0.0006" 是正常的——
#    这类问题有大量等效解。所以别用"loss 差不多"去判断"模型一样"。
#
# 3. 判断改进要看"均值 ± 方差"，至少三个种子。
#    单次实验的 1% 差异，很可能只是随机波动。

