# E02：过拟合与欠拟合
#
# 【这一课解决什么问题】
#   训练准确率 100%，验证准确率 58%。这是好事还是坏事？
#
#   要分清两种情况，它们的处理方向完全相反：
#     欠拟合: 模型没学会 -> 应该加大模型 / 训练更久
#     过拟合: 模型背了答案 -> 应该加数据 / 加正则 / 减小模型
#
#   搞反了会越调越差。


# ============================================================
# 一、用两条曲线判断四种状态
# ============================================================
#           训练集      验证集      结论        该怎么办
#   ------------------------------------------------------------------
#   1       差          差          欠拟合      加大模型、训练更久、调 lr
#   2       好          好          正常        继续
#   3       很好        差          过拟合      加数据、加正则、早停
#   4       差          更差        有 bug      查数据管道（大概率不是训练问题）
#
# 关键看的是"两条曲线之间的差距"，而不是某一条的绝对值。
#
# 训练 99% / 验证 70%  ->  差距大，过拟合
# 训练 70% / 验证 68%  ->  差距小，但都不高，欠拟合
#
# 同一个"70%"，含义完全不同


# ============================================================
# 二、实测：让模型去学"不存在的规律"
# ============================================================
# 造 200 个样本，标签完全是随机抽的 —— 数据里没有任何可学的东西。
# 任何模型在这份数据上的理论正确率都应该接近 50%。
#
# 但训练集给 150 个，模型有几千个参数，会发生什么？

import torch
import torch.nn as nn

torch.manual_seed(0)

N, D = 200, 20
X = torch.randn(N, D)
y = torch.randint(0, 2, (N,))          # 随机标签

Xtr, ytr = X[:150], y[:150]
Xva, yva = X[150:], y[150:]

net = nn.Sequential(nn.Linear(D, 128), nn.ReLU(), nn.Linear(128, 2))
opt = torch.optim.Adam(net.parameters(), lr=0.01)
loss_fn = nn.CrossEntropyLoss()


def acc(model, x, t):
    return (model(x).argmax(dim=1) == t).float().mean().item()


print("=" * 60)
print("一、随机标签上的训练（不存在可学规律）")
print(f"{'step':>6} {'训练loss':>10} {'训练acc':>9} {'验证loss':>10} {'验证acc':>9}")

for step in range(1, 601):
    opt.zero_grad()
    loss = loss_fn(net(Xtr), ytr)
    loss.backward()
    opt.step()
    if step % 100 == 0 or step == 1:
        vl = loss_fn(net(Xva), yva).item()
        print(f"{step:>6} {loss.item():>10.5f} {acc(net, Xtr, ytr):>9.3f}"
              f" {vl:>10.5f} {acc(net, Xva, yva):>9.3f}")

# 输出：
#    step  训练loss   训练acc    验证loss   验证acc
#       1  0.66804     0.647    0.71912     0.480
#     100  0.00083     1.000    2.31472     0.600
#     200  0.00034     1.000    2.52831     0.600
#     300  0.00019     1.000    2.67834     0.580
#     400  0.00012     1.000    2.79513     0.580
#     500  0.00008     1.000    2.89157     0.580
#     600  0.00006     1.000    2.97178     0.580
#
# 三件事同时发生：
#   ① 训练 loss 一路降到 0.00006，训练准确率 100%
#   ② 验证 loss 一路上"升"到 2.97
#   ③ 验证准确率一直卡在 50%~58% —— 就是瞎猜的水平
#
# 模型把 150 个样本全部背下来了，一个规律都没学到（因为根本没有规律）。
# 这就是过拟合的极端形态：
#
#   训练 loss 下降，只说明"模型记住了训练集"，
#   完全不说明"模型学会了规律"。


# ============================================================
# 三、过拟合的本质
# ============================================================
# 参数远多于样本时，模型总能找到一组参数，把训练集"精确拟合"。
# 这时候它拟合的不是规律，而是"每个样本独有的噪声"。
#
# 判断标准不是"参数量多不多"，而是：
#   训练集和验证集的表现差距有多大。
#
#   参数多 + 数据多     -> 不一定过拟合
#   参数少 + 数据少     -> 也会过拟合（当数据里有噪声时）
#
# 所以"加数据"永远是最有效的解法，因为噪声在更多样本里会被平均掉。


# ============================================================
# 四、四种应对手段（按有效性排序）
# ============================================================
# ① 更多数据
#    最有效，没有之一。噪声被平均掉，规律被强化。
#    代价：要标注，最贵。
#
# ② 数据增强
#    不改标签、只改外观，等于"免费造数据"。
#    这是视觉任务里最常用的手段（下一节细讲）。
#
# ③ 正则化
#    weight decay：在损失里加一项"权重的平方和"，
#    逼权重保持小值。直观理解：权重小 -> 函数更平滑 -> 不容易记住噪声。
#
# ④ 早停与 Dropout
#    早停：验证集指标开始变差就停下，别等训练完。
#    Dropout：训练时随机丢弃神经元（C07 讲过原理），
#             防止神经元之间形成"合谋记忆"。
#
# ⑤ 减小模型
#    最后手段。参数少了自然记不住，但可能连规律也学不好。


# ============================================================
# 五、数据增强：什么能增强，什么不能
# ============================================================
# 原理：对图片做变换，但**标签不能变**。
#
#   自然图片（猫、狗、车）
#     水平翻转      可以（左边来的猫和右边来的猫是同一只）
#     小角度旋转    可以
#     随机裁剪      可以（只要还包含整个物体）
#     颜色抖动      可以
#
#   MNIST 手写数字
#     水平翻转      不行（"2" 翻转后不像任何数字）
#     大角度旋转    不行（"6" 旋转 180 度变成 "9"，标签就错了）
#     小幅平移      可以（通常在 10% 以内）
#     小角度旋转    可以（正负 10 度以内）
#     随机擦除      可以（模拟笔画残缺）
#
# ★ 判断标准只有一条：
#   "变换之后的图，人看了还认为是同一个类别吗？"
#   人会改变判断的，就不能用。
#
# 增强的另一个作用：它把"这些变换下标签不变"这个先验教给了模型，
# 相当于变相扩大了数据分布。
#
# 但要小心：验证集不能用随机增强。
# 验证要可复现、要公平，只能用确定的预处理（C07 讲过）。


# ============================================================
# 六、欠拟合怎么办（方向完全相反）
# ============================================================
# 症状：训练集和验证集都不高，而且很接近。
#
# 可能原因与对策：
#   模型太小        -> 加层、加通道
#   训练不够        -> 加 epoch（先看训练 loss 是否还在降）
#   学习率太小      -> 加大（A09 的三种曲线）
#   欠拟合也可能是数据问题：
#     标签质量差（标错的多）、特征不足以区分类别
#
# 注意：欠拟合时加正则、加 Dropout 会让情况更糟。
# 一定要先判断方向。


# ============================================================
# 七、一个判断陷阱：验证集的波动
# ============================================================
# 验证集如果只有几百个样本，准确率 ±2% 的波动完全是噪声：
#   500 个样本，错 1 个就差 0.2%
#
# 所以"这一轮验证准确率比上一轮高了 1%"，不能当成进步的证据。
# 判断要看：
#   连续 3~5 个 epoch 的趋势
#   或者多次训练的方差（固定随机种子做几次）
#
# 小验证集上的单点差异，不具备统计意义。


# ============================================================
# 八、这一课要记住的三句
# ============================================================
# 1. 判断过拟合看"训练和验证的差距"，不看单条曲线的绝对值。
#    训练 99% / 验证 70% 是过拟合；训练 70% / 验证 68% 是欠拟合。
#
# 2. 训练 loss 下降只说明"记住了训练集"，不说明"学会了规律"。
#    随机标签的实验就证明了这一点：训练 100%，验证永远 50%。
#
# 3. 数据增强的前提是"变换后标签不变"。
#    人会改变判断的变换，就不能用。

