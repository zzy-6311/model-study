# E03：初始化、梯度消失与梯度爆炸
#
# 【这一课解决什么问题】
#   有些网络从第一步就训不动：loss 不动、参数不变、准确率是瞎猜水平。
#   你可能换了学习率、换了优化器，都没用。
#
#   原因往往在更深处：梯度在往回传的时候，已经被"连乘"吃掉了
#   （或者放大到爆炸）。


# ============================================================
# 一、为什么梯度会消失或爆炸
# ============================================================
# 反向传播的链式法则就是"连乘"：
#
#   第 1 层的梯度 = 第 2 层的梯度 × 第 2 层的局部导数
#   再往前 = 再乘一层……
#
# 所以 20 层就是乘了 20 次。每个因子稍微偏离 1 一点，20 次之后：
#
#   每层 × 0.5  ->  20 层后 9.5e-07      （梯度消失）
#   每层 × 2    ->  20 层后 1.05e+06     （梯度爆炸）
#   每层 × 0.9  ->  20 层后 0.12
#   每层 × 1.5  ->  20 层后 3325
#
# 这就是核心：**不是某一层出了问题，而是"连乘"把误差放大了**。
#
# 前向传播同理：每一层乘一次权重，20 层之后激活也会爆掉或消失。


# ============================================================
# 二、实测：20 层网络的三种初始化
# ============================================================
# 搭一个 20 层、每层 64 宽、带 ReLU 的全连接网络，
# 只改初始化权重的缩放倍数，看前向激活和反向梯度。

import torch
import torch.nn as nn

torch.manual_seed(0)


def build(depth=20, width=64, scale=1.0):
    layers = [nn.Linear(64, width), nn.ReLU()]
    for _ in range(depth - 1):
        layers += [nn.Linear(width, width), nn.ReLU()]
    model = nn.Sequential(*layers)
    if scale != 1.0:
        with torch.no_grad():
            for p in model.parameters():
                p.mul_(scale)
    return model


x = torch.randn(32, 64)

print("=" * 62)
print("一、三种初始化的后果")
print(f"{'初始化':<12} {'第1层激活':>9} {'第20层激活':>10} {'首层梯度':>11} {'末层梯度':>11}")

for scale, name in ((1.0, "默认初始化"), (3.0, "权重放大3倍"), (0.1, "权重缩小10倍")):
    torch.manual_seed(0)
    model = build(20, 64, scale)

    acts = []
    h = x
    for layer in model:
        h = layer(h)
        acts.append(h.abs().mean().item())

    model.zero_grad()
    model(x).mean().backward()
    g_first = model[0].weight.grad.abs().mean().item()
    g_last = model[-2].weight.grad.abs().mean().item()

    print(f"{name:<12} {acts[0]:>9.5f} {acts[-1]:>10.5f} {g_first:>11.3e} {g_last:>11.3e}")

# 输出：
#   默认初始化      0.47869     0.04000    9.155e-11    3.194e-04
#   权重放大3倍     1.43607    30.79952    2.161e-01    1.568e-01
#   权重缩小10倍    0.04787     0.00384    7.950e-30    3.710e-05
#
# 三种情况各有毛病：
#
#   默认初始化：激活一路缩小（0.48 -> 0.04），
#              首层梯度只有 9e-11，前面 19 层基本学不动
#   放大 3 倍：激活爆到 30.8，训练会直接发散
#   缩小 10 倍：梯度 8e-30，等于 0，网络彻底死掉
#
# ★ 注意第一行：**即使用默认初始化，20 层纯 MLP 的首层梯度也只有 1e-11。**
#   这说明"初始化"只能缓解，不能根治。


# ============================================================
# 三、初始化到底在调什么
# ============================================================
# 目标是"方差保持"：让每层的输出，和输入的尺度差不多。
#
# 如果权重太小 -> 每层输出越来越小 -> 激活消失
# 如果权重太大 -> 每层输出越来越大 -> 激活爆炸
# 合适的大小 -> 输出方差约等于输入方差
#
# 推导思路（一层，输入 n 个、权重随机）：
#   输出的方差 ≈ n × 权重方差 × 输入方差
#   要让输出方差 = 输入方差，就得让 权重方差 ≈ 1/n
#   也就是 权重的标准差 ≈ 1/sqrt(n)
#
# 这就是 Xavier 初始化的核心；考虑 ReLU 会砍掉一半神经元，
# 再乘一个 sqrt(2) 的修正，就是 Kaiming 初始化。
#
# ★ 你在 B05 已经见过这个数字：
#   nn.Linear(2,1) 的权重初始化范围是 ±1/sqrt(in_features)
#   in=2 时就是 ±0.707，当时实测范围正好是 [-0.707, 0.707]。
#   那不是随便定的，就是方差保持的结果。


# ============================================================
# 四、但初始化只是缓解，不是解药
# ============================================================
# 上面第一行已经说明：即使是"正确"的初始化，
# 20 层之后首层梯度也只有 1e-11。
#
# 因为连乘的本质问题没解决：每层都会让信号衰减一点。
#
# 真正的解药是两个结构：
#
#   ① 残差连接（ResNet）
#      输出 = 输入 + 变换(输入)
#      反向传播时，梯度有一条"直接通路"回到前面，不用层层连乘。
#      这是 2015 年之后深网络能堆到上百层的根本原因。
#
#   ② BatchNorm
#      把每层输入强制拉回均值 0、方差 1。
#      不管前面怎么缩放，进入下一层的分布是稳定的。
#      所以 BN 之后，网络对初始化的敏感度大幅下降。
#
# ★ 记住这条逻辑链：
#   深层网络 -> 连乘导致梯度消失 -> 靠残差短路和 BN 稳定分布解决
#   这也是你在 YOLO 结构里看到大量 BN、以及 C3k2 里有残差分支的原因。


# ============================================================
# 五、梯度爆炸怎么处理：梯度裁剪
# ============================================================
# 现象：训练到某一步 loss 突然变成 nan，或者参数直接跳到 1e30。
#
# 原因：某个 batch 特别"难"，梯度算出来特别大，
#       一步更新就把参数推到很远，再也回不来。
#
# 梯度裁剪的做法：
#   算出梯度向量的总长度（范数）
#   如果超过阈值（比如 1.0），就按比例整体缩小到阈值
#
#   等价于：方向不变，只把步子限制在阈值内。
#
# ★ 裁剪解决的是"偶发的巨大梯度"，不解决"方差整体失衡"。
#   如果网络本身每层都在放大信号，裁剪只是按住葫芦起了瓢。
#
# 另一个常见误区：看到 loss 抖动就加裁剪。
#   抖动更常见的原因是学习率偏大或 batch 太小，先查那两个。


# ============================================================
# 六、怎么诊断
# ============================================================
# 训练前先做一次"体检"，打印每一层梯度的范数：
#
#   如果首层梯度在 1e-8 以下  ->  梯度消失，考虑残差/BN/换初始化
#   如果某层梯度突然到 1e2 以上 ->  有放大，考虑裁剪或调小 lr
#   如果全部是 0 或 None       ->  不是梯度问题，是计算图断了
#     （.detach() 用错、loss 用了 .item()、标签没参与计算）
#
# 还要看激活值：每层输出的均值、标准差是否稳定。
# 一路缩小或一路放大，都是信号失衡的证据。


# ============================================================
# 七、这一课要记住的三句
# ============================================================
# 1. 梯度是连乘出来的。每一层偏离 1 一点点，20 层后就差几个数量级。
#    这是深度网络的根本困难，不是某个 bug。
#
# 2. 合适的初始化让"权重标准差 = 1/sqrt(输入数)"，保持方差稳定。
#    nn.Linear 的默认初始化就是这个（B05 见过 ±0.707）。
#
# 3. 初始化只能缓解。真正解决靠残差连接和 BatchNorm。
#    梯度裁剪管的是"偶发爆炸"，不是根本失衡。

