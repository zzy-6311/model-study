# E01：训练出问题时，第一步该干什么
#
# 【这一课解决什么问题】
#   训练跑完了，准确率只有 40%。或者 loss 一直不降。
#   原因可能有二十种：数据错、标签错、学习率错、梯度断了、模型写错……
#
#   如果一个个试，一天就过去了。
#   这一课给一个顺序：按"数据 -> 输出 -> 损失 -> 梯度 -> 更新"从上游查到下游，
#   再加上一个五分钟就能做完的快速验证。


# ============================================================
# 一、先做完这一件事：小样本拟合
# ============================================================
# 做法：
#   取 5~10 个样本（真的只要几个）
#   关掉所有随机增强
#   训练 100 步左右
#
# 判断：
#   如果 loss 降到接近 0、这 5 个全预测对 -> 管道是通的
#   如果 loss 卡在某个值不动 -> 别急着调参，先找 bug


import torch
import torch.nn as nn

torch.manual_seed(0)

X = torch.randn(5, 20)          # 5 个样本，每个 20 维
y = torch.tensor([0, 1, 2, 3, 4])   # 5 个不同的类

net = nn.Sequential(
    nn.Linear(20, 64),
    nn.ReLU(),
    nn.Linear(64, 5),
)
opt = torch.optim.Adam(net.parameters(), lr=0.05)
loss_fn = nn.CrossEntropyLoss()

print("=" * 60)
print("一、小样本拟合")
print("模型参数 =", sum(p.numel() for p in net.parameters()), " 样本数 =", len(X))

for step in range(51):
    opt.zero_grad()
    loss = loss_fn(net(X), y)
    loss.backward()
    opt.step()
    if step in (0, 1, 2, 3, 5, 10, 20, 50):
        pred = net(X).argmax(dim=1)
        print(f"  step {step:3d}  loss = {loss.item():.6f}  预测 = {pred.tolist()}")

# 输出：
#   模型参数 = 1669   样本数 = 5
#   step   0  loss = 1.595773   预测 = [0,1,2,3,4]
#   step   1  loss = 0.657...   预测 = [0,1,2,3,4]
#   step   2  loss = 0.13...
#   step   5  loss = 0.000111
#   step  10  loss = 0.000000
#
# 1669 个参数去拟合 5 个样本，本来就该秒过。
# 所以"5 个样本都拟合不了"，一定是实现出了问题，不是模型不够强。


# ============================================================
# 二、为什么这个方法有效
# ============================================================
# 一个几万参数的模型，表达能力强到可以"记住"任意几个样本
# （这就是过拟合）。
#
# 所以：
#   训练集小到 5 个 -> 如果它能学会，说明整条链是通的
#   如果连 5 个都学不会 -> 一定是链条断了，和超参数无关
#
# 这一步能过滤掉绝大多数低级错误：
#   标签和图片错位、类别数写错、损失函数用反、梯度没传、参数没更新……
#
# 它验证不了的是泛化能力——5 个样本上 100% 不代表真实数据上 100%。
# 只验证"管道通不通"，别的什么都不验证。


# ============================================================
# 三、一个立刻能用的数字：loss 是不是 ln(类别数)
# ============================================================
# 模型在完全瞎猜时，对 C 个类别会输出均匀分布，
# 交叉熵 = -ln(1/C) = ln(C)。
#
#   5 类  -> ln(5)  = 1.609
#   10 类 -> ln(10) = 2.303
#   80 类 -> ln(80) = 4.382
#
# 所以：
#   loss 一直停在 ln(C) 附近  ->  模型什么都没学到
#                                  （学习率太小、梯度断了、或者参数根本没在更新）
#   loss 比 ln(C) 还大很多    ->  初始化或损失函数有问题
#
# 这个数比"loss 是多少"有意义得多，因为它和数据无关，
# 只和任务有关。


# ============================================================
# 四、五个检查点，按顺序查
# ============================================================
# 小样本拟合失败了，就按这个顺序查。从上游往下游，一次只查一个。

print()
print("=" * 60)
print("二、五个检查点")

# ① 数据：模型看到的到底是什么？
#    抽出第一个 batch，打印：
#      - 输入的 shape 是不是 [B, C, H, W]
#      - 输入的取值范围（0~1？还是 0~255？还是标准化后？）
#      - 标签的 shape 是不是 [B]、dtype 是不是 int64
#      - 把图片和标签一起显示出来看一眼（最有效）
#    常见问题：图片和标签错位、标签范围超过类别数、通道顺序反了
#
# ② 输出：模型的输出长什么样？
#      - logits 的 shape 是不是 [B, C]
#      - 数值范围是否夸张（比如几万），说明输出层没接好
#      - 对同一个 batch 连续算两次，结果是否一致（不一致说明有未关闭的随机层）
#
# ③ 损失：这个数合理吗？
#      - 是不是 nan / inf
#      - 是不是正好等于 ln(C)
#      - 手动把"正确类别的 logits"调高，loss 会不会下降
#        （不会下降 -> 损失函数和数据对不上）
#
# ④ 梯度：梯度有没有传回来？
#      - 每个参数的 .grad 是不是 None
#      - 梯度范数是多少（是 0 说明断了；是 1e50 说明爆炸了）
#      - 第一次 backward 之后，参数有没有变
#
# ⑤ 更新：参数真的被改了吗？
#      - 保存 step 前的参数快照，step 后对比
#      - 如果完全没变：学习率为 0、优化器没拿到参数、或者用了 .detach()
#
# ★ 这个顺序的意义：
#   前面的错了，后面的检查全是白费。
#   比如标签错了，你去调学习率、换模型，都毫无意义。


# ============================================================
# 五、一次只改一个因素
# ============================================================
# 查出问题之后，改一处、跑一次、对比一次。
#
# 反例（很常见）：
#   同时改学习率、换优化器、加数据增强、换模型 —— 结果变好了，
#   但你不知道是哪一个起的作用，下次再出问题还是一脸茫然。
#
# 正例：
#   基线跑一次记下指标 -> 只改学习率 -> 对比 -> 记下来 -> 再改下一个


# ============================================================
# 六、这一课要记住的三句
# ============================================================
# 1. 训练不对，先做"小样本拟合"：5 个样本、100 步。
#    学不会 = 管道坏了，不用往下调参。
#
# 2. loss 停在 ln(类别数) 附近 = 模型在瞎猜。
#    这个数字能立刻区分"没学到"和"学到一点但不够"。
#
# 3. 排查顺序永远是：数据 -> 输出 -> 损失 -> 梯度 -> 更新。
#    上游错了，下游的检查都没有意义。

