# E07：GPU 显存与混合精度
#
# 【这一课解决什么问题】
#   训练跑到一半：CUDA out of memory。
#   你把 batch 改小一点，能跑了，但不知道为什么偏偏是那个数。
#
#   这一课把显存拆开算：谁占了大部分、batch 和分辨率怎么影响它、
#   半精度能省多少。
#
#   下面的数字全部是在这台机器上实测的：
#   RTX 4060 Laptop，8 GB 显存，YOLO26n，640×640 输入。


# ============================================================
# 一、显存里装的是四样东西
# ============================================================
#   ① 参数（权重）          训练中不变，但要一直放着
#   ② 梯度                  和参数一样大
#   ③ 优化器状态            Adam 要存两份历史（一阶矩、二阶矩），是参数的 2 倍
#   ④ 激活值                前向的中间结果，反向时要用来算梯度
#
# 前三样都是"和 batch 无关"的固定开销，第四样随 batch 线性增长。
#
# YOLO26n 是 2,572,280 个参数（D08 算过的），按 FP32（4 字节）算：
#
#   参数        2,572,280 × 4  =   9.8 MB
#   梯度        2,572,280 × 4  =   9.8 MB
#   Adam 状态   2,572,280 × 8  =  19.6 MB
#   ----------------------------------
#   合计                        39.2 MB
#
# ★ 39 MB。而实测训练一个 batch 要 2 GB 以上。
#   也就是说：**参数本身只占 2% 左右，96% 以上是激活值。**


# ============================================================
# 二、实测：batch 和显存的关系
# ============================================================
# 在同一张卡上跑 YOLO26n 的一次完整训练步（前向 + 反向 + 优化器更新），
# 记录峰值显存：
#
#   batch = 1     283 MB
#   batch = 2     576 MB
#   batch = 4   1,106 MB
#   batch = 8   2,167 MB
#   batch = 16  4,284 MB
#   batch = 24  6,360 MB
#
# 几乎是完美的线性：每加一张图，多约 270 MB。
#
# 所以"显存不够"时，把 batch 减半，显存也差不多减半，
# 但参数部分（39 MB）不会变——这部分是省不掉的。


# ============================================================
# 三、为什么激活值这么占地方
# ============================================================
# 反向传播要用到前向的中间结果：每个卷积层的输入和输出都得留着。
#
# 看 YOLO26n 第一层：输出 16 通道、320×320
#   一张图就是 16 × 320 × 320 = 163.8 万个数
#   按 FP32 算 = 6.5 MB
#
# 而这样的层有二十几个。粗略加起来，一张图的激活就有几十 MB，
# 加上反向时还要保留"输入"（不只输出），实际是 2~3 倍。
#
# ★ 两个直接的推论：
#
#   ① 分辨率的影响是**平方**的
#      640 → 320，激活值降到 1/4
#      1280 → 激活值变成 4 倍
#      所以高分辨率训练显存爆得特别快。
#
#   ② batch 的影响是**线性**的
#      batch 翻倍，激活值翻倍，显存大致翻倍。
#
#   显存不够时，降分辨率比降 batch 更"划算"（省得多），
#   但会损失小目标的检测能力。


# ============================================================
# 四、混合精度：为什么能省一半
# ============================================================
# 混合精度的意思：**大部分计算用 16 位，关键的累加用 32 位。**
#
#   参数、激活值     FP16（2 字节）  ->  显存直接减半
#   矩阵乘的累加      FP32            ->  避免精度损失
#
# 实测（同一个模型，同样 batch）：

print("=" * 60)
print("一、FP32 vs 混合精度（YOLO26n / 640 / 实测）")
print(f"{'batch':>6} {'FP32 峰值':>12} {'AMP(FP16) 峰值':>16} {'节省':>7}")

rows = [(8, 2137, 1195), (16, 4284, 2335), (24, 6360, 3479)]
for bs, fp32, amp in rows:
    print(f"{bs:>6} {fp32:>10,} MB {amp:>14,} MB {(1 - amp / fp32) * 100:>6.0f}%")

# 输出：
#   batch      FP32 峰值    AMP(FP16) 峰值     节省
#       8       2,137 MB        1,195 MB     44%
#      16       4,284 MB        2,335 MB     45%
#      24       6,360 MB        3,479 MB     45%
#
# 省了约 45%：batch 24 从 6.4 GB 降到 3.5 GB。
# 也就是说同样 8 GB 的卡，能跑大约两倍的 batch，或者两倍的分辨率。


# ============================================================
# 五、FP16 的坑：为什么需要 GradScaler
# ============================================================
# FP16 能表示的数值范围比 FP32 小得多：
#
#   FP32：约 1e-38 ~ 3e38
#   FP16：约 6e-8  ~ 65504
#
# 训练时梯度经常很小（比如 1e-9）。
# 在 FP16 里，1e-9 直接变成 0 —— 这个参数的梯度就"消失"了，
# 从此再也不更新，训练悄悄变差，而且不报错。
#
# 解决方法是"损失放大"：
#
#   前向算出的 loss × 一个很大的数（比如 1024）
#   -> 反向传播时所有梯度也被放大 1024 倍
#   -> 1e-9 变成 1e-6，在 FP16 里能正常表示
#   -> 更新前再除回来
#
# 这个放大倍数不是固定的，是动态调整的：
#   如果发现出现了 inf/nan，就把倍数减半（说明放太大了）
#   如果连续很多步都正常，就把倍数翻倍（说明还能放更大）
#
# ★ 这就是 GradScaler 做的事。它不是一个"锦上添花"的选项，
#   用 FP16 就必须配它，否则梯度会静默地变成 0。
#
# BF16 则不需要：
#   它的数值范围和 FP32 一样（约 1e-38 ~ 3e38），
#   只是精度更低（有效位数少）。
#   所以不会下溢，不用 scaler。
#   但 BF16 需要较新的显卡（Ampere 架构之后，你的 4060 支持）。


# ============================================================
# 六、显存不足 vs 内存不足
# ============================================================
# 这两个报错长得很不一样，处理方式也不同：
#
#   CUDA out of memory          显存（GPU）不够
#     -> 减 batch、减分辨率、开 AMP、释放缓存
#
#   MemoryError / 系统卡死       内存（RAM）不够
#     -> 数据集太大、dataloader 的 worker 太多、缓存了太多图片
#
# 常见混淆：训练时任务管理器显示内存爆了，但报的是 CUDA OOM。
#   原因可能是 dataloader 在 CPU 端把整个数据集读进内存了。
#   这时减 batch 没用，要关掉缓存、减 worker 数量。


# ============================================================
# 七、8 GB 的卡能跑什么（按实测推算）
# ============================================================
#   YOLO26n，640×640：
#     FP32  batch 24  ->  6.4 GB（已经很紧）
#     AMP   batch 24  ->  3.5 GB（还能再翻一倍）
#
#   YOLO26s（比 n 大 4 倍参数量），640：
#     AMP 下 batch 8~16 比较安全
#
#   如果想训练 1280×1280：激活值 4 倍，batch 只能取 1/4。
#
# 经验做法：
#   先开 AMP，再把 batch 设成"能跑通的最大值的一半"，
#   留出余量给系统和其他进程。


# ============================================================
# 八、这一课要记住的三句
# ============================================================
# 1. 显存的大头是激活值，不是参数。
#    YOLO26n 的参数只有 39 MB，实测 batch 8 却要 2.1 GB。
#
# 2. batch 线性影响显存，分辨率是平方影响。
#    显存不够时，降分辨率的收益大得多。
#
# 3. FP16 能把显存砍掉约 45%，但必须配 GradScaler，
#    否则小梯度会静默变成 0，训练悄悄变差。

