# E08：训练效率——瓶颈到底在哪一段
#
# 【这一课解决什么问题】
#   nvidia-smi 看到 GPU 利用率只有 40%，训练很慢。
#   直觉是"显卡不行"，但多数时候显卡在**等数据**。
#
#   这一课把一步训练的耗时拆开，找出真正的瓶颈。
#   下面的数字全部是这台机器实测的（RTX 4060 Laptop / YOLO26n / 640×640 / batch 8）。


# ============================================================
# 一、一步训练的时间花在哪
# ============================================================
# 完整的一步包含：
#
#   ① 读图 + 预处理（CPU）   解码 jpg、resize、归一化、转张量
#   ② 拷贝到 GPU             CPU 内存 -> 显存
#   ③ 前向（GPU）
#   ④ 反向（GPU）
#   ⑤ 更新参数（GPU）
#
# 实测：
#
#   前向                47.6 ms
#   反向               105.5 ms      <- 大约是前向的 2.2 倍
#   优化器更新           7.8 ms
#   ------------------------------
#   GPU 合计           160.8 ms
#
#   CPU->GPU 拷贝        11.5 ms
#   CPU 预处理（单线程）  142.9 ms   <- ★ 快赶上 GPU 的总时间了
#
# ★ 这就是关键：
#   单线程做预处理要 143 ms，GPU 算一步要 161 ms。
#   两者几乎相等 -> 如果串行执行，GPU 有一半时间是空闲的。
#
#   这就是"GPU 利用率 40%"的真实原因：不是卡不行，是在等数据。


# ============================================================
# 二、怎么把这段隐藏掉
# ============================================================
# 手段只有一个：让"准备数据"和"GPU 计算"并行起来。
#
#   ① 多进程读数据（num_workers）
#      8 个 worker 并行，143 ms 的理想值变成约 18 ms。
#      这也是为什么几乎所有训练脚本都有 num_workers 参数。
#
#   ② 预取（prefetch）
#      当前 batch 在 GPU 上算的时候，后面几个 batch 已经在准备了。
#      只要"准备速度" > "计算速度"，GPU 就几乎不用等。
#
#   ③ 固定内存（pin_memory）+ 异步拷贝
#      让拷贝也能和计算重叠。11.5 ms 本身不大，但能省就省。
#
# ★ 判断标准很简单：
#   CPU 预处理时间 < GPU 计算时间  ->  GPU 满负荷，说明配置够了
#   CPU 预处理时间 > GPU 计算时间  ->  CPU 是瓶颈，加 worker


# ============================================================
# 三、测时间的正确方法（这个容易错）
# ============================================================
# CUDA 是**异步**的：Python 调用 cuDNN 之后立刻返回，
# 真正的计算在 GPU 上排队执行。
#
# 所以这样测出来的是"发出指令的时间"，不是计算时间：
#
#   t0 = time.time()
#   y = model(x)
#   print(time.time() - t0)       # 错：可能只测到 0.1 ms
#
# 正确做法：在测速前后加 torch.cuda.synchronize()，
# 强制等 GPU 真的算完。
#
#   t0 = time.perf_counter()
#   y = model(x)
#   torch.cuda.synchronize()      # 等真正算完
#   print(time.perf_counter() - t0)
#
# 另外必须"预热"：第一次前向包含 cuDNN 选择算法、分配内存，
# 比稳态慢好几倍。正式测之前先空跑 3 次。


# ============================================================
# 四、num_workers 的几个坑
# ============================================================
# ① Windows 上必须包在主入口里
#    Windows 用 spawn 方式创建进程，不是 fork。
#    如果 Dataset 的定义或训练代码在模块顶层，
#    子进程 import 时会把整个脚本再跑一遍 -> 无限递归或直接崩。
#    正确写法：
#
#      if __name__ == "__main__":
#          main()
#
# ② worker 不是越多越好
#    每个 worker 是一个独立进程，各自持有一份数据索引和缓存。
#    worker 太多：内存暴涨、进程切换开销变大、反而更慢。
#    经验：从 4 开始试，看 CPU 核数和内存。
#
# ③ 每个 worker 有自己的随机状态
#    数据增强的随机性在 worker 里发生。
#    要让结果可复现，得给每个 worker 单独设种子（E06 讲过）。
#
# ④ 最后一个 batch 可能拖慢
#    batch 大小不一致时，每一步的耗时都不同，
#    某些框架会有等待同步的开销。


# ============================================================
# 五、最小的工程结构
# ============================================================
# 不需要框架，一个文件+一个配置就能跑。关键是分层清晰：
#
#   config.py / config.yaml     超参数、路径、类别名（不写在代码里）
#   dataset.py                  Dataset 类（只负责"取一个样本"）
#   model.py                    网络结构（只负责结构）
#   train.py                    主入口：
#                                 build_data()   -> 数据集和 dataloader
#                                 build_model()  -> 模型、优化器、调度器
#                                 train_one_epoch()  -> 一轮训练
#                                 validate()     -> 一次验证
#                                 save_ckpt()    -> 存检查点
#
# 判断拆分标准：**能不能单独测**。
#   build_model() 能单独跑 -> 结构对不对一看就知道
#   validate() 能单独跑   -> 指标计算可以和训练解耦
#
# 反例：所有代码写在一个 500 行的 main() 里，
#       想单独验证"数据管道对不对"都做不到。


# ============================================================
# 六、优化顺序（先测再改）
# ============================================================
#   第 1 步：分段计时，找出最大的一块
#   第 2 步：只改那一块，改完重新测
#   第 3 步：记录"改之前/改之后"的完整条件（batch、分辨率、worker 数）
#
# 最容易犯的错：
#   没测就上手改（换卡、换框架、上分布式），
#   结果瓶颈根本不在那里，白花时间。
#
# 还有一个反直觉的事实：
#   训练变快不等于训练变好。batch 加大之后每步更快，
#   但收敛需要的步数可能变多，总时间不一定省。


# ============================================================
# 七、这一课要记住的三句
# ============================================================
# 1. GPU 利用率低，先查 CPU 端的数据准备速度。
#    实测：预处理 143 ms vs GPU 计算 161 ms，几乎打平。
#
# 2. 测 GPU 时间必须 synchronize + 预热，
#    否则测到的是"发指令的时间"。
#
# 3. 优化之前先分段计时。没有数据的优化都是猜。

