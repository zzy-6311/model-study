# E04：优化器、调度器、正则化——那些"调参"在调什么
#
# 【这一课解决什么问题】
#   打开任何一个训练脚本，会看到一堆旋钮：
#     lr、momentum、weight_decay、scheduler、warmup……
#   它们经常被混在一起说成"调参"，但各自管的事完全不同。
#   搞不清分工，就会出现"改了 weight_decay 却以为在调学习率"。


# ============================================================
# 一、四个旋钮，各管一件事
# ============================================================
#   旋钮            管什么                        改错了的后果
#   ------------------------------------------------------------------
#   lr              每步走多远                     太大发散，太小磨蹭
#   momentum        方向要不要参考历史             太大冲过头，太小没加速
#   weight_decay    权重能不能随便变大             太大欠拟合，太小过拟合
#   scheduler       lr 随训练阶段怎么变            前期崩、后期震荡
#
# 它们的共同点：都作用于"参数怎么更新"。
# 它们的区别：改的是更新的不同方面（步长 / 方向 / 约束 / 节奏）。


# ============================================================
# 二、weight_decay 到底在做什么
# ============================================================
# 数学上，它给损失加了惩罚项：
#
#   总损失 = 原损失 + (λ/2) × Σ w²
#
# 于是梯度里多了一项 λ×w。
# 效果：每一步除了沿原梯度走，还会把权重往 0 拉一点。
#
# 为什么这样能抗过拟合？
#   权重小 -> 每层的输出对输入变化不敏感 -> 函数更平滑
#   平滑的函数不容易"记住"个别样本的噪声
#
# 实测（40 个训练样本、100 维特征，参数比样本还多）：

import math
import torch
import torch.nn as nn

torch.manual_seed(0)

N, D = 50, 100
X = torch.randn(N, D)
w_true = torch.randn(D, 1) * 0.1
y = X @ w_true + 0.5 * torch.randn(N, 1)     # 加了噪声
Xtr, ytr = X[:40], y[:40]
Xva, yva = X[40:], y[40:]


def run(wd, epochs=300, lr=0.05):
    torch.manual_seed(1)
    model = nn.Linear(D, 1)
    opt = torch.optim.AdamW(model.parameters(), lr=lr, weight_decay=wd)
    for _ in range(epochs):
        opt.zero_grad()
        ((model(Xtr) - ytr) ** 2).mean().backward()
        opt.step()
    with torch.no_grad():
        tr = ((model(Xtr) - ytr) ** 2).mean().item()
        va = ((model(Xva) - yva) ** 2).mean().item()
        wn = sum(p.norm().item() for p in model.parameters())
    return tr, va, wn


print("=" * 60)
print("一、weight_decay 的作用")
print(f"{'wd':>6} {'训练MSE':>9} {'验证MSE':>9} {'权重范数':>9}")
for wd in (0.0, 0.1, 1.0, 3.0, 10.0, 30.0):
    tr, va, wn = run(wd)
    print(f"{wd:>6} {tr:>9.4f} {va:>9.4f} {wn:>9.3f}")

# 输出：
#     wd   训练MSE   验证MSE   权重范数
#    0.0   0.0000   1.0902     0.908
#    0.1   0.0000   0.8668     0.799
#    1.0   0.0001   0.8470     0.794
#    3.0   0.0008   0.8805     0.778
#   10.0   0.0218   0.8124     0.683
#   30.0   0.3037   0.7122     0.312
#
# 三件事：
#   ① 训练 MSE 从 0 一路涨到 0.30（模型变"笨"了，拟合不动了）
#   ② 验证 MSE 从 1.09 降到 0.71（泛化反而变好了）
#   ③ 权重范数从 0.91 缩到 0.31（这就是"惩罚"在起作用）
#
# 这就是正则化的本质：**用一点训练精度，换泛化能力。**
#
# 注意：在这个小任务里，wd 一直加大就一直变好，
# 没有出现"加到某个点后验证变差"的拐点。
# 为什么？因为真实的权重本来就很小（0.1 量级），
# 缩得更小反而更接近真相。
# 在真实任务里加到过大是会欠拟合的，最优点要找。


# ============================================================
# 三、一个容易搞混的细节：L2 正则和 weight_decay 不完全等价
# ============================================================
#   在 SGD 里：weight_decay 就是"把 λw 加到梯度里"，和 L2 正则完全等价。
#
#   在 Adam 里：如果也这么做，会被 Adam 的"自适应缩放"搅乱
#              （因为梯度里混进了和损失无关的项）。
#   所以有了 AdamW：把"权重衰减"单独拿出来，不和梯度混。
#
#   实践含义：
#     用 Adam 时，尽量用 AdamW，weight_decay 的含义更干净。
#     同一个 wd 数值，在 SGD 和 AdamW 里的效果不一样，不要照抄。


# ============================================================
# 四、scheduler：让 lr 随阶段变化
# ============================================================
# 为什么需要调度？
#   训练初期：梯度的统计还不准，步子太大容易崩 -> 需要 warmup
#   训练中期：步子要够大，才能快速下降
#   训练后期：接近最优点，步子太大会来回震荡 -> 需要衰减
#
# 一个常用的组合（warmup + 余弦退火）：
#   前几轮 lr 从 0 线性升到设定值
#   之后按余弦曲线平滑降到接近 0

print()
print("=" * 60)
print("二、warmup + 余弦的 lr 曲线（共 30 轮，warmup 5 轮）")

total, warm, base_lr = 30, 5, 0.01
for e in range(total):
    if e < warm:
        lr = base_lr * (e + 1) / warm
    else:
        progress = (e - warm) / (total - warm)
        lr = base_lr * 0.5 * (1 + math.cos(math.pi * progress))
    if e % 3 == 0 or e == total - 1:
        print(f"  epoch {e:>2}: lr = {lr:.6f}")

# 输出：
#   epoch  0: lr = 0.002000      <- warmup：从设定值的 1/5 开始
#   epoch  3: lr = 0.008000
#   epoch  6: lr = 0.009961      <- 峰值，接近设定的 0.01
#   epoch 12: lr = 0.008187
#   epoch 18: lr = 0.004686      <- 余弦中段
#   epoch 27: lr = 0.000351
#   epoch 29: lr = 0.000039      <- 接近 0，最后几步几乎不动
#
# warmup 解决什么？
#   训练刚开始时，BatchNorm 的统计量还不准、参数还是随机的，
#   梯度的方向很不稳定。用小 lr 先走几步，让状态稳定下来再加速。
#
# 余弦衰减解决什么？
#   后期用大 lr 会在最优点附近来回跳，损失下不去。
#   平滑地降到接近 0，让模型能"落"在最优点上。


# ============================================================
# 五、为什么不能只看最后那一个 loss
# ============================================================
# 两个配置可能最终验证 loss 一样，但一个：
#   前 10 轮就到了，后 90 轮一直平
#   另一个：
#   前 90 轮都很差，最后 10 轮突然追上
#
# 这两种情况在真实项目里含义完全不同：
#   前者可能已经饱和，再加训练也没用
#   后者说明 lr 调得太保守，浪费了 90 轮
#
# 所以判断配置好坏要看三样：
#   收敛速度（多少轮到达某个指标）
#   最终水平
#   稳定性（曲线抖不抖、多次训练方差多大）


# ============================================================
# 六、实验纪律（比任何技巧都重要）
# ============================================================
#   ① 固定数据划分，把 indices 记下来
#   ② 固定随机种子（能固定的部分）
#   ③ 一次只改一个因素
#   ④ 每次实验记录：改了什么、指标怎么变、结论是什么
#
# 反例：同时加 weight_decay、换 scheduler、加数据增强，
#       结果变好了，但你不知道是哪个起的作用。
#       下次换一个数据集，全部重来。


# ============================================================
# 七、这一课要记住的三句
# ============================================================
# 1. lr / momentum / weight_decay / scheduler 是四个独立的旋钮，
#    weight_decay 管"权重的大小"，scheduler 管"lr 的节奏"。
#
# 2. weight_decay 用训练精度换泛化：训练 MSE 上升、验证 MSE 下降、
#    权重范数变小。加到过大就会欠拟合。
#
# 3. 判断一个配置要看收敛速度、最终水平、稳定性三样，不是只看最后那个数。

