import torch

# B02：按维度归约 / 拼接 / 广播
#
# 上一课（B01）讲的是"怎么重新摆数据"，这一课讲"怎么把数据压缩"和"怎么让形状对得上"
# 三个问题：
#   1. dim 参数到底在删哪一维？
#   2. cat 和 stack 都是"合起来"，差在哪？
#   3. 形状不同也能相加 —— 广播的规则是什么，什么时候会悄悄算错

# ============================================================
# 一、先说明：arange 出来的是整数，不能直接求平均
# ============================================================
xi = torch.arange(6).reshape(2, 3)
print("=" * 62)
print("一、原始张量（整数）")
print(xi)
print("dtype =", xi.dtype)          # torch.int64

try:
    xi.mean()
except RuntimeError as e:
    print("报错 ->", str(e)[:70], "...")
# 这就是 A02 讲过的：mean() 不能对整数张量用
#   因为平均值可能是小数，整数存不下，PyTorch 干脆让你先明确转成浮点

x = xi.float()
print("转成浮点后 dtype =", x.dtype)     # torch.float32
print(x)
# x = [[0., 1., 2.],
#      [3., 4., 5.]]      形状 [2,3]
# 记法：2 行（2 个样本）、3 列（3 个特征）


# ============================================================
# 二、dim 参数：删掉哪一维
# ============================================================
print("=" * 62)
print("二、dim 到底删哪一维")

print("mean()        =", x.mean().item(), x.mean().shape)
# 不写 dim -> 全部元素求平均 -> 0 维标量 ()，A02 学过

print("mean(dim=0)   =", x.mean(dim=0).tolist(), x.mean(dim=0).shape)
# (0+3)/2=1.5  (1+4)/2=2.5  (2+5)/2=3.5
# 第 0 维（行）被删掉了 -> 剩下 [3]
# 含义：每一个"列"的平均，也就是 每个特征在 2 个样本上的平均值

print("mean(dim=1)   =", x.mean(dim=1).tolist(), x.mean(dim=1).shape)
# (0+1+2)/3=1.0   (3+4+5)/3=4.0
# 第 1 维（列）被删掉了 -> 剩下 [2]
# 含义：每一行的平均，也就是 每个样本的 3 个特征的平均值

print("sum(dim=0)    =", x.sum(dim=0).tolist())   # [3, 5, 7]
print("sum(dim=1)    =", x.sum(dim=1).tolist())   # [3, 12]

# ★ 一句话记法：dim=k 的意思就是"把第 k 维压没掉"
#   形状 [2,3] 写 dim=0 -> 剩下 [3]
#   形状 [2,3] 写 dim=1 -> 剩下 [2]
#   想不清就问自己：结果里还留哪些维？留下的那一维长度是多少？


# ============================================================
# 三、keepdim：压的时候留个"空壳"
# ============================================================
print("=" * 62)
print("三、keepdim")

print("dim=0          ->", x.mean(dim=0).shape)                  # [3]
print("dim=0, keepdim ->", x.mean(dim=0, keepdim=True).shape)    # [1,3]
print("dim=1          ->", x.mean(dim=1).shape)                  # [2]
print("dim=1, keepdim ->", x.mean(dim=1, keepdim=True).shape)    # [2,1]

print("keepdim 的值 =", x.mean(dim=1, keepdim=True).tolist())
# [[1.0],
#  [4.0]]
# 数值一样，但形状从 [2] 变成 [2,1] —— 变成了一列

# ★ 为什么要这个"空壳"？看第七节的实战
#   简单说：原张量是 [2,3]，你要拿一个"每行的和"去除它
#   [2] 和 [2,3] 对不上会报错，[2,1] 才能按行广播下去


# ============================================================
# 四、cat：沿已有的维度拼起来
# ============================================================
print("=" * 62)
print("四、cat 拼接")

a = torch.tensor([[1, 2, 3], [4, 5, 6]])       # [2,3]
c = torch.tensor([[7, 8, 9], [10, 11, 12]])    # [2,3]

print("cat dim=0 ->", torch.cat([a, c], dim=0).shape)    # [4,3]
print(torch.cat([a, c], dim=0).tolist())
# [[1, 2, 3],
#  [4, 5, 6],
#  [7, 8, 9],      <- c 接在 a 下面，行数变成 4
#  [10, 11, 12]]

print("cat dim=1 ->", torch.cat([a, c], dim=1).shape)    # [2,6]
print(torch.cat([a, c], dim=1).tolist())
# [[1, 2, 3, 7, 8, 9],       <- 每一行后面接上 c 的同一行
#  [4, 5, 6, 10, 11, 12]]

# ★ cat 只动一维，其他维必须完全一致
#   [2,3] 和 [2,5] 可以 cat(dim=0) -> [4,3]? 不行！列数不同，必须都是 3
#   [2,3] 和 [2,3] 才能任意 dim 拼接


# ============================================================
# 五、stack：新造一维，把两个张量"摞"成上下层
# ============================================================
print("=" * 62)
print("五、stack 堆叠")

print("stack dim=0 ->", torch.stack([a, c], dim=0).shape)    # [2,2,3]
print(torch.stack([a, c], dim=0).tolist())
# [[[1, 2, 3], [4, 5, 6]],      <- 第 0 层是 a
#  [[7, 8, 9], [10, 11, 12]]]   <- 第 1 层是 c

print("stack dim=1 ->", torch.stack([a, c], dim=1).shape)    # [2,2,3]
print(torch.stack([a, c], dim=1).tolist())
# [[[1, 2, 3], [7, 8, 9]],      <- 第 0 行：a 的第0行 + c 的第0行
#  [[4, 5, 6], [10, 11, 12]]]   <- 第 1 行

# ★ cat 和 stack 的区别：
#   cat   ：合并已有的一维，维度数不变     [2,3]+[2,3] -> [4,3] 或 [2,6]
#   stack ：新增一维，维度数 +1            [2,3]+[2,3] -> [2,2,3]
#
# ★ 注意 stack 的 dim=0 和 dim=1 形状都是 [2,2,3]！
#   形状一样但内容排布不同（和 B01 的 permute vs reshape 是同一个坑）
#   dim 的意义是"新维度插在第几个位置"


# ============================================================
# 六、广播：形状不同也能算，规则是从末尾对齐
# ============================================================
print("=" * 62)
print("六、广播规则")

print(x.shape, "+ [3] ->", (x + torch.tensor([10.0, 20.0, 30.0])).tolist())
# x 是 [2,3]，加一个 [3]：从右边对齐，3 和 3 匹配，前面的 2 保持
#   [[0+10, 1+20, 2+30],
#    [3+10, 4+20, 5+30]]
# 也就是说 [3] 被复制到了两行上

try:
    x + torch.tensor([10.0, 20.0])
except RuntimeError as e:
    print("[2,3] + [2] 报错 ->", str(e)[:95], "...")
# 从右边对齐：3 和 2 对不上 -> 报错
# 报错信息里写的 "non-singleton dimension 1" 就是指第 1 维（长度 3 对 2）

# 广播三条规则：
#   1. 从最右边一维开始向左逐维比较
#   2. 相等 -> 通过；有一个是 1 -> 那个维度会被"复制展开"
#   3. 缺的维度当作 1（所以 [2,3]+[3] 相当于 [2,3]+[1,3]）
#   对不上就报错

# ★ 危险的地方：能跑不代表对
#   [2,1] + [2] 不报错，但会广播成 [2,2]（A02 那个坑）
#   判断标准永远是"这个广播是我想要的吗"，而不是"它跑通了吗"


# ============================================================
# 七、keepdim 的实战用途：每行归一化
# ============================================================
print("=" * 62)
print("七、为什么需要 keepdim")

print("每行的和 =", x.sum(dim=1).tolist())        # [3, 12]   形状 [2]
print("每行的和（keepdim）= ", x.sum(dim=1, keepdim=True).tolist())   # [[3],[12]]  形状 [2,1]

try:
    x / x.sum(dim=1)
except RuntimeError as e:
    print("不带 keepdim ->", str(e)[:85], "...")
# [2,3] 除以 [2]：从右边对齐，3 和 2 对不上 -> 直接报错

print("带 keepdim ->", (x / x.sum(dim=1, keepdim=True)).tolist())
# [[0/3,     1/3,     2/3    ]     -> 每行自己除以自己那行的和
#  [3/12,    4/12,    5/12   ]]
# 输出：[[0.0, 0.333, 0.667],
#        [0.25, 0.333, 0.4167]]

# ★ 所以 keepdim 的真正作用是：
#   先归约得到一个"每行一个数"的结果，再拿它去和原张量做运算时，
#   需要保持 [2,1] 的形状才能沿着列方向广播下去，
#   否则 [2] 会被当成"两列"去对齐，直接报错

# ============================================================
# 总结
# ============================================================
# 归约   sum / mean + dim=k    把第 k 维压掉；keepdim=True 压完留个长度1的空壳
# 拼接   cat([a,b], dim=k)     沿第 k 维接起来，维度数不变
# 堆叠   stack([a,b], dim=k)   新建一维插在第 k 位，维度数 +1
# 广播   从末尾对齐，相等或用 1 补，对不上报错
#
# 最该记住的两句：
#   1. dim=k = 把第 k 维压没
#   2. "跑通了"不等于"算对了"，广播的合法性要自己判断
