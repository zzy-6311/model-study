import torch

# 这次学习学习率的调整
# 这一课：lr 到底取多少？
#   同一个问题、同一个初始参数，只改 lr，跑出来是完全不同的三种命运：
#     太慢（像没动）、合适（快速下降）、发散（越来越大，最后爆掉）

x = torch.tensor([[1.0, 2.0], [3.0, 4.0]], dtype=torch.float64)
target = torch.tensor([[2.0], [4.0]], dtype=torch.float64)
# 照旧

def train(lr, steps=100):
    # 把"训练"打包成函数：给一个 lr，跑 steps 步，返回每一步的 loss 列表
    # 好处：改 lr 只要换个参数，不用把整个循环抄一遍

    w = torch.tensor([[0.3], [0.5]], dtype=torch.float64, requires_grad=True)
    b = torch.tensor([0.1], dtype=torch.float64, requires_grad=True)
    # ★ 每次进来都重新创建 w、b
    #   这样所有 lr 都从同一个起点 (0.3, 0.5, 0.1) 出发，比较才公平
    #   如果放在函数外面，第二个 lr 就接着第一个 lr 的结果继续跑，结论全废

    losses = []

    for step in range(steps + 1):        # 0 ~ steps，共 steps+1 个点
        w.grad = None
        b.grad = None

        y = x @ w + b
        loss = ((y - target) ** 2).mean()
        losses.append(loss.item())
        # 先记下"这一步开始时"的 loss，再更新参数，所以 losses[0] 是初始值

        if step == steps:                # 最后一步只记录，不再更新
            break

        loss.backward()
        with torch.no_grad():
            w -= lr * w.grad
            b -= lr * b.grad

        if not torch.isfinite(loss):
            # .isfinite(x)  判断是不是有限数；nan 和 inf 都返回 False
            #   not 取反 -> 出现 nan/inf 时为 True
            # 一旦爆掉就别往下算了：后面全是 nan，白跑，还可能更慢
            # inf = infinity，无穷大：数值太大，超出了浮点数的表示上限
            # nan = Not a Number，不是数：运算本身无意义，没有合法结果
            print(f"   !! lr={lr} 在第 {step} 步出现 nan/inf，停止")
            break

    return losses


print("=" * 62)
print("同一初始参数，四个学习率，看前 100 步的 loss")

for lr in (0.0005, 0.01, 0.05, 0.07):
    losses = train(lr)
    print(f"\nlr = {lr}")

    for i in (0, 1, 5, 10, 20, 50, 100):
        if i < len(losses):
            # :.6g  = 保留 6 位有效数字，自动在普通写法和科学记数法之间选
            #         大数显示成 4.28e+16，不会把一行撑爆
            print(f"   step {i:3d}   loss = {losses[i]:.6g}")

# ============================================================
# 预期结果
# ============================================================
# lr = 0.0005   太慢    0.68 -> 0.658 -> 0.58 -> 0.49 -> 0.36 -> 0.14 -> 0.0346
# lr = 0.01     合适    0.68 -> 0.321 -> 0.0219 -> 0.0069 -> 0.0061 -> ... -> 0.0033
# lr = 0.05     更快    0.68 -> 0.234 -> 0.0088 -> 0.0049 -> 0.0033 -> 0.0010 -> 0.000154
# lr = 0.07     发散    0.68 -> 0.9975 -> 4.66 -> 32.2 -> 1544 -> 1.7e8 -> 4.28e16

# ============================================================
# 三种形态怎么认
# ============================================================
# 太慢（lr 太小）  loss 一直在降，但降得很磨蹭；100 步还不如别人 5 步
#                  特点：单调、平滑、永远不爆，就是慢
# 合适            每一步都在明显下降，几十步就逼近很低的值
# 发散（lr 太大）  loss 不降反升，而且越来越大：1 -> 4 -> 32 -> 1543 -> 1.7e8
#                  特点：第一步就可能变大，之后每步放大约 40 倍
# 中间还有"震荡"  loss 忽上忽下，但整体还在降 —— 说明已经踩到上限附近

# ============================================================
# 为什么 lr 有上限
# ============================================================
# 走路类比：梯度告诉你下坡方向，lr 是你一步跨多远
#   步子小  -> 慢慢挪，方向没错，就是费步数
#   步子大  -> 一步跨过谷底，冲到对面的上坡，下一步又被推回来更多
#   再大点  -> 每一跳都比上一跳更远，直接飞出山谷 -> nan/inf
#
# 这个问题的数学上限约 0.063（由数据本身决定）
#   所以 0.05 还在界内（能收敛），0.07 已经越界（发散）
#   λmax（Hessian 最大特征值）≈ 31.6，上限 = 2 / 31.6 ≈ 0.063
#   不需要会算，但要记住：上限不是固定的常数，换数据就换数值

# ============================================================
# 一个重要的坑：lr 和数据的尺度是绑死的
# ============================================================
# 假设把 x 全部放大 10 倍，梯度会放大 10 倍，Hessian 放大 100 倍，
# 于是上限从 0.063 掉到 0.00063。
# 所以"网上说 lr=0.01 好用"是没有意义的，它只对那组数据成立。
# 这也是为什么换数据集/换模型后常常要重新调 lr。

# ============================================================
# 什么时候停
# ============================================================
# 1. 出现 nan / inf          立刻停，检查 lr 是否过大、数据是否有异常值
# 2. 到了预定步数            最常见，简单可靠
# 3. loss 连续 N 步几乎不变  变化小于某个阈值就停，省时间
# 4. 验证集开始变差          说明开始过拟合；这是 C/E 阶段的内容
# 不要用"loss 必须等于 0"当停止条件 —— 那往往意味着出问题了