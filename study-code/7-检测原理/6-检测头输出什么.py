# G06：三个尺度，每个位置输出什么
#
# 【这一课解决什么问题】
#   G01 说了"8400 个位置，每个位置输出 84 个数"。
#   这 84 个数具体是什么？4 个框参数是哪 4 个？它怎么变成一个框？
#
#   这一课把"位置 -> 框"这条链条走通。


# ============================================================
# 一、三个尺度，来自三次下采样
# ============================================================
#   输入 640×640，网络里有三次步长 2 的卷积：
#     640 -> 320 -> 160 -> 80   （P3，stride 8）
#     80  -> 40                 （P4，stride 16）
#     40  -> 20                 （P5，stride 32）
#
#   每个尺度有自己的特征图，各自做一遍检测：

for name, stride in (("P3", 8), ("P4", 16), ("P5", 32)):
    n = 640 // stride
    print(f"  {name}: stride={stride:>2}  特征图 {n}×{n} = {n * n:>5} 个位置")

print("  合计:", 80 * 80 + 40 * 40 + 20 * 20, "个位置")

# 输出：
#   P3: stride= 8  特征图 80×80 =  6400 个位置
#   P4: stride=16  特征图 40×40 =  1600 个位置
#   P5: stride=32  特征图 20×20 =   400 个位置
#   合计: 8400 个位置
#
# ★ 位置多不代表精度高。P3 位置多、格子小，适合小物体；
#   P5 位置少、格子大，适合大物体。


# ============================================================
# 二、每个位置对应图上的一个"参考点"
# ============================================================
#   特征图上的每个格子，对应原图上的一小块区域。
#   我们用格子中心当"参考点"：
#
#     参考点像素坐标 = (格子列号 + 0.5) × stride
#                      (格子行号 + 0.5) × stride
#
#   加 0.5 是因为格子有大小，中心在中间。
#
#   三个尺度各自的中心点范围：
#     stride 8 ：4.0 ~ 636.0
#     stride 16：8.0 ~ 632.0
#     stride 32：16.0 ~ 624.0
#
# ★ 注意：**边缘的像素（0~3、636~640）没有精确的参考点**。
#   这是密集预测的固有代价，靠"预测值可以超出参考点"来弥补。


# ============================================================
# 三、每个位置输出什么
# ============================================================
#   以 YOLO26 为例（80 类）：
#
#     box 分支   4 个数   到参考点四边的距离（左、上、右、下）
#     cls 分支  80 个数   每个类别的分数（logits）
#     ------------------------------------------------
#     合计      84 个数
#
#   ★ 注意 box 分支输出的是"距离"，不是坐标。
#     为什么？因为距离相对参考点，更容易学：
#       输出 0 就是"贴着参考点的一个点"
#       输出正数就是往外扩
#     如果直接输出绝对坐标，模型要重新学"图像坐标系"，
#     而且不同尺度的数值范围差很多。


# ============================================================
# 四、4 个距离怎么变成一个框
# ============================================================
#   给定参考点 (cx, cy) 和四个距离 (l, t, r, b)：
#
#     x1 = cx - l
#     y1 = cy - t
#     x2 = cx + r
#     y2 = cy + b
#
#   就这么简单。这一步叫 dist2bbox（距离转框）。
#
#   手算一个：

stride = 8
gx, gy = 1.5, 1.5                        # 网格坐标（第 1 列、第 1 行）
l, t, r, b = 1.0, 0.5, 1.0, 0.5          # 距离，单位是"格子"

cx, cy = gx * stride, gy * stride
print()
print("=" * 60)
print("一、从一个位置到一个框")
print(f"  参考点像素坐标 = ({cx}, {cy})")
print(f"  四个距离（单位格）= l={l} t={t} r={r} b={b}")
print(f"  换算成像素 = ({l * stride}, {t * stride}, {r * stride}, {b * stride})")
print(f"  xyxy = ({cx - l * stride}, {cy - t * stride},"
      f" {cx + r * stride}, {cy + b * stride})")

# 输出：
#   参考点像素坐标 = (12.0, 12.0)
#   xyxy = (4.0, 8.0, 20.0, 16.0)
#
# ★ 这和路线文档里 H07 给的例子完全一致：
#   网格点 (1.5,1.5)、ltrb=(1,0.5,1,0.5)、stride=8 -> xyxy=(4,8,20,16)

# ★ 注意距离的单位是"格子"，不是像素。
#   换算成像素要乘 stride。
#   同样输出 l=1，在 P3 是 8 像素，在 P5 是 32 像素 ——
#   这就是为什么三个尺度能覆盖不同大小的物体。


# ============================================================
# 五、YOLO26 的一个特殊点：reg_max = 1
# ============================================================
#   早期的 YOLO（v8 等）用的是 DFL（分布焦点损失）：
#   把每个距离拆成 reg_max 个"桶"，预测一个分布，
#   再加权求和得到最终距离。reg_max 一般是 16。
#
#   你本地的 yolo26.yaml 里写的是：
#
#     reg_max: 1   # DFL bins
#
#   学习注释也说了："此检测配置直接预测四边距离，不使用多桶 DFL 回归。"
#
#   ★ reg_max=1 意味着：
#     没有"分布"了，box 分支直接输出 4 个实数（l,t,r,b）
#     分类头也不用拆桶，结构更简单
#
#   所以在 YOLO26 里，那 4 个数就是直接的距离值，
#   不要套用"多桶分布回归"的解释（那是别的版本）。
#
#   ★ 这也提醒一件事：**看源码时要确认版本的实际配置，
#     不能把别的版本的机制默认套过来。**


# ============================================================
# 六、为什么必须三个尺度
# ============================================================
#   假设只有 P5（20×20，stride 32）：
#     一个格子对应原图 32×32 像素。
#     一个 20×20 像素的小物体，比格子还小 ——
#     它落在哪个格子里都差不多，模型分不清它的位置。
#
#   假设只有 P3（80×80，stride 8）：
#     一个格子 8×8 像素，小物体能占几个格子，位置准。
#     但一个 400×400 的大物体要占 50×50 个格子，
#     预测框要跨 50 个格子 —— 相当于让模型去描述一个
#     "范围远超自己视野"的框，很难学。
#
#   ★ 所以：小物体交给 P3，中等交给 P4，大物体交给 P5。
#     每个尺度的"格子大小"刚好和它负责的物体尺寸匹配。
#
#   这就是"多尺度检测"的全部道理：
#   让不同大小的物体，都能在自己合适的尺度上"占几个格子"。


# ============================================================
# 七、完整链条回顾
# ============================================================
#   输入 640×640
#     -> backbone 下采样，得到三张特征图（80、40、20）
#     -> head 融合后，每个尺度输出 box(4) + cls(80)
#     -> 三个尺度拼起来：[B, 84, 8400]
#     -> 每个位置：参考点 + 4 个距离 -> 一个框
#     -> 再过分数阈值和 NMS（G08）
#     -> 得到最终的几个框
#
#   ★ 从"一张图"到"几个框"，中间就是这条链。


# ============================================================
# 八、这一课要记住的三句
# ============================================================
# 1. 三个尺度 = 三次下采样，位置数 6400 + 1600 + 400 = 8400。
#
# 2. 每个位置输出 4 个距离 + C 个类别分数。
#    距离是相对参考点的，单位是"格子"，换算成像素要乘 stride。
#
# 3. 本地 YOLO26 是 reg_max=1，直接回归距离，没有 DFL 分桶。
#    看源码要按本地配置来，不要套别的版本。

