# G07：标签分配——哪个预测该学哪个真实框
#
# 【这一课解决什么问题】
#   模型输出 8400 个预测，真实标注可能只有 3 个框。
#   损失函数要算"预测错多少"，但前提是知道"这个预测该对应哪个框"。
#
#   这个"配对"过程叫标签分配（label assignment）。
#   它是 YOLO 最核心的机制之一——分配错了，模型根本学不会。


# ============================================================
# 一、先说为什么不能"全配对"
# ============================================================
#   最偷懒的想法：8400 个预测，每个都和最近的 GT 算一次损失。
#
#   问题：
#     ① 绝大多数位置是背景，硬让它们学框 = 噪声
#     ② 一个 GT 会对应几十个位置，全学 = 学出一堆重复框
#     ③ 计算量爆炸（8400 × GT 数）
#
#   ★ 所以必须挑出"少数几个该学的位置"，其他都当负样本。


# ============================================================
# 二、筛选的第一步：只看"中心落在框内"的位置
# ============================================================
#   对每个 GT 框，先找出所有"中心点落在它内部"的位置。
#
#   8400 个位置里，一个中等大小的框大概只覆盖几十个位置。
#   这一步就把候选从 8400 缩到几十个。
#
#   ★ 注意是"中心点"，不是"框和位置有交集"。
#     用中心点是为了避免一个 GT 牵连太多位置。


# ============================================================
# 三、第二步：算"对齐度"，挑最好的几个
# ============================================================
#   候选位置有几十个，还要再挑。挑的标准不是单一的 IoU，
#   而是把"分类分数"和"IoU"结合起来：
#
#     对齐度 = 分类分数^alpha × IoU^beta
#
#   为什么两个都要？
#     只有 IoU 大：可能是位置对但类别还没学好的预测
#     只有分数高：可能是类别猜对但框歪了的预测
#     两者都好，才是理想的"正样本"
#
#   alpha 和 beta 控制两者的权重。本地 YOLO 用的是
#   alpha=0.5、beta=6 —— IoU 的话语权大得多。


alpha, beta = 0.5, 6.0
candidates = [("A", 0.90, 0.80), ("B", 0.70, 0.90), ("C", 0.50, 0.50)]

print("=" * 62)
print("一、三个候选位置的对齐度（alpha=0.5, beta=6）")
print(f"{'候选':>4} {'分类分数':>8} {'IoU':>6} {'对齐度':>9}")
for name, score, iou in candidates:
    align = (score ** alpha) * (iou ** beta)
    print(f"{name:>4} {score:>8.2f} {iou:>6.2f} {align:>9.4f}")

# 输出：
#   候选  分类分数    IoU    对齐度
#     A      0.90   0.80    0.2487
#     B      0.70   0.90    0.4446     <- 最高
#     C      0.50   0.50    0.0110
#
# ★ 注意 B 的分数比 A 低（0.70 vs 0.90），但对齐度更高。
#   因为 beta=6，IoU 从 0.80 提到 0.90 的收益，
#   远大于分数从 0.70 提到 0.90。
#
#   如果 beta=1（同等重要）：
#     A: 0.7589   B: 0.7530   -> 这时候 A 反而略高


# ============================================================
# 四、第三步：每个 GT 只保留 TopK 个
# ============================================================
#   算出对齐度后，每个 GT 只取分数最高的 K 个位置当正样本。
#
#   本地的配置（YOLO26 的双分支）：
#     one-to-many 分支：topk = 10    一个 GT 带 10 个正样本
#     one-to-one  分支：topk = 7，再挑 1 个
#
# ★ 为什么允许"一个 GT 多个正样本"？
#   一个样本能提供更多梯度，训练更快。
#   但太多会让模型输出一堆重复框——所以有 TopK 限制。


# ============================================================
# 五、第四步：解决冲突
# ============================================================
#   一个位置可能同时被多个 GT 选中（两个物体挨得很近）。
#
#   做法：逐个位置看，它被哪些 GT 选中过，取对齐度最高的那个。
#
#   ★ 一个位置只能属于一个 GT。
#     如果两个物体真的重叠得很厉害，那本来就有歧义，
#     取更"像"的那个是合理的近似。


# ============================================================
# 六、软标签：分类目标不是 1，而是"对齐度"
# ============================================================
#   传统做法：正样本的分类目标是 one-hot（[0,0,1,0...]）。
#
#   YOLO 的做法：用对齐度当"软标签"。
#
#   实测（上面三个候选，按最大值归一化）：
#     A: target_score = 0.559
#     B: target_score = 1.000
#     C: target_score = 0.025
#
# ★ 为什么要软标签？
#   一个 GT 周围的位置"质量"不同：稍微偏一点的位置，框只能部分覆盖物体。
#   硬把它当成 1（完全正确），等于在教模型"模糊的框也很好"。
#   软标签告诉模型："你是 0.56 分的好，不是满分"。

print()
print("=" * 62)
print("二、软标签")
best = max((s ** alpha) * (u ** beta) for _, s, u in candidates)
for name, score, iou in candidates:
    align = (score ** alpha) * (iou ** beta)
    print(f"  {name}: 对齐度 {align:.4f} -> 分类目标 {align / best:.3f}")


# ============================================================
# 七、完整流程
# ============================================================
#   对每个 GT 框：
#     ① 筛出中心落在框内的位置（8400 -> 几十）
#     ② 每个位置算 IoU（用当前预测框和 GT）
#     ③ 算对齐度 = 分数^alpha × IoU^beta
#     ④ 取 TopK（10）
#     ⑤ 生成 fg_mask（哪些位置是正样本）
#     ⑥ 生成 target_scores（软标签）
#
#   所有 GT 处理完后：
#     ⑦ 冲突位置归给对齐度最高的 GT
#     ⑧ 其余位置全部算负样本
#
# ★ 阅读源码时的顺序也是这样（roadmap 里 H09 给的顺序）：
#   候选点 -> 框内筛选 -> 类别分数与IoU度量 -> TopK -> 冲突解决 -> fg_mask


# ============================================================
# 八、训练时的两件事
# ============================================================
#   有了 fg_mask 和 target_scores 之后：
#
#   ① 分类损失
#      正样本位置：和软标签比（BCE）
#      负样本位置：和全 0 比（都压低）
#      —— G01 说的"1:119 不平衡"，就是靠"只对正样本算框损失"来缓解的
#
#   ② 框回归损失
#      只对正样本位置算，用 CIoU + L1（G05）
#      负样本位置不算框损失 —— 它们本来就没框
#
# ★ 这两条解释了检测损失为什么和分类损失长得不一样：
#   分类损失对 8400 个位置都算，框损失只对几十个位置算。


# ============================================================
# 九、这一课要记住的三句
# ============================================================
# 1. 标签分配 = 从 8400 个预测里挑出几十个"正样本"，其余当负样本。
#
# 2. 挑的标准是对齐度 = 分数^alpha × IoU^beta。
#    beta 很大（6），说明"框准"比"分类分数高"更重要。
#
# 3. 分类用软标签（按对齐度打折），框回归只对正样本算。

