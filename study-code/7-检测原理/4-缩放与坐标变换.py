# G04：图片缩放后，框坐标怎么跟着变
#
# 【这一课解决什么问题】
#   模型只吃 640×640，但你的图是 1280×720。
#   缩放之后，原来的框坐标当然也要跟着变。
#
#   而推理完之后，模型给的框是在 640×640 坐标系里的，
#   你还得把它变回原图坐标系。
#
#   这一来一回如果搞错了，框就会整体偏移、或者大小不对。
#   这是 YOLO 部署里最常见的 bug，没有之一。


# ============================================================
# 一、两种缩放方式
# ============================================================
#   ① 直接拉伸 1280×720 -> 640×640
#      横竖缩放比例不同（0.5 和 0.889）
#      人会被拉成瘦子，圆球变成椭圆
#      模型没见过这种变形，准确率会掉
#
#   ② 等比缩放 + 补边（LetterBox）
#      先按同一个比例缩放，短边不够的地方补灰边
#      1280×720 -> 640×360，上下各补 140 像素 -> 640×640
#      长宽比保持，物体不变形
#
# ★ YOLO 默认用第二种。代价是多一次填充、多一步坐标还原。


# ============================================================
# 二、LetterBox 的四个数
# ============================================================
#   输入：原图宽 W、高 H，目标尺寸 S=640
#
#   r     = min(S/W, S/H)          等比缩放比（取小的那个，保证能装下）
#   new_w = round(W * r)           缩放后的宽
#   new_h = round(H * r)           缩放后的高
#   pad_w = (S - new_w) / 2        左右各补多少
#   pad_h = (S - new_h) / 2        上下各补多少
#
# 正变换（原图坐标 -> 模型坐标）：
#   x' = x * r + pad_w
#   y' = y * r + pad_h
#
# 逆变换（模型坐标 -> 原图坐标）：
#   x = (x' - pad_w) / r
#   y = (y' - pad_h) / r
#
# ★ 注意顺序：正变换是"先缩放、后平移"，
#   逆变换就必须"先减平移、后除缩放"。
#   顺序搞反（先除 r 再减 pad）是经典错误。


# ============================================================
# 三、算一个具体的例子
# ============================================================

S = 640
W, H = 1280, 720

r = min(S / W, S / H)
new_w, new_h = round(W * r), round(H * r)
pad_w, pad_h = (S - new_w) / 2, (S - new_h) / 2

print("=" * 60)
print("一、1280×720 的图做 LetterBox")
print(f"  缩放比 r     = {r}")
print(f"  缩放后尺寸   = {new_w} × {new_h}")
print(f"  左右各补     = {pad_w}")
print(f"  上下各补     = {pad_h}")
print(f"  最终尺寸     = {new_w + 2 * pad_w} × {new_h + 2 * pad_h}")

# 输出：
#   缩放比 r     = 0.5
#   缩放后尺寸   = 640 × 360
#   左右各补     = 0.0
#   上下各补     = 140.0
#   最终尺寸     = 640 × 640
#
# 解释：宽 1280 缩到 640 需要 0.5 倍；高 720 缩到 360。
#       宽正好占满，高只有 360，上下各补 140。


def forward_box(box, r, pad_w, pad_h):
    x1, y1, x2, y2 = box
    return [x1 * r + pad_w, y1 * r + pad_h, x2 * r + pad_w, y2 * r + pad_h]


def inverse_box(box, r, pad_w, pad_h):
    x1, y1, x2, y2 = box
    return [(x1 - pad_w) / r, (y1 - pad_h) / r, (x2 - pad_w) / r, (y2 - pad_h) / r]


original = [100.0, 200.0, 300.0, 400.0]
scaled = forward_box(original, r, pad_w, pad_h)
back = inverse_box(scaled, r, pad_w, pad_h)

print()
print("二、一个框的往返")
print("  原图坐标   ", original)
print("  缩放后坐标 ", [round(v, 2) for v in scaled])
print("  逆变换回来 ", [round(v, 2) for v in back])

# 输出：
#   原图坐标    [100.0, 200.0, 300.0, 400.0]
#   缩放后坐标  [50.0, 240.0, 150.0, 340.0]
#   逆变换回来  [100.0, 200.0, 300.0, 400.0]
#
# 逐步验证缩放：
#   x1: 100 * 0.5 + 0 = 50
#   y1: 200 * 0.5 + 140 = 240      <- 加了 140 的补边
#   x2: 300 * 0.5 + 0 = 150
#   y2: 400 * 0.5 + 140 = 340


# ============================================================
# 四、最常见的两个错误
# ============================================================
# 错误 A：逆变换忘了减 pad
forgot_pad = [(v / r) for v in scaled]
print()
print("=" * 60)
print("三、逆变换忘了减 padding")
print("  正确还原 ", [round(v, 2) for v in back])
print("  忘了减pad", [round(v, 2) for v in forgot_pad])
print("  y 方向偏差", round(forgot_pad[1] - back[1], 2), "像素")

# 输出：
#   正确还原   [100.0, 200.0, 300.0, 400.0]
#   忘了减pad [100.0, 480.0, 300.0, 680.0]
#   y 方向偏差 280.0 像素
#
# ★ 240 / 0.5 = 480，多了 280 像素（= 140 / 0.5）。
#   框整体往下掉了 280 像素 —— 而图只有 720 高，
#   这个框直接跑到画面外面去了。
#
#   这就是"框整体偏移"的典型成因。


# ============================================================
# 五、错误 B：pad 的取整
# ============================================================
#   pad_h = (640 - 360) / 2 = 140   这里正好是整数。
#
#   但很多尺寸除不尽，比如 (640 - 359) / 2 = 140.5。
#   如果填充时用了 int(140.5) = 140（只在上面补 140），
#   而还原时按 140.5 算，就会有 0.5 像素的系统偏差。
#
#   正确做法：**填充和还原必须用同一个 pad 值**。
#   常见写法是拆成上下两个整数：
#     pad_top = (S - new_h) // 2
#     pad_bottom = S - new_h - pad_top
#   还原时只看 pad_top（或者反过来，但必须一致）。
#
# ★ 原则：**记录你实际补了多少，就用那个数去还原。**
#   不要"重新算一遍"，因为重新算可能得到不同的取整结果。


# ============================================================
# 六、为什么这套东西必须和推理代码放在一起
# ============================================================
#   推理流程是：
#     原图 -> LetterBox -> 模型 -> 框（640 坐标系）-> 逆变换 -> 原图坐标系
#
#   其中 LetterBox 的参数 r、pad_w、pad_h 是**每张图都不同**的。
#   如果你把它们存成全局变量，多张图批量推理时就会串：
#
#     图 A 用了 r=0.5, pad_h=140
#     图 B 用了 r=0.42, pad_h=166
#     处理完 A 的框却用 B 的参数还原 -> 全错
#
# ★ 所以参数必须"跟着这张图走"，不能是全局状态。
#   批量推理时尤其要注意这一点。


# ============================================================
# 七、这一课要记住的三句
# ============================================================
# 1. LetterBox = 等比缩放 + 补边。长宽比保持，物体不变形。
#
# 2. 正变换"先缩放后平移"，逆变换必须"先减平移后除缩放"。
#    忘了减 pad，框会整体偏移（实测偏 280 像素）。
#
# 3. r、pad_w、pad_h 是每张图各自的，不能存成全局变量。

