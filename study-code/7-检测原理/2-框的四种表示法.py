# G02：框的四种表示法
#
# 【这一课解决什么问题】
#   一个矩形框只需要 4 个数。可这 4 个数到底怎么排，
#   不同工具用的是不同约定：
#
#     COCO 标注文件     [x, y, w, h]      左上角 + 宽高，像素
#     YOLO 标注文件     [cx, cy, w, h]    中心 + 宽高，归一化 0~1
#     模型输出/画图     [x1, y1, x2, y2]  左上角 + 右下角，像素
#
#   混用一次，框就整体偏移、或者宽高反了。
#   这一课把这四种写法钉死，并且给你往返验证的方法。


# ============================================================
# 一、四种写法
# ============================================================
#  写法        含义                         谁在用
#  ------------------------------------------------------------
#  xyxy        x1,y1(左上) x2,y2(右下)       画图、NMS、模型内部
#  xywh        x,y(左上) w,h(宽高)            COCO 标注文件
#  cxcywh      cx,cy(中心) w,h(宽高)          YOLO 标注、检测头输出
#  normalized  上面任何一种除以宽高，变成 0~1   YOLO 标注、跨尺度计算
#
# ★ 记住一条：**"xywh" 里的 xy 到底是左上角还是中心点，
#   看名字是看不出来的。** 只能看文档或看数据。
#   COCO 是左上角，YOLO 的中心形式通常写作 cxcywh。


# ============================================================
# 二、亲手转一遍
# ============================================================
# 举一个具体例子（来自路线文档）：
#   图 640×480（宽 640，高 480）
#   框 [160, 120, 320, 240]（xyxy）

W, H = 640, 480
x1, y1, x2, y2 = 160, 120, 320, 240

print("=" * 60)
print("一、同一个框的四种写法")
print(f"  图像尺寸: 宽 {W} 高 {H}")
print(f"  xyxy      [{x1}, {y1}, {x2}, {y2}]")

# xyxy -> xywh（左上角 + 宽高）
w = x2 - x1
h = y2 - y1
print(f"  xywh      [{x1}, {y1}, {w}, {h}]")

# xyxy -> cxcywh
cx = (x1 + x2) / 2
cy = (y1 + y2) / 2
print(f"  cxcywh    [{cx:.1f}, {cy:.1f}, {w}, {h}]")

# 归一化（除以宽、高）
print(f"  归一化中心  [{cx / W:.4f}, {cy / H:.4f}, {w / W:.4f}, {h / H:.4f}]")

# 输出：
#   xyxy      [160, 120, 320, 240]
#   xywh      [160, 120, 160, 120]
#   cxcywh    [240.0, 180.0, 160.0, 120.0]
#  归一化中心  [0.3750, 0.3750, 0.2500, 0.2500]
#
# ★ 检查一下归一化的结果：
#   cx/640 = 240/640 = 0.375    （用**宽**除）
#   cy/480 = 180/480 = 0.375    （用**高**除）
#
#   两个恰好都等于 0.375，是因为这个框正好在正中央。
#   换成别的框，两个数就不一样了 —— 这正是最容易错的地方。


# ============================================================
# 三、坑一：归一化的分母用错
# ============================================================
# 归一化的规则是：
#
#   横坐标、宽  ->  除以 图像宽度 W
#   纵坐标、高  ->  除以 图像高度 H
#
# 但在代码里，(H, W) 这个顺序太常见了（数组是先行后列），
# 很容易写成：

wrong_cx = cx / H
wrong_cy = cy / W
print()
print("=" * 60)
print("二、分母用反了会怎样")
print(f"  正确: cx/{W} = {cx / W:.4f}   cy/{H} = {cy / H:.4f}")
print(f"  错误: cx/{H} = {wrong_cx:.4f}   cy/{W} = {wrong_cy:.4f}")

# 输出：
#   正确: cx/640 = 0.3750   cy/480 = 0.3750
#   错误: cx/480 = 0.5000   cy/640 = 0.2812
#
# ★ 640 和 480 差不多，错了还能看出是个框（只是位置偏了）。
#   如果图是 1920×200，错的就会离谱到 0.1 和 3.5（超出 0~1 范围）。
#   这时有些库会静默裁剪到 1.0，框直接贴在边上。
#
#   经验：**归一化之后的值如果超过 1，先怀疑分母用错。**
#   当然，框可以部分超出图像（比如被裁剪的物体），
#   超出一点是正常的，超出两倍就不正常了。


# ============================================================
# 四、坑二：往返转换必须能还原
# ============================================================
# 判断自己有没有搞错，最可靠的办法是"转过去再转回来"：

def xyxy_to_cxcywh_norm(box, W, H):
    x1, y1, x2, y2 = box
    cx = (x1 + x2) / 2 / W
    cy = (y1 + y2) / 2 / H
    w = (x2 - x1) / W
    h = (y2 - y1) / H
    return [cx, cy, w, h]


def cxcywh_norm_to_xyxy(box, W, H):
    cx, cy, w, h = box
    cx, cy, w, h = cx * W, cy * H, w * W, h * H
    return [cx - w / 2, cy - h / 2, cx + w / 2, cy + h / 2]


original = [160.0, 120.0, 320.0, 240.0]
back = cxcywh_norm_to_xyxy(xyxy_to_cxcywh_norm(original, W, H), W, H)
print()
print("=" * 60)
print("三、往返转换")
print("  原始      :", original)
print("  转回来    :", [round(v, 3) for v in back])
print("  误差      :", [round(abs(a - b), 6) for a, b in zip(original, back)])

# 输出：误差全是 0.0
#
# ★ 两条互逆的公式，往返一趟必须回到原点。
#   回不去，说明某一个公式写错了（通常是把 +w/2 写成 -w/2，
#   或者把 W/H 弄反）。
#
#   这个检查只要几行代码，能在写数据管道时第一时间发现错误，
#   比训练跑完发现框全偏了再回来查要省几百倍时间。


# ============================================================
# 五、坑三：坐标是 0 起还是 1 起
# ============================================================
#   图像数组的坐标从 0 开始（左上角像素是 [0,0]）。
#   但有些标注工具、MATLAB、以及部分格式用 1 起。
#
#   差 1 像素听上去无所谓，但如果你做了缩放，
#   这个 1 像素会被放大成 2~4 个像素，框就开始对不齐了。
#
#   ★ 判断方法：把标注画到图上，看框边是不是正好压住物体边缘。
#     差 1 像素肉眼看不出来，但可以用"最小框"来测：
#     一个 1×1 的框，转成 xywh 之后应该是 w=1，不是 w=0。


# ============================================================
# 六、坑四：取整不要太早
# ============================================================
#   坐标是浮点数的世界里，**越晚取整越好**。
#
#   如果在中间步骤就 int() 掉：
#     缩放 0.37 倍后，160 -> 59.2 -> 取整 59
#     再转回去：59 / 0.37 = 159.46，丢掉了 0.54 像素
#
#   一个框错 0.5 像素没关系，但如果是"先取整再算 IoU"，
#   在很小很密的框上（比如航拍图里的小车）误差会非常可观。
#
#   规矩：全程浮点，最后画图时再取整。


# ============================================================
# 七、坑五：宽高和坐标的顺序
# ============================================================
#   数组是 (行, 列) = (H, W)，图像显示是 (宽, 高) = (W, H)。
#   这两个顺序在所有工具里都是反的。
#
#   最常见的错误：
#     img.shape  -> (480, 640)   是 (H, W)
#     写代码时    -> 用 img.shape[0] 当宽度，其实是高度
#
#   ★ 记法：**OpenCV/PIL/numpy 里 shape 的前两个永远是 (高, 宽)。**
#     需要宽度时用 img.shape[1]。


# ============================================================
# 八、这一课要记住的三句
# ============================================================
