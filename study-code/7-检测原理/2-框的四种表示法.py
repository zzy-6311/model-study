#    名字不能说明 xy 是左上还是中心，只能查文档。
#
# 2. 归一化时：横坐标和宽除以 W，纵坐标和高除以 H。
#    结果超过 1 太多，先怀疑分母用反了。
#
# 3. 写完转换函数，立刻做一次"往返转换"验证。
