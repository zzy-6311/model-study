# G09：Precision / Recall / AP / mAP
#
# 【这一课解决什么问题】
#   分类的准确率很直观：对几个 / 总共几个。
#   检测没有"总共几个"——
#     漏检算错吗？算。
#     多框了算错吗？算。
#     框偏了一点算对还是错？要看 IoU 阈值。
#
#   所以检测不能用准确率，只能用 AP/mAP。这一课把它算一遍。


# ============================================================
# 一、为什么不能用准确率
# ============================================================
#   分类：每张图一个答案，对错一目了然。
#
#   检测：一张图里"正确答案"是几个框，模型的输出也是几个框，
#         但两者数量不一定相等、顺序也不固定。
#
#   而且"框对不对"本身是个阈值问题：
#     IoU 0.6 算不算对上？0.7 呢？
#
#   ★ 所以检测的评价是"在某个 IoU 阈值下，能检出多少、误检多少"。


# ============================================================
# 二、三个概念：TP / FP / FN
# ============================================================
#   TP（真正例）：预测的框和一个真实框 IoU ≥ 阈值（且该 GT 还没被别的预测占走）
#   FP（假正例）：预测的框找不到对应真实框，或者对应的是已经被占的 GT
#   FN（假负例）：真实框没有对应的预测 —— 也就是"漏检"
#
#   ★ 没有 TN（真负例）这个概念：
#     图上没有物体的地方是无数的，没法统计"正确地说这里没有东西"。
#     这正是检测和分类的根本区别。
#
#   ★ 注意 FP 的第二种情况："对应的是已经被占的 GT"。
#     同一个物体被预测两次，第二次算 FP —— 这是重复检测的惩罚。


# ============================================================
# 三、Precision 和 Recall
# ============================================================
#   Precision（精确率）= TP / (TP + FP)    预测出来的里面，有多少是真的
#   Recall   （召回率）= TP / (TP + FN)    真实的里面，找到了多少
#
#   两个都在意：只想都检出来 -> 到处画框（精度低）；
#               只想不误检 -> 只画最有把握的（召回低）。


# ============================================================
# 四、为什么是"曲线"：阈值一变，两个数都变
# ============================================================
#   模型的每个框都带分数。分数阈值设 0.9 时只输出 1 个框，
#   设 0.1 时输出 20 个。每换一个阈值，P 和 R 都不同。
#
#   所以不能只报一个数，而是把所有阈值扫一遍，得到一条 PR 曲线。

preds = [
    ("P1", 0.95, 0.90, 0),   # 和 GT0 的 IoU 是 0.90
    ("P2", 0.80, 0.80, 0),   # 也想匹配 GT0（重复）
    ("P3", 0.60, 0.70, 1),   # 和 GT1 的 IoU 是 0.70
    ("P4", 0.30, 0.10, 0),   # 和谁都对不上
]
n_gt = 2


def evaluate(iou_thr):
    matched = set()
    tp = fp = 0
    rows = []
    for name, score, iou, gt in preds:
        if iou >= iou_thr and gt not in matched:
            matched.add(gt)
            tp += 1
        else:
            fp += 1
        rows.append((name, tp, fp, tp / (tp + fp), tp / n_gt))
    return rows


print("=" * 62)
print("一、IoU 阈值 0.5 时，逐个预测累积")
print(f"{'预测':>4} {'TP':>4} {'FP':>4} {'Precision':>10} {'Recall':>8}")
for name, tp, fp, p, r in evaluate(0.5):
    print(f"{name:>4} {tp:>4} {fp:>4} {p:>10.3f} {r:>8.3f}")

# 输出：
#   预测   TP   FP  Precision   Recall
#   P1     1    0      1.000    0.500
#   P2     1    1      0.500    0.500      <- 重复检测，精度掉一半
#   P3     2    1      0.667    1.000      <- 找到第二个目标，召回满
#   P4     2    2      0.500    1.000      <- 误检，精度又掉
#
# ★ 读这张表：随着阈值降低（放进更多预测），
#   召回一路上升，精度上下波动。
#   这就是 PR 曲线。


# ============================================================
# 五、AP：PR 曲线下的面积
# ============================================================
#   把 P 当纵轴、R 当横轴，画出来的曲线下面那块面积就是 AP。
#
#   数值上的算法（全点插值）：
#     按分数从高到低走一遍
#     每走一步，取"当前及之后所有点的最大精度"作为这一段的精度
#     乘上召回的增加量，累加
#
#   直观含义：模型在各个召回水平上的"平均靠谱程度"。
#   AP = 1 表示完美（任何阈值下都不误检、不漏检）。

def ap_at(iou_thr):
    rows = evaluate(iou_thr)
    recalls = [r[4] for r in rows]
    precs = [r[3] for r in rows]
    ap = 0.0
    prev_r = 0.0
    for i in range(len(rows)):
        p_interp = max(precs[i:])       # 该召回点之后的最高精度
        if recalls[i] > prev_r:
            ap += (recalls[i] - prev_r) * p_interp
            prev_r = recalls[i]
    return ap


print()
print("=" * 62)
print("二、不同 IoU 阈值下的 AP")
for thr in (0.5, 0.6, 0.7, 0.75, 0.8, 0.9):
    print(f"  IoU ≥ {thr:.2f} : AP = {ap_at(thr):.4f}")

# 输出：
#   IoU >= 0.50 : AP = 0.8333
#   IoU >= 0.70 : AP = 0.8333     <- P3 的 0.70 刚好卡上
#   IoU >= 0.75 : AP = 0.5000     <- P3 掉了，只剩 P1
#
# ★ 道理：IoU 阈值越严格，同一个预测越容易从 TP 变成 FP。
#   AP 会随阈值升高而下降。


# ============================================================
# 六、mAP 和那两个常见指标
# ============================================================
#   mAP（mean AP）= 每个类别各算一次 AP，再取平均。
#   80 类就平均 80 个数。
#
#   然后是两个最常见的指标：
#
#   AP50 / mAP50    只在 IoU=0.5 这一个阈值上算
#                   -> 宽松，"大概框住就算对"
#
#   mAP50-95        在 IoU=0.5、0.55、0.60 ... 0.95 这 10 个阈值上
#                   各算一次 mAP，再平均
#                   -> 严格，能区分"框得准"和"框得糊"
#
#   ★ 所以 AP50 总是比 mAP50-95 高不少。
#     一个模型 AP50=0.9、mAP50-95=0.6，说明"能框到，但框不够贴"。

# 用 10 个阈值算一次 mAP50-95（单类别）
ths = [0.5 + 0.05 * i for i in range(10)]
print()
print("三、mAP50-95 的算法（这 10 个阈值）")
aps = [ap_at(t) for t in ths]
for t, a in zip(ths, aps):
    print(f"  IoU ≥ {t:.2f} : AP = {a:.4f}")
print("  平均 =", round(sum(aps) / len(aps), 4))


# ============================================================
# 七、三个常见误解
# ============================================================
#   ① "mAP 是分类准确率"
#      不是。它是"检测质量"，同时包含位置和类别。
#
#   ② "AP 是把不同阈值下的 precision 和 recall 简单平均"
#      不是。是按召回分段、用插值精度加权积分。
#
#   ③ "AP50 高就说明模型好"
#      AP50 只看"大概框住"，松得很。
#      看一个检测器的真实定位能力，要看 mAP50-95。


# ============================================================
# 八、这一课要记住的三句
# ============================================================
# 1. 检测没有"准确率"，只有 TP/FP/FN，和由此算出的 P/R。
#    没有 TN，因为"没有物体的地方"无从统计。
#
# 2. 阈值一变 P 和 R 都变，所以要看整条 PR 曲线，
#    曲线下面积就是 AP。
#
# 3. mAP50 宽松、mAP50-95 严格。
#    前者看"能不能框到"，后者看"框得准不准"。

