# G01：检测和分类到底差在哪
#
# 【这一课解决什么问题】
#   分类你已经会了：一张图 -> 一个类别。
#   检测：一张图里有几个物体、各是什么、在哪里。
#
#   听起来只是"多了几个框"，但正是这个"多"，把问题彻底改变了。
#   这一课讲清楚检测的三个根本困难——后面整个 G 阶段都在解它们。


# ============================================================
# 一、输出格式就不一样
# ============================================================
#   分类：固定输出 C 个数
#     一张图 -> [C] -> argmax -> 一个类别
#     不管图里有什么，输出形状永远是 [C]
#
#   检测：数量不固定
#     一张图可能有 0 个物体，也可能 50 个。
#     每个物体要 4 个坐标 + 1 个类别。
#     输出是 [N, 5] 或 [N, 4+C]，N 是变的。
#
# ★ 神经网络最喜欢"固定形状的输出"。
#   "数量不定"这件事，直接让 [B, C] 这种结构用不了。


# ============================================================
# 二、于是有了"密集预测"
# ============================================================
# 既然数量不定，就让网络在**每个位置**都猜一次：
#
#   把特征图看成一张网格，每个格子回答三个问题：
#     ① 这里有没有物体？（目标性）
#     ② 如果有，框多大、相对格子中心偏多少？（4 个坐标）
#     ③ 是什么类别？（C 个分数）
#
# 这样输出形状就固定了。

positions = 80 * 80 + 40 * 40 + 20 * 20
print("=" * 60)
print("一、640×640 的图，检测头输出多少个预测")
print("  80×80 尺度（步长 8） :", 80 * 80)
print("  40×40 尺度（步长 16）:", 40 * 40)
print("  20×20 尺度（步长 32）:", 20 * 20)
print("  合计位置数           :", positions)
print()
print("  每个位置输出 4 + 80 = 84 个数")
print("  所以输出张量是 [B, 84, ", positions, "]", sep="")

# 输出：
#   合计位置数: 8400
#   输出张量 [B, 84, 8400]
#
# ★ 这和 D08 里看到的 Detect 输出 (84, 8400) 完全对上。


# ============================================================
# 三、困难一：正负样本极度不平衡
# ============================================================
# 一张图里真正有物体的位置有多少？
#
#   COCO 平均每张图约 7 个物体。
#   就算每个物体占 10 个位置当正样本，也只有 70 个。
#   而总位置数是 8400。
#
#   正 : 负 ≈ 70 : 8330 ≈ 1 : 119
#
# ★ 如果按"每个位置分类对错"直接算损失，
#   模型会学会"全部猜背景"——准确率 99%，一个物体都检不出来。
#
#   这就是为什么检测的损失函数必须特殊设计：
#   要专门平衡正负样本、专门挑出"该学的那几十个位置"。
#   （G07 的标签分配就是在解决这个。）


# ============================================================
# 四、困难二：几千个预测，怎么和几个真实框对应
# ============================================================
#   模型输出 8400 个预测，真实标注可能只有 3 个框。
#   哪个预测该负责哪个真实框？
#
#   这叫"标签分配"（label assignment）。
#
#   最简单的想法："中心点落在框里就算正样本"。
#   但一个框可能覆盖几十个位置，全算正样本，
#   模型会学出一堆重复的框。
#
#   YOLO 的做法是算一个"对齐度"：
#     类别分数高 + 和真实框的 IoU 大 -> 才是好正样本
#   然后每个真实框只挑 TopK 个最优的预测来学。
#
# ★ 这是 YOLO 最核心的机制之一（G07 细讲）。
#   分配得好不好，直接决定模型能不能训起来。


# ============================================================
# 五、困难三：同一个物体会被预测很多次
# ============================================================
#   即使训练好了，推理时相邻的几个位置都会觉得"这物体归我"，
#   各自输出一个框 -> 一只猫被画了 7 个框。
#
#   解决办法是 NMS（非极大值抑制）：
#     按分数排序，保留最高的
#     把和它重合度太高的其它框删掉
#
# ★ NMS 是后处理，不在网络里。它自己也有代价：
#   类别多、框多的时候很慢。
#   YOLO26 的 end2end 模式就是想绕开 NMS。


# ============================================================
# 六、三个任务对比
# ============================================================
#   任务    输出              回答的问题
#   --------------------------------------------------
#   分类    [B, C]            这张图是什么
#   检测    [B, N, 4+C]       有什么、在哪、各几个
#   分割    [B, C, H, W]      每个像素属于什么
#
# ★ 只有检测的 N 是可变的，这才是它比分类难的根本原因。
#   分割输出形状固定，但每个像素都要分类，计算量大得多。


# ============================================================
# 七、G 阶段的路线
# ============================================================
#   G02  框怎么表示（xyxy / xywh / cxcywh / 归一化）
#   G03  标签文件与数据检查
#   G04  图片缩放后盒坐标怎么变（LetterBox 逆变换）
#   G05  IoU：两个框重合多少
#   G06  三尺度检测头，每个位置输出什么
#   G07  标签分配：哪个预测学哪个真实框
#   G08  分数阈值、TopK、NMS
#   G09  Precision / Recall / AP / mAP
#   G10  一个简化单目标检测，把上面全串一遍


