# G05：IoU——衡量两个框有多重合
#
# 【这一课解决什么问题】
#   检测训练的核心问题是"这个预测框和答案有多接近"。
#   用坐标差吗？不行 —— 差 1 像素在小框上是灾难，在大框上无所谓。
#
#   需要一个"相对"的度量。这就是 IoU。


# ============================================================
# 一、定义：交集比并集
# ============================================================
#   IoU = 两个框重叠的面积 / 两个框合起来占的面积
#
#       完全重合  -> 1
#       完全不相交 -> 0
#
# 计算只需要三步：
#   ① 交集矩形的左上角 = 两个框左上角的 max
#   ② 交集矩形的右下角 = 两个框右下角的 min
#   ③ IoU = 交集面积 / (A面积 + B面积 - 交集面积)
#
# ★ 第 ③ 步减去交集，是因为交集被算了两次。


# ============================================================
# 二、手算一遍
# ============================================================
#   A = [0, 0, 2, 2]     边长 2，面积 4
#   B = [1, 1, 3, 3]     边长 2，面积 4
#
#   交集：左上 (max(0,1), max(0,1)) = (1,1)
#         右下 (min(2,3), min(2,3)) = (2,2)
#         边长 1，面积 1
#
#   并集 = 4 + 4 - 1 = 7
#
#   IoU = 1 / 7 ≈ 0.1429


def iou(a, b):
    ax1, ay1, ax2, ay2 = a
    bx1, by1, bx2, by2 = b
    ix1, iy1 = max(ax1, bx1), max(ay1, by1)
    ix2, iy2 = min(ax2, bx2), min(ay2, by2)
    iw = max(0.0, ix2 - ix1)          # 不相交时宽度为负，取 0
    ih = max(0.0, iy2 - iy1)
    inter = iw * ih
    area_a = max(0.0, ax2 - ax1) * max(0.0, ay2 - ay1)
    area_b = max(0.0, bx2 - bx1) * max(0.0, by2 - by1)
    union = area_a + area_b - inter
    return inter / union if union > 0 else 0.0


print("=" * 60)
print("一、手算验证")
v = iou([0, 0, 2, 2], [1, 1, 3, 3])
print(f"  [0,0,2,2] vs [1,1,3,3] -> IoU = {v:.4f}")
print(f"  1/7 = {1/7:.4f}")


# ============================================================
# 三、为什么不用坐标差
# ============================================================
# 同样是"偏了 1 像素"，IoU 完全不同：

print()
print("=" * 60)
print("二、同样偏 1 像素")
for name, a, b in [("小框 10×10 ", [0, 0, 10, 10], [1, 0, 11, 10]),
                   ("大框 100×100", [0, 0, 100, 100], [1, 0, 101, 100])]:
    print(f"  {name}: IoU = {iou(a, b):.4f}")

# 输出：
#   小框 10×10 : IoU = 0.8182
#   大框 100×100: IoU = 0.9802
#
# ★ 坐标差都是 1 像素，但 IoU 一个是 0.82，一个是 0.98。
#   小框偏 1 像素，重叠度就掉到八成；
#   大框偏 1 像素，几乎没影响。
#
#   这正是我们想要的："偏得严不严重"是相对的。
#   用绝对坐标差训练，模型会顾此失彼。


# ============================================================
# 四、IoU 的盲区：不相交时全是 0
# ============================================================
#   两个框完全不相交，IoU = 0。
#   但"离得 2 像素"和"离得 200 像素"，IoU 都是 0。
#
# ★ 对训练来说这是致命的：
#   模型预测的框如果在真实框外面，梯度是 0 —— 它不知道该往哪边挪。
#
# 于是有了一系列改进版。


# ============================================================
# 五、GIoU / DIoU / CIoU：补上 IoU 的盲区
# ============================================================
#   ① GIoU（Generalized IoU）
#      算出两个框的"最小外接矩形" C
#      GIoU = IoU - (C面积 - 并集面积) / C面积
#
#      不相交时 IoU=0，但 C 越大，"浪费的空间"越多，GIoU 越负。
#      于是"离得近"和"离得远"就能区分了。
#
#   ② DIoU（Distance IoU）
#      直接加一个中心点距离惩罚：
#      DIoU = IoU - (中心距离²) / (外接框对角线²)
#      比 GIoU 收敛更快，因为它直接优化"中心对齐"。
#
#   ③ CIoU（Complete IoU）
#      在 DIoU 基础上再加长宽比惩罚：
#      CIoU = DIoU - α × (长宽比差异)
#      同时管住中心对齐、大小、形状三件事。


def giou(a, b):
    ax1, ay1, ax2, ay2 = a
    bx1, by1, bx2, by2 = b
    ix1, iy1 = max(ax1, bx1), max(ay1, by1)
    ix2, iy2 = min(ax2, bx2), min(ay2, by2)
    inter = max(0.0, ix2 - ix1) * max(0.0, iy2 - iy1)
    area_a = (ax2 - ax1) * (ay2 - ay1)
    area_b = (bx2 - bx1) * (by2 - by1)
    union = area_a + area_b - inter
    i = inter / union if union > 0 else 0.0

    # 最小外接矩形
    cx1, cy1 = min(ax1, bx1), min(ay1, by1)
    cx2, cy2 = max(ax2, bx2), max(ay2, by2)
    c_area = (cx2 - cx1) * (cy2 - cy1)
    return i - (c_area - union) / c_area if c_area > 0 else i


print()
print("=" * 60)
print("三、不相交时，GIoU 能区分远近")
for name, a, b in [("离 2 像素 ", [0, 0, 10, 10], [12, 0, 22, 10]),
                   ("离 200 像素", [0, 0, 10, 10], [200, 200, 210, 210])]:
    print(f"  {name}: IoU = {iou(a, b):.4f}   GIoU = {giou(a, b):.4f}")

# 输出：
#   离 2 像素  : IoU = 0.0000   GIoU = -0.0909
#   离 200 像素: IoU = 0.0000   GIoU = -0.9955
#
# ★ IoU 都是 0，但 GIoU 从 -0.09 到 -1.0，
#   梯度能告诉模型"往那边挪"。
#
#   这就是为什么现代检测器都用 GIoU/DIoU/CIoU 当损失，
#   而不是直接用 IoU。


# ============================================================
# 六、IoU 在检测里的四处用途
# ============================================================
#   ① 判断预测和真实框"够不够近"（正样本分配，G07）
#   ② NMS：删掉和已保留框重合度太高的（G08）
#   ③ 评价：预测框和真实框 IoU 超过阈值才算"检对了"（G09）
#   ④ 训练损失：框回归的损失函数（CIoU）
#
# ★ 一个数值，贯穿训练、推理、评价三个阶段。
#   这也是为什么这一课要放在这么前面。


# ============================================================
# 七、两个边界情况
# ============================================================
#   ① 零面积框
#      宽或高为 0 -> 并集为 0 -> 除零。
#      代码里要判断 union > 0，否则会得到 nan。
#
#   ② 完全包含
#      小框完全在大框内：
#        [0,0,100,100] 和 [40,40,60,60]
#        交集 400，并集 10000，IoU = 0.04
#      但小框其实"完全在里面"。
#      IoU 对这种"包含关系"不敏感 —— 这也是 GIoU 等改进的动机之一。
#
#      实测：IoU = 0.0400


# ============================================================
# 八、这一课要记住的三句
# ============================================================
# 1. IoU = 交集 / 并集，范围 0~1。
#    [0,0,2,2] 和 [1,1,3,3] 的 IoU 是 1/7。
#
# 2. IoU 是相对度量：同样偏 1 像素，小框掉到 0.82，大框还有 0.98。
#    这就是不用绝对坐标差的原因。
#
# 3. IoU 在不相交时恒为 0，没有梯度。
#    GIoU/DIoU/CIoU 补上了"距离"和"形状"的信息。

