# G10：把检测的整条链走一遍
#
# 【这一课做什么】
#   前面 9 课分别讲了框的表示、缩放、IoU、检测头、分配、NMS、mAP。
#   这一课用一组具体数字，把它们串成一条完整的线：
#
#     图里有 2 个目标 -> 模型给出 4 个预测 -> 筛选 -> 判对错 -> 算 AP
#
#   不训练模型，只是"把后处理走一遍"，看每一步的输出。


# ============================================================
# 一、场景设定
# ============================================================
# 真实标注（GT）：
#   猫  [100, 100, 300, 400]
#   狗  [400,  50, 600, 300]
#
# 模型给出的预测（已经过 sigmoid，按分数排序前先不排）：
#   P1  猫  [105,  98, 298, 405]  分数 0.90     <- 框得很准
#   P2  猫  [110, 100, 300, 400]  分数 0.70     <- 和 P1 几乎一样（重复）
#   P3  狗  [410,  45, 595, 310]  分数 0.80
#   P4  猫  [ 50,  50,  90,  90]  分数 0.30     <- 图里那个位置没东西


def iou(a, b):
    ax1, ay1, ax2, ay2 = a[:4]
    bx1, by1, bx2, by2 = b[:4]
    iw = max(0, min(ax2, bx2) - max(ax1, bx1))
    ih = max(0, min(ay2, by2) - max(ay1, by1))
    inter = iw * ih
    union = (ax2 - ax1) * (ay2 - ay1) + (bx2 - bx1) * (by2 - by1) - inter
    return inter / union if union else 0


GT = [("cat", [100, 100, 300, 400]),
      ("dog", [400, 50, 600, 300])]

PRED = [("cat", [105, 98, 298, 405], 0.90),
        ("cat", [110, 100, 300, 400], 0.70),
        ("dog", [410, 45, 595, 310], 0.80),
        ("cat", [50, 50, 90, 90], 0.30)]


# ============================================================
# 二、第一步：算 IoU（G05）
# ============================================================
print("=" * 62)
print("一、每个预测最匹配哪个 GT，IoU 多少")
for i, (c, box, s) in enumerate(PRED):
    best, bi = 0.0, -1
    for j, (gc, gb) in enumerate(GT):
        if gc != c:                      # 只和同类 GT 比
            continue
        v = iou(box, gb)
        if v > best:
            best, bi = v, j
    print(f"  P{i + 1} {c} 分数{s}  ->  最匹配 GT{bi}  IoU={best:.3f}")

# 输出：
#   P1 cat 分数0.9  ->  最匹配 GT0  IoU=0.944
#   P2 cat 分数0.7  ->  最匹配 GT0  IoU=0.950   <- 和 P1 抢同一个 GT
#   P3 dog 分数0.8  ->  最匹配 GT1  IoU=0.876
#   P4 cat 分数0.3  ->  最匹配 GT-1 IoU=0.000   <- 没有同类 GT 可匹配


# ============================================================
# 三、第二步：分数阈值 + NMS（G08）
# ============================================================
print()
print("=" * 62)
print("二、阈值 0.25，按类别 NMS（IoU 阈值 0.45）")
order = sorted(range(len(PRED)), key=lambda i: -PRED[i][2])   # 按分数降序
kept = []
for i in order:
    c, box, s = PRED[i]
    if s < 0.25:
        print(f"  P{i + 1} 分数 {s} < 0.25 -> 丢弃")
        continue
    dup = [k for k in kept if PRED[k][0] == c and iou(box, PRED[k][1]) > 0.45]
    if dup:
        print(f"  P{i + 1} 分数 {s} 与 P{dup[0] + 1} 重叠 -> NMS 丢弃")
    else:
        kept.append(i)
        print(f"  P{i + 1} 分数 {s} -> 保留")

# 输出：
#   P1 分数 0.9 -> 保留
#   P3 分数 0.8 -> 保留
#   P2 分数 0.7 与 P1 重叠 -> NMS 丢弃
#   P4 分数 0.3 -> 保留
#
# ★ 注意 P2：它其实比 P1 更贴合 GT（0.950 > 0.944），
#   但分数更低，所以被 NMS 删掉了。
#   NMS 只认分数，不认 IoU 谁更好 —— 这是它的设计，不是 bug。


# ============================================================
# 四、第三步：判 TP / FP（G09）
# ============================================================
print()
print("=" * 62)
print("三、逐个判 TP/FP，累积 P/R")
used = set()
tp = fp = 0
rows = []
for i in kept:
    c, box, s = PRED[i]
    hit = -1
    for j, (gc, gb) in enumerate(GT):
        if gc == c and j not in used and iou(box, gb) >= 0.5:
            hit = j
            break
    if hit >= 0:
        used.add(hit)
        tp += 1
        tag = "TP"
    else:
        fp += 1
        tag = "FP"
    rows.append((f"P{i + 1}", tag, tp / (tp + fp), tp / len(GT)))

print(f"{'预测':>4} {'判定':>4} {'Precision':>10} {'Recall':>8}")
for name, tag, p, r in rows:
    print(f"{name:>4} {tag:>4} {p:>10.3f} {r:>8.3f}")

# 输出：
#   预测  判定  Precision   Recall
#   P1    TP       1.000    0.500
#   P3    TP       1.000    1.000
#   P4    FP       0.667    1.000
#
# ★ P4 是误检（那个位置没东西），它让精度从 1.000 掉到 0.667。
#   但召回已经是 1.000 了（两个 GT 都找到了）。


# ============================================================
# 五、第四步：算 AP
# ============================================================
ap = 0.0
prev_r = 0.0
for _, _, p, r in rows:
    if r > prev_r:
        ap += (r - prev_r) * p
        prev_r = r

print()
print("=" * 62)
print("四、AP@0.5 =", round(ap, 4))

# 输出：AP@0.5 = 1.0
#
# ★ 奇怪吗？明明有一个误检，AP 还是 1.0。
#
#   因为那个误检排在**最后**：
#     走到 P4 时，召回已经是 1.0 了
#     AP 只在"召回增加"的时候加分
#     P4 没有让召回增加 -> 不加分
#
#   ★ 这就是 AP 的一个特性：
#     **排在所有正确检测之后的误检，不影响 AP。**
#     所以模型可以"多报一些候选"而几乎不损失 AP ——
#     这也是为什么推理时阈值可以设得比较低。
#
#   反过来，如果 P4 排在 P1 前面（分数更高），
#   它就会把前面几段的精度拉低，AP 会明显下降。
#   试试把 P4 的分数改成 0.95，AP 会掉到 0.5 左右。


# ============================================================
# 六、整条链回顾
# ============================================================
#   训练阶段：
#     ① 输入 640×640 -> 特征图 -> 8400 个位置（G01/G06）
#     ② 每个位置输出 84 个数（4 个距离 + 80 个类别）
#     ③ 标签分配：选出几十个正样本（G07）
#     ④ 分类损失（软标签 BCE）+ 框损失（CIoU，只对正样本）
#     ⑤ 反向传播、更新参数（A/B 阶段）
#
#   推理阶段：
#     ⑥ 前向得到 8400 个预测
#     ⑦ sigmoid 类别分数、距离转框（G02/G06）
#     ⑧ 分数阈值 -> NMS -> TopK（G08）
#     ⑨ 坐标逆变换，回到原图（G04）
#     ⑩ 评价：IoU 判 TP/FP -> P/R -> AP/mAP（G05/G09）
#
# ★ G 阶段的所有课，都挂在这条链的某一环上。


# ============================================================
# 七、这一课要记住的三句
# ============================================================
# 1. 后处理的顺序是固定的：
#    分数阈值 -> NMS -> TopK -> 坐标逆变换。
#
# 2. NMS 只认分数，不认谁的框更准。
#    分数低的那个即使框更好，也会被删掉。
#
# 3. AP 只对"增加召回"的预测加分，
#    排在最后的误检不影响 AP —— 这就是推理阈值可以设低的原因。

