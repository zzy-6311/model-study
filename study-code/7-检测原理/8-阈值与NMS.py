# G08：分数阈值、TopK、NMS
#
# 【这一课解决什么问题】
#   推理时模型给出 8400 个预测，其中几十个"有希望的"。
#   但同一个物体会被相邻的多个位置都预测到 —— 一只猫被画了 5 个框。
#
#   这一课讲三个后处理操作：它们常被混为一谈，实际做的是三件不同的事。


# ============================================================
# 一、三个操作，三件事
# ============================================================
#   ① 分数阈值   低于阈值的全丢          -> 去掉"没信心"的
#   ② TopK       只留分数最高的 K 个      -> 控制数量上限
#   ③ NMS        删掉互相重叠的          -> 去掉"重复"的
#
#   ★ 顺序很重要：先阈值（快速筛掉大部分），再 NMS，
#     最后（可选）TopK 控制最终输出数量。


# ============================================================
# 二、NMS 在做什么
# ============================================================
#   核心思想：同一个物体，只保留分数最高的那个框。
#
#   步骤：
#     1. 所有框按分数从高到低排序
#     2. 取第一个（最高分），保留
#     3. 把所有和它 IoU 超过阈值的框删掉
#     4. 回到第 2 步，直到没有框剩下
#
#   就这么简单。它的前提假设是：
#     "两个 IoU 很高的框，说的是同一个物体。"


def iou(a, b):
    ax1, ay1, ax2, ay2 = a[:4]
    bx1, by1, bx2, by2 = b[:4]
    iw = max(0, min(ax2, bx2) - max(ax1, bx1))
    ih = max(0, min(ay2, by2) - max(ay1, by1))
    inter = iw * ih
    union = (ax2 - ax1) * (ay2 - ay1) + (bx2 - bx1) * (by2 - by1) - inter
    return inter / union if union else 0


boxes = [
    ("A", [0, 0, 100, 100], 0.90),
    ("B", [5, 5, 105, 105], 0.80),      # 和 A 几乎重叠
    ("C", [200, 200, 300, 300], 0.70),  # 另一个物体
    ("D", [0, 0, 100, 100], 0.60),      # 和 A 完全相同
    ("E", [100, 100, 200, 200], 0.50),  # 只在角上碰到 A
]

print("=" * 62)
print("一、五个框（同一类别）")
for name, box, score in boxes:
    print(f"  {name}: 框{box}  分数{score}")

print()
print("关键 IoU：")
print(f"  A-B: {iou(boxes[0][1], boxes[1][1]):.3f}")
print(f"  A-D: {iou(boxes[0][1], boxes[3][1]):.3f}")
print(f"  A-E: {iou(boxes[0][1], boxes[4][1]):.3f}")

print()
print("二、NMS 过程（IoU 阈值 0.45）")
order = sorted(boxes, key=lambda t: -t[2])
kept = []
for name, box, score in order:
    if any(iou(box, kb) > 0.45 for kb in kept):
        print(f"  取 {name}（{score}）-> 和已保留框重叠超过 0.45，删掉")
    else:
        kept.append(box)
        print(f"  取 {name}（{score}）-> 保留")

print()
print(f"最终保留 {len(kept)} 个框")

# 输出：
#   A-B: 0.822   （偏移 5 像素，还很高）
#   A-D: 1.000   （完全相同）
#   A-E: 0.000   （只在角上接触，IoU 为 0）
#
#   NMS:
#     取 A(0.9) -> 保留
#     取 B(0.8) -> 和 A 重叠 0.822，删掉
#     取 C(0.7) -> 保留
#     取 D(0.6) -> 和 A 重叠 1.0，删掉
#     取 E(0.5) -> 保留
#   最终 3 个框：A、C、E
#
# ★ 注意 E：它和 A 只在角上碰到，IoU=0，所以被保留。
#   这是 NMS 的一个已知局限——"相邻但不同物体"的框不会被误删，
#   但"真正重叠的两个物体"也会有一个被删掉。


# ============================================================
# 三、三个参数的直观影响
# ============================================================
#   分数阈值 0.25 -> 低：召回高（不漏检），但误检多
#   分数阈值 0.50 -> 高：误检少，但漏检多
#
#   IoU 阈值 0.45 -> 低：删得狠，重叠的物体只留一个
#   IoU 阈值 0.70 -> 高：删得少，重复框可能留下来
#
#   TopK 300      最多输出 300 个框（防止极端情况输出上千个）


# ============================================================
# 四、按类别 NMS vs 类别无关
# ============================================================
#   按类别 NMS（默认）：
#     只在"同一类别"的框之间比 IoU
#     -> "人"和"自行车"即使重叠，都保留
#
#   类别无关 NMS：
#     所有类别的框放在一起比
#     -> 重叠的人和自行车只留一个
#
#   ★ 什么时候用类别无关？
#     目标通常互斥时（一个位置不可能既是人又是自行车）。
#     用错的话，挨在一起的两个不同物体只报出一个。


# ============================================================
# 五、NMS 的代价
# ============================================================
#   框越多越慢：
#     朴素实现是 O(n²)（两两比 IoU）
#     实际会用排序 + 提前终止做优化
#
#   影响 NMS 耗时的因素：
#     分数阈值调低 -> 进 NMS 的框变多 -> 变慢
#     类别数多 -> 每类各做一遍 NMS
#     高分辨率 -> 位置数多
#
#   ★ 这也是为什么 YOLO26 要搞 end2end（下一节）。


# ============================================================
# 六、YOLO26 的 end2end：绕过 NMS
# ============================================================
#   训练时同时训练两个分支（G07 提过）：
#     one-to-many：一个 GT 带 10 个正样本 -> 学得充分
#     one-to-one ：一个 GT 只带 1 个正样本 -> 输出天然不重复
#
#   推理时只用 one-to-one 分支：
#     因为每个 GT 只有一个位置负责，所以不会出现"一个物体多个框"
#     -> 不需要 NMS
#
#   ★ 要注意的两点（本地实现的事实，来自 D08 的版本表）：
#     ① 即使调用的函数名叫 non_max_suppression，
#        end2end 分支里可能只是做"分数筛选 + TopK"，没有真正的抑制
#     ② 训练时 one-to-one 分支的输入是 detach 过的，
#        它的梯度不会传回 backbone
#
#   ★ 所以"YOLO 一定用 NMS"这句话是错的。
#     要看当前配置和运行模式。


# ============================================================
# 七、完整的后处理顺序
# ============================================================
#   ① 模型输出 [B, 84, 8400]（logits + 距离）
#   ② sigmoid 类别分数（G06）
#   ③ 距离 -> xyxy（dist2bbox）
#   ④ 分数阈值过滤           0.25
#   ⑤ NMS（如果不是 end2end） IoU 0.45
#   ⑥ TopK 限制              300
#   ⑦ 坐标逆变换            减 padding、除以缩放比（G04）
#   ⑧ 输出 [N, 6]：x1,y1,x2,y2,score,class


# ============================================================
# 八、这一课要记住的三句
# ============================================================
# 1. 阈值、TopK、NMS 是三件事：去没信心、限数量、去重复。
#
# 2. NMS 的思想很简单：同一物体只留最高分，
#    和它 IoU 超阈值的全删。代价是框多时慢。
#
# 3. YOLO26 的 end2end 分支输出天然不重复，可以不要 NMS。
#    但"函数名叫 NMS"不代表它真的在做抑制，要看实际分支。

