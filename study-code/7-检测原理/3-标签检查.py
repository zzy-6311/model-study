# G03：标签文件，以及怎么检查它
#
# 【这一课解决什么问题】
#   检测训练不收敛，有一半的概率是标签错了。
#   而标签错了，模型不会报错，只会"学不会"。
#
#   这一课讲清楚 YOLO 标签的格式，以及一个能自动抓错的检查器。


# ============================================================
# 一、YOLO 标签长什么样
# ============================================================
# 每张图片配一个同名的 .txt 文件：
#
#   images/train/IMG_001.jpg   ->   labels/train/IMG_001.txt
#
# .txt 里每一行是一个物体，五个数，空格分隔：
#
#   类别编号  cx  cy  w  h
#
# 三个要点：
#   ① 都是归一化的（除以图宽/图高），范围 0~1
#   ② cx cy 是**中心点**，不是左上角
#   ③ 类别从 0 开始（0, 1, 2...）
#
# 一个例子（图 640×480，一个框 x1=160,y1=120,x2=320,y2=240，类别 3）：
#
#   3 0.375000 0.375000 0.250000 0.250000
#
# 这正是 G02 算出来的那组数。


# ============================================================
# 二、空标签是合法的
# ============================================================
# 一个 .txt 文件里什么都没有（0 字节），意思是：
#   "这张图里没有任何目标。"
#
# ★ 这不是"标签缺失"，这是有效信息。
#   检测模型必须学会"这里什么都没有"——如果训练集里
#   全都是含有目标的图，模型会倾向于到处都画框。
#
#   真实数据集里通常有相当比例的"背景图"（不含目标），
#   故意保留它们是有意义的。
#
# ★ 反过来说：一个 0 字节的 .txt，和"文件不存在"是两件事。
#   前者是"确认没有目标"，后者是"可能忘了标注"。


# ============================================================
# 三、五种最常见的标签错误
# ============================================================
#   ① 用像素坐标写进了归一化格式
#      行里出现 "160 120 320 240" 这种几百的数
#      -> 训练时这些值会被当成"超出图像 100 倍"，框全在画外
#
#   ② 用了 xyxy 而不是 cxcywh
#      数值都在 0~1 范围内，看起来没问题，但含义全错
#      -> 框的位置和大小都会诡异
#
#   ③ 类别号从 1 开始
#      YOLO 从 0 开始。如果数据是从别的格式转过来的，
#      可能出现 "10" 这种类别号，而你的 nc 只有 10（合法范围 0~9）
#
#   ④ 图片和标签错位
#      文件名对不上、或者顺序对不上
#      -> 模型学到的是"这张图对应那个框"，全乱
#
#   ⑤ 宽高是 0 或负数
#      标注时点了两下同一个点，或者 x2<x1
#
# ★ 这五种都不会让程序崩，只会让训练"莫名其妙不收敛"。


# ============================================================
# 四、写一个检查器，让它自动抓错
# ============================================================

import os
import tempfile

root = os.path.join(tempfile.gettempdir(), "g03_demo")
os.makedirs(root, exist_ok=True)

# 造几个"有病"的标签文件
samples = {
    "good.txt": "3 0.375 0.375 0.250 0.250",
    "pixels.txt": "3 160 120 160 120",            # 用了像素值
    "bad_class.txt": "10 0.5 0.5 0.1 0.1",        # 类别 10，但 nc=10
    "zero_size.txt": "1 0.5 0.5 0.0 0.2",         # 宽为 0
    "out_of_range.txt": "1 1.4 0.5 0.2 0.2",      # cx > 1
    "empty.txt": "",                               # 空：合法
}
for name, content in samples.items():
    with open(os.path.join(root, name), "w", encoding="utf-8") as f:
        f.write(content + ("\n" if content else ""))

NC = 10          # 类别数


def check_label(path, nc):
    problems = []
    with open(path, encoding="utf-8") as f:
        lines = [ln.strip() for ln in f if ln.strip()]
    if not lines:
        return ["（空标签，合法：表示这张图没有目标）"]

    for i, line in enumerate(lines, 1):
        parts = line.split()
        if len(parts) != 5:
            problems.append(f"第 {i} 行有 {len(parts)} 个数，应该是 5 个")
            continue
        cls, cx, cy, w, h = parts[0], *map(float, parts[1:])
        cls = int(float(cls))
        if not (0 <= cls < nc):
            problems.append(f"第 {i} 行类别 {cls} 超出范围 [0, {nc - 1}]")
        if not (0 <= cx <= 1 and 0 <= cy <= 1):
            problems.append(f"第 {i} 行中心点 ({cx}, {cy}) 超出 0~1")
        if not (0 < w <= 1 and 0 < h <= 1):
            problems.append(f"第 {i} 行宽高 ({w}, {h}) 不合法")
        if max(cx, cy, w, h) > 5:
            problems.append(f"第 {i} 行数值像像素坐标，不像归一化")
    return problems


print("=" * 60)
print("一、检查结果")
for name in samples:
    result = check_label(os.path.join(root, name), NC)
    print(f"  {name:<18}", result if result else "OK")


# ============================================================
# 五、检查器的输出说明
# ============================================================
# 一个合格的检查器至少要做这几件事：
#
#   ① 每个标签文件都能对应到一张图片，反之亦然
#   ② 类别号在 [0, nc-1] 内
#   ③ 坐标在合理范围（0~1，允许略微超出，但不能 100 倍）
#   ④ 宽高 > 0
#   ⑤ 每行 5 个数
#   ⑥ 统计每个类别的框数量，看有没有哪类特别少
#   ⑦ 统计框的尺寸分布，看有没有异常的大框/小框
#
# ★ 第 ⑥ ⑦ 条特别有用：
#   某个类别只有 2 个框 -> 训练出来必然很差，不是模型的问题
#   出现 90% 面积的巨框 -> 多半是标注时把整张图框起来了


# ============================================================
# 六、为什么"看一眼"不够
# ============================================================
#   人的眼睛能发现"框画错了"，但发现不了：
#     - 数值单位不对（0.375 和 160 看起来都"像个坐标"）
#     - 类别号从 1 开始（差 1，很难察觉）
#     - 某一行多了个空格导致解析错位
#
#   ★ 所以必须用代码检查，而且要**在训练之前**查。
#     训练 8 小时之后才发现标签错，是检测项目里最常见的浪费。


# ============================================================
# 七、这一课要记住的三句
# ============================================================
# 1. YOLO 标签每行 5 个数：类别 cx cy w h，全部归一化，类别从 0 开始。
#
# 2. 空的 .txt 是合法且重要的（表示"这张图没有目标"），
#    不要删掉它。
#
# 3. 标签错误不会让训练报错，只会让它"学不会"。
#    训练前必须跑一个自动检查器。

